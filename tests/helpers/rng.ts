/**
 * Генераторы псевдослучайных чисел для тестов на случайных сценариях: одно зерно — одна
 * и та же лента на любой машине, красный прогон воспроизводится по зерну.
 *
 * ⚠️ Последовательности закреплены: от них зависят сгенерированные сценарии в тестах, и смена
 * хоть одной константы молча подменит проверяемые случаи. Нужен другой генератор — добавь
 * новый, а не правь существующий.
 *
 * Все три возвращают функцию без аргументов, которая отдаёт число из `[0, 1)`
 * (у `minstd` — из `(0, 1)`). Зерно — целое.
 */

/** Park–Miller (minstd): `s = s · 48271 mod (2³¹ − 1)`. Зерно — от 1 до 2³¹ − 2. */
export function minstd(seed: number): () => number {
  let s = seed;
  return () => (s = (s * 48271) % 2147483647) / 2147483647;
}

/** mulberry32: 32 бита состояния, хорошо перемешанные младшие биты. */
export function mulberry32(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let x = s;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Линейный конгруэнтный с константами ANSI C `rand`: `s = (s · 1103515245 + 12345) mod 2³¹`.
 *
 * ⚠️ Произведение считается в double и при больших `s` теряет младшие биты — это не настоящий
 * `rand` из C. Так и оставлено: ленты тестов, которые на нём построены, держатся за именно эту
 * последовательность.
 */
export function ansiLcg(seed: number): () => number {
  let s = seed;
  return () => {
    s = (s * 1103515245 + 12345) % 2147483648;
    return s / 2147483648;
  };
}
