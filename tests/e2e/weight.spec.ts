import { existsSync, readFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { expect, test } from '@playwright/test';
import { PAGES } from './pages';

/**
 * Бюджет клиентского кода по страницам.
 *
 * В курсе появился второй рантайм: уроку про ре-рендеринг нужен настоящий React, иначе это
 * рассказ о React, а не разбор. Плата честная — страница такого урока весит больше двухсот
 * килобайт скрипта против тринадцати у уроков про движок.
 *
 * Опасность не в самой цене, а в её расползании: один импорт из общего слоя, сделанный
 * по привычке, — и React уезжает на страницы, где он не нужен вовсе. Заметить это на глаз
 * нельзя: страница выглядит так же и работает так же, просто грузится дольше. Поэтому здесь
 * порог, а не пожелание.
 *
 * Считается вес несжатых файлов: цифра стабильная и не зависит от настроек сервера, а ловим
 * мы не проценты, а разницу в разы.
 *
 * ⚠️ **Считается весь граф, а не только то, что названо в HTML** (2026-10-01). До этого тест
 * складывал файлы `/_astro/*.js`, упомянутые в разметке, — а рантайм фреймворка тянут сами
 * чанки своими `import`. У `/frameworks/react-vs-vue/` тест видел 16 КБ, браузер качал 345,
 * из них 203 — React DOM; у любой «лёгкой» темы — 7–50 КБ вместо настоящих 130–165 (рантайм
 * Vue). То есть проверка «React не утёк» не могла сработать никогда. Нашёл это стенд темы
 * «Острова и resumability». Теперь вес — замыкание по статическим импортам, а утечка React
 * ловится отдельной проверкой по признаку рантайма, а не порогом веса.
 */
const DIST = new URL('../../dist/', import.meta.url);

/**
 * Темы, где второй рантайм — предмет разговора, и потому его вес оправдан.
 *
 * ⚠️ Список поимённый, и это важнее, чем кажется. Раньше здесь стоял префикс `/render/`,
 * то есть бюджет в 320 КБ выдавался всему направлению — включая страницы, которые весят
 * 14–38 КБ. Ровно та беда, от которой этот тест и защищает, проходила бы молча: занеси
 * кто-нибудь React в общий слой, `/render/render-pipeline/` вырос бы с 14 КБ до двухсот,
 * а тест остался бы зелёным. Порог обязан относиться к теме, а не к участку адреса.
 */
const HEAVY_PAGES = new Set(['/frameworks/react-rerender/', '/frameworks/react-vs-vue/']);
const HEAVY_BUDGET_KB = 400;

/**
 * Страницы, где интерактив — предмет темы, а не украшение.
 *
 * Третья категория появилась не для того, чтобы «позеленело»: `/js/object-model/` осознанно
 * стала самой интерактивной темой курса — двенадцать островов вместо шести, потому что таблицы
 * о поведении языка там больше не набраны руками, а вычисляются у читателя (замки, перечисление,
 * порядок ключей, `instanceof`, протокол итерации, песочница; демо prototype pollution
 * 2026-10-03 переехало в «Безопасность бэкенда»).
 * `/kit/` — витрина, куда по правилу проекта обязан попасть каждый новый общий приём.
 *
 * ⚠️ Проверено перед тем, как трогать порог: 81 КБ у темы и 70 КБ у витрины — это **Vue-острова**,
 * ни одного React-модуля в их графе нет. То есть сценарий, от которого защищает этот тест
 * (второй рантайм расползся по страницам, где он не нужен), здесь не наступил. Иначе правильным
 * ответом была бы не правка порога, а удаление лишнего импорта.
 *
 * Общий порог при этом **не поднят**: 60 КБ остаются для всех остальных тридцати с лишним
 * страниц. Ослабить сторож разом для всех — ровно та ошибка, которую этот файл уже однажды
 * исправлял, заменив бюджет «по участку адреса» на поимённый список.
 *
 * 100 КБ — запас над нынешними 81, но не бесконечный: если тема перевалит и его, это повод
 * разобраться, что там выросло, а не подвинуть число ещё раз.
 */
const INTERACTIVE_PAGES = new Set(['/js/object-model/', '/js/event-loop/']);
const INTERACTIVE_BUDGET_KB = 230;

/**
 * Витрина — отдельный случай, и мерить её порогом темы неправильно.
 *
 * `/kit/` собирает токены и общие компоненты: каждый новый общий приём обязан туда попасть
 * по правилу проекта. Значит её вес растёт при любом пополнении набора, и сравнивать его
 * с весом одного урока бессмысленно — в курс она не входит и читателю по маршруту не попадается.
 *
 * ⚠️ **Порог сработал так, как задумано, и это стоит прочесть целиком.** Здесь стояло
 * предупреждение: «было 130 КБ, стало 188, до порога двенадцать — ещё один стенд витрина
 * примет, а два уже нет; правильный ответ тогда не поднять число, а разделить витрину».
 * Через несколько часов добавились ещё три стенда, страница выросла до **233** и упёрлась.
 * Витрину разделили: токены и компоненты остались на `/kit/` (**16 КБ**), шестнадцать
 * вычисляющих демо уехали на `/kit/labs/` (**218 КБ**). Порог не двигали — ради этого
 * разговора он и стоял.
 */
const SHOWCASE_PAGES = new Set(['/kit/']);
const SHOWCASE_BUDGET_KB = 200;

/**
 * Галерея вычисляющих демо — своя категория, потому что её вес это и есть её содержание.
 *
 * `/kit/labs/` существует ровно затем, чтобы держать все лаборатории разом: шестнадцать
 * островов по 8–27 КБ. Делить её дальше значило бы дробить галерею ради числа — три группы
 * внутри страницы (семантика, очереди, память) уже дают естественное деление по смыслу.
 *
 * ⚠️ Условие, без которого порог трогать нельзя, проверено: **React на странице нет ни байта**.
 * И проверено не подстрокой — подстрока здесь врёт трижды подряд. Поиск `/react/i` ловит
 * `reactive` из системы реактивности Vue; поиск `createElement(` ловит обычный
 * `document.createElement(`. Верный ответ даёт только граф импортов: чанки тянут
 * `runtime-core.esm-bundler` и общие кирпичи, и ни один не подтягивает React-чанк.
 * То есть сценарий, от которого защищает этот тест — второй рантайм уехал туда, где не нужен, —
 * здесь не наступил, и 218 КБ это честная цена шестнадцати демо.
 *
 * Запас до 260 оставлен небольшой намеренно: его хватит на два-три новых стенда, а дальше
 * разговор повторится — и тогда правильным ответом снова будет деление, а не правка числа.
 *
 * Для сравнения — темы, куда те же стенды встали: 37, 35, 22 и 19 КБ при общем пороге 60.
 * Вычисляющее демо само по себе почти ничего не весит: его логика — чистые функции, а тяжелеет
 * страница от числа островов, а не от того, что они считают.
 */
const LABS_PAGES = new Set(['/kit/labs/']);
const LABS_BUDGET_KB = 360;

/**
 * Всё остальное: страницы обязаны остаться такими же лёгкими, какими были.
 *
 * Пороги выше пересчитаны 2026-10-01 под настоящий вес графа (см. шапку): обычная тема
 * 125–165 КБ, из них ~120 — общий рантайм Vue; `object-model` 192, `event-loop` 165,
 * витрина-лаборатория 313, темы с React 232 и 345. Запас — 25–55 КБ: хватит на новый остров,
 * не хватит на второй рантайм.
 */
const LEAN_BUDGET_KB = 190;

function budgetFor(page: string): number {
  if (HEAVY_PAGES.has(page)) return HEAVY_BUDGET_KB;
  if (LABS_PAGES.has(page)) return LABS_BUDGET_KB;
  if (SHOWCASE_PAGES.has(page)) return SHOWCASE_BUDGET_KB;
  if (INTERACTIVE_PAGES.has(page)) return INTERACTIVE_BUDGET_KB;
  return LEAN_BUDGET_KB;
}

/** Статические импорты чанка: `import … from "./x.js"`, `export … from "./x.js"`, `import "./x.js"`. */
function staticImports(file: string): string[] {
  const source = readFileSync(fileURLToPath(new URL(`./_astro/${file}`, DIST)), 'utf8');
  return [...source.matchAll(/(?:import|export)\s*(?:[\w*{}\s,$]*?from\s*)?["']\.\/([^"']+\.js)["']/g)].map((m) => m[1]);
}

/**
 * Чанки, которые браузер скачает для страницы: всё, что названо в HTML (скрипты, `component-url`
 * и `renderer-url` островов), плюс всё, что они импортируют статически, — до конца графа.
 * Динамические `import()` внутри чанков не считаются: их грузят по событию, а не при открытии.
 */
function pageChunks(page: string): string[] | null {
  const html = new URL(`.${page}index.html`, DIST);
  if (!existsSync(html)) return null;

  const source = readFileSync(html, 'utf8');
  const queue = [...new Set([...source.matchAll(/\/_astro\/([^"'&]+?\.js)/g)].map((m) => m[1]))];
  const seen = new Set<string>();
  while (queue.length) {
    const file = queue.pop()!;
    if (seen.has(file) || !existsSync(new URL(`./_astro/${file}`, DIST))) continue;
    seen.add(file);
    queue.push(...staticImports(file));
  }
  return [...seen];
}

function scriptWeightKb(page: string): number | null {
  const chunks = pageChunks(page);
  if (!chunks) return null;
  let bytes = 0;
  for (const file of chunks) bytes += statSync(fileURLToPath(new URL(`./_astro/${file}`, DIST))).size;
  return Math.round(bytes / 1024);
}

/**
 * Признак рантайма React DOM. Не подстрока «react»: её дают `reactive` из Vue, а «react-dom» —
 * строки демо про гидратацию (`SsrLab`) и батчинг. Хук DevTools объявляет только сам рантайм.
 */
const REACT_RUNTIME = '__REACT_DEVTOOLS_GLOBAL_HOOK__';

function hasReactRuntime(page: string): boolean {
  return (pageChunks(page) ?? []).some((file) =>
    readFileSync(fileURLToPath(new URL(`./_astro/${file}`, DIST)), 'utf8').includes(REACT_RUNTIME),
  );
}

for (const page of PAGES) {
  const budget = budgetFor(page);

  test(`React только там, где он предмет темы: ${page}`, () => {
    expect(
      hasReactRuntime(page),
      HEAVY_PAGES.has(page)
        ? `${page} — тема про React, а рантайма React в её графе нет: сломался сам поиск?`
        : `${page} тянет рантайм React. Острова грузятся только там, где стоят, — значит React утёк в общий импорт.`,
    ).toBe(HEAVY_PAGES.has(page));
  });

  test(`вес скриптов в бюджете: ${page}`, () => {
    const weight = scriptWeightKb(page);
    expect(weight, `страница ${page} не собралась`).not.toBeNull();
    expect(
      weight,
      `${page} весит ${weight} КБ при бюджете ${budget} КБ. ` +
        'Если это React — проверьте, не утёк ли он в общий слой: острова грузятся только там, где стоят.',
    ).toBeLessThanOrEqual(budget);
  });
}
