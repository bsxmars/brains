import { describe, expect, it } from 'vitest';
import { extent, linePath, linear, log, logTicks, niceTicks } from '@/shared/lib/chart';

/**
 * Шкалы — это то, чем курс меряет свои же утверждения.
 *
 * Девять «диаграмм» в уроках нарисованы полосками без осей, и именно поэтому там дважды
 * оказались неверные числа: глазу не с чем свериться. Раз появились оси, их арифметика
 * обязана быть проверена — иначе ошибка шкалы выглядит убедительнее правды.
 */
describe('линейная шкала', () => {
  const scale = linear([0, 100], [0, 200]);

  it('переводит значение в координату', () => {
    expect(scale(0)).toBe(0);
    expect(scale(50)).toBe(100);
    expect(scale(100)).toBe(200);
  });

  it('переворачивается, когда ось идёт снизу вверх', () => {
    // У SVG ноль сверху, поэтому ось Y почти всегда задаётся обратным диапазоном.
    const y = linear([0, 10], [100, 0]);
    expect(y(0)).toBe(100);
    expect(y(10)).toBe(0);
  });
});

describe('логарифмическая шкала', () => {
  const scale = log([1, 1000], [0, 300]);

  it('равные отношения дают равные отрезки', () => {
    // Ради этого она и нужна: ×10 всегда одинаковый шаг, на какой бы высоте он ни случился.
    const first = scale(10) - scale(1);
    const second = scale(100) - scale(10);
    expect(Math.abs(first - second)).toBeLessThan(0.0001);
  });

  it('засечки встают по степеням', () => {
    expect(logTicks([1, 1000], 3)).toEqual(expect.arrayContaining([1, 10, 100, 1000]));
  });
});

describe('круглые засечки', () => {
  it('выбирает числа, которые человек назвал бы сам', () => {
    expect(niceTicks([0, 97], 5)).toEqual([0, 20, 40, 60, 80, 100]);
  });
});

describe('путь ломаной', () => {
  it('собирает координаты в один путь', () => {
    expect(linePath([[0, 10], [5, 0]])).toBe('M0,10L5,0');
  });

  it('пустой список даёт пустую строку, а не «null» в разметке', () => {
    expect(linePath([])).toBe('');
  });
});

describe('диапазон значений', () => {
  it('оставляет запас сверху, чтобы пик не упирался в рамку', () => {
    const [lo, hi] = extent([10, 40, 100]);
    expect(lo).toBe(0);
    expect(hi).toBeGreaterThan(100);
  });

  it('включает ноль, даже если все значения выше', () => {
    // Столбики, начинающиеся не от нуля, врут о соотношении — это первое, чем обманывают графики.
    expect(extent([50, 60])[0]).toBe(0);
  });
});
