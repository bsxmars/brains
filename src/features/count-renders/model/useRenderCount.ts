import { useRef } from 'react';

/**
 * Сколько раз была вызвана функция этого компонента.
 *
 * Это и есть определение ре-рендера: «React вызвал функцию заново». Другого способа узнать
 * факт вызова на статическом сайте нет — `<Profiler onRender>` вырезается из продакшен-сборки,
 * а курс собирается статически, значит на него опираться нельзя.
 *
 * ⚠️ Счётчик живёт на фибере (`useRef`), а не в модуле, и увеличивается **в теле компонента** —
 * то есть в render-фазе, где побочных эффектов быть не должно. Это сознательное нарушение
 * правила: прибор обязан мерить именно вызовы, а не коммиты, а всё остальное в React
 * происходит уже после. Цена нарушения ровно та, о которой говорит урок: в StrictMode
 * и при прерванном конкурентном рендере число окажется больше числа видимых обновлений.
 * В демо ни того, ни другого нет — острова монтируются без StrictMode, а все обновления
 * идут синхронной полосой.
 */
export function useRenderCount(): number {
  const count = useRef(0);
  count.current += 1;
  return count.current;
}
