export type ProbeRow = { expr: string; out: string | null };

function consoleOf(rows: ProbeRow[]): string {
  const w = Math.max(...rows.map((r) => r.expr.length)) + 2;
  return rows
    .map((r) => {
      if (r.out === null) return r.expr + ';';
      return r.expr.length + r.out.length + 5 <= 78 ? r.expr.padEnd(w) + '// ' + r.out : r.expr + '\n// → ' + r.out;
    })
    .join('\n');
}

