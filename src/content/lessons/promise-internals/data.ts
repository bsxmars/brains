export const POOL_CODE = `async function pool(items, limit, fn) {
  const it = items[Symbol.iterator]();
  // limit работников берут задачи из одного общего списка:
  // кто закончил свою, тот берёт следующую
  await Promise.all(Array.from({ length: limit }, async () => {
    for (let next = it.next(); !next.done; next = it.next()) await fn(next.value);
  }));
}`;

