function* lines() {
  try { yield 'строка 1'; yield 'строка 2'; }
  finally { log.push('файл закрыт'); }
}

function firstLine() {
  using it = lines();
  return it.next().value;
}

firstLine();   // 'строка 1', и в log уже есть 'файл закрыт'`;

