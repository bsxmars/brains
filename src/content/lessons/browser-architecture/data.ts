/** Native same-origin checks, executed unchanged by the browser regression spec. */
export const FRAME_ACCESS_CODE = `async function probeFrames(urls) {
  const results = [];
  for (const url of urls) {
    const frame = document.createElement('iframe');
    const loaded = new Promise(resolve => frame.onload = resolve);
    frame.src = url;
    document.body.append(frame);
    await loaded;
    let canReadDOM;
    try {
      void frame.contentWindow.document;
      canReadDOM = true;
    } catch (error) {
      if (error.name !== 'SecurityError') throw error;
      canReadDOM = false;
    }
    results.push({ url, canReadDOM });
    frame.remove();
  }
  return results;
}
// Запустить на https://app.shop.com: все три адреса должны отвечать HTML.
const probes = await probeFrames(${JSON.stringify(["https://app.shop.com/", "https://cdn.shop.com/widget", "https://api.shop.com:8443/status"], null, 2)});
console.table(probes);`;

