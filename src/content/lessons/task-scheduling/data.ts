export const IDLE_VS_POST_TASK =
  '**Чем он отличается от `postTask({ priority: \'background\' })`.** `postTask` ставит настоящую задачу. Она выполнится — просто после остальных задач планировщика, — и время ей никто не ограничивает. `requestIdleCallback` вообще не задача планировщика. Это колбэк, который браузер вызывает, только когда ему нечем заняться. Отсюда три отличия. Первое: он может не наступить никогда — поэтому и нужен `timeout`, иначе фоновая работа тихо не выполнится. Второе: он приходит с дедлайном, и соблюдать дедлайн должны вы сами: `timeRemaining()` уйдёт в ноль, но колбэк никто не прервёт. Третье: он обещает не место в очереди, а остаток времени. `background` значит «после моих важных задач», а простой — «если останется время».';

