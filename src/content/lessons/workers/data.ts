/**
 * Данные темы «Воркеры и параллелизм».
 *
 * ── Чем и как мерилось ───────────────────────────────────────────────────────────────
 *
 * Chromium 153 (HeadlessChrome/153.0.8010.12) под Playwright 1.63 на macOS, 8 логических ядер,
 * страница отдаётся обычным http-сервером с localhost. Воркер поднимается из `blob:` — тот же
 * способ, что в демо на странице, чтобы числа урока и числа читателя мерили одно и то же.
 *
 * Каждый замер — медиана пяти прогонов. Буфер заполняется (`fill`) **до** замера: у нетронутого
 * `ArrayBuffer` физические страницы ещё не выданы, и копия такого буфера обошлась бы
 * подозрительно дёшево — мерили бы ленивую аллокацию, а не канал.
 *
 * Снимаются два времени, а не одно:
 *   «внутри postMessage» — сколько главный поток простоял в самом вызове (цена сериализации);
 *   «до ответа воркера»  — плюс десериализация на той стороне и два прохода через очереди задач.
 *
 * Таблица изоляции снята дважды на одной и той же странице: без заголовков и с
 * `Cross-Origin-Opener-Policy: same-origin` + `Cross-Origin-Embedder-Policy: require-corp`.
 * Всё про `structuredClone` и `ArrayBuffer.prototype.transfer` проверено в Node 24.11
 * и закреплено `tests/unit/clone-survival.test.ts`.
 *
 * ── Где числа разошлись с конспектом ─────────────────────────────────────────────────
 *
 * 1. `lastIndex` у `RegExp` клонирование **не переживает**. И Node 24.11, и Chromium 153 дают
 *    ноль: спека переносит `[[OriginalSource]]` и `[[OriginalFlags]]`, позиция поиска в список
 *    не входит. В уроке это записано как молчаливая потеря и закрыто тестом.
 * 2. «Chrome оставляет конструктор `SharedArrayBuffer` доступным и без изоляции» — в этой сборке
 *    неверно: `typeof SharedArrayBuffer` равен `'undefined'`. Вывод конспекта («проверять надо
 *    `crossOriginIsolated`») от этого только крепнет, но сам факт сборкозависим. До 2026-10-29
 *    `ISOLATION_FOOT` и тонкое место 04 всё ещё повторяли «браузеры оставляли конструктор» —
 *    переписано: имя спрятано, а буфер достаётся через `WebAssembly.Memory({ shared: true })`
 *    (замер `wasm-threads/data.ts`, `SHARED_BROWSER`, e2e `wasm-threads.spec.ts`).
 * 3. Отправка SAB в shared worker **не бросила** у отправителя — сработал `messageerror`
 *    у получателя. Конспект допускал оба исхода; проверен второй.
 * 4. Геттер класса в клон не попадает вовсе. Конспект (и вообще расхожее объяснение) обещает
 *    «геттер вычислится во время `postMessage` и уедет значением» — но это верно только для
 *    **собственных перечисляемых** геттеров, то есть для литерала объекта. Геттер, объявленный
 *    в классе, живёт на прототипе, и сериализатор до него не доходит: `structuredClone(new
 *    Money(1250))` даёт `{ currency: 'EUR' }` и в Node 24.11, и в Chromium 153. Закреплено тестом.
 * 5. `AbortSignal` движкозависим: в Chromium — `DataCloneError`. В Node 26.8.2 вызов не бросает,
 *    но и сигнала не переносит: клон — пустой `Object` (`aborted === undefined`). Прежняя
 *    строка «в Node сигнал клонируется» была неправдой и снята 2026-10-29. Из юнит-теста случай
 *    исключён (в Node он не `throw`, а молчаливая потеря).
 * 6. **Цена старта воркера была снята под нагрузкой.** В теме стояла «медиана 20 мс, разброс
 *    6–76 мс, `blob:`, без сети». Пересъёмка той же методикой на тихой машине (Chromium
 *    153.0.8010.12, Playwright): **1.7 мс** на пустой странице и **3.4 мс** на собранной
 *    странице этой темы под `astro preview`. Три независимых прогона, разброс внутри прогона
 *    1.6–3.9 мс после прогрева. Сам разброс 6–76 и был подписью занятой машины — ровно тот
 *    случай, о котором предупреждает свод проекта. Число заменено на отношение: старт на два
 *    порядка дороже round-trip (0.01 мс), а абсолют подписан условиями замера. Вывод темы
 *    («воркеры пулятся, а не создаются под задачу») от этого не пострадал — он опирается
 *    на память агента и на сам разброс, а не на двадцатку.
 *
 * ── Что снято для шестого раздела (Chromium 153.0.8010.12, Node 26.8.2) ──────────────
 *
 * `navigator.hardwareConcurrency` — 8; `os.availableParallelism()` — 8; старт `worker_threads`
 * в Node — 14 мс; round-trip пустого сообщения — 0.01 мс (медиана пяти прогонов по 200 обменов);
 * перенос 8 МБ — 1.2 мс, исходный буфер после переноса нулевой. В **выделенном** воркере:
 * `requestAnimationFrame` — `function`, `OffscreenCanvas` — `function`, `document`
 * и `localStorage` — `undefined`. В `SharedWorker`: `requestAnimationFrame` — **`undefined`**,
 * `OffscreenCanvas` — `function`. Этим закрыты два обещания соседних тем: «Рендеринг · WebGL»
 * отсылает сюда за офскрин-холстом и единственным кадровым циклом вне окна, а «Устройство
 * браузера» — за ответом, сколько воркеров заводить. До сих пор оба пункта лежали
 * в «за кадром», то есть ссылки вели к отказу от разбора.
 *
 * ── Второй проход (сентябрь 2026, Node 26.8.2, детерминированные прогоны без таймеров) ──
 *
 * Переносимые стримы (раздел 3, `STREAM_TRANSFER_*`) сняты в `worker_threads`: без списка
 * переноса — `DataCloneError`; после переноса исходный стрим `locked === true`; пока воркер
 * не читает, источник отработал `pull` 2 раза (один чанк в очереди, один в пути), после
 * одного чтения — 3; чанк-`Uint8Array` у отправителя после пересылки **не** отсоединён,
 * то есть чанки клонируются, а не переносятся; чанк с функцией даёт `DataCloneError` у читателя
 * в воркере и `cancel` источника с той же ошибкой; `reader.cancel('stop')` в воркере доходит
 * до `cancel` источника с причиной `'stop'`. ⚠️ В браузере этот раздел запуском не проверялся —
 * опора на спецификацию (cross-realm transform streams).
 *
 * Пул (`POOL_CODE`, раздел 6) прогнан в Node через прослойку `Worker` поверх `worker_threads`:
 * два воркера и очередь на три — шесть задач дают пять ответов и один быстрый отказ; ошибка
 * в воркере доходит до `reject`; зависшая задача по таймауту убивает воркер и заменяет его
 * новым (3 запуска, 1 `terminate`), и пул продолжает отвечать; перенос буфера через пул
 * обнуляет его у отправителя.
 *
 * `structuredClone`: идентичность сохраняется внутри одного вызова (`c.a === c.b`), а между
 * двумя вызовами — нет. Добавлено в `MEMORY_MAP_NOTE`.
 *
 * Логика, а не факт: `SHAPE_NOTE` и тонкое место 01 говорили «цену определяет число объектов,
 * а не число байт» — и спорили с таблицей `COST` в том же разделе, где копия дорожает вместе
 * с объёмом. Формулировка сужена до «при равном объёме»: числа не менялись.
 *
 * ── Третий проход: «за кадром» раскрыт (сентябрь 2026) ────────────────────────────────
 *
 * Node 26.8.2, детерминированные прогоны, закреплено `tests/unit/workers.test.ts`:
 * `worker_threads` — тот же `process.pid`, `process.exit(3)` в воркере завершает только
 * воркер (код 3 в событии `exit`), брошенная ошибка приходит событием `error`; `cluster.fork`
 * — свой pid, канал по умолчанию JSON: `Map` и `SharedArrayBuffer` приезжают `{}` молча,
 * с `serialization: 'advanced'` `Map` доезжает, а SAB даёт `could not be cloned`;
 * `process.env` воркера — копия, `SHARE_ENV` делает его общим; пул `Buffer` помечен
 * `markAsUntransferable` (у `Buffer.allocUnsafe` — да, у `Buffer.alloc` — нет), перенос
 * помеченного буфера — `DataCloneError`, копия — проходит; `performance.timeOrigin`
 * у `worker_threads` **совпадает** с процессом.
 *
 * Chromium 153.0.8010.12, свой Playwright-скрипт на отдельном порту (не общий прогон):
 * в выделенном воркере `self.fonts` — `FontFaceSet`, `FontFace` — `function`,
 * `fillText` у 2D-контекста офскрин-холста есть, `devicePixelRatio` и `matchMedia` —
 * `undefined`; шрифт, загруженный страницей, в воркере не виден (`self.fonts.size` 0, ширина
 * текста равна запасному шрифту); после `transferControlToOffscreen()` у элемента и `width = …`,
 * и `getContext` дают `InvalidStateError`, а `offscreen.width = 600` в воркере проходит;
 * `structuredClone(new PointerEvent(…))` — `DataCloneError`; `performance.timeOrigin`
 * воркера позже, чем у страницы: сырое `performance.now()` воркера не попало в окно
 * «до создания — после ответа» по часам страницы, переведённое через `timeOrigin` — попало,
 * а `performance.mark(имя, { startTime })` принял его.
 * ⚠️ Там же найдено: строка шрифта, использованная в воркере **до** загрузки шрифта, остаётся
 * на запасном и после загрузки (ширина 132.2 до и после; на странице та же последовательность
 * даёт 132.2 → 216); новая строка (другой кегль) шрифт подхватывает. Это поведение реализации,
 * а не норма, — в тексте так и подписано.
 *
 * ── Вычитка 2026-10-29: правда и доступность ─────────────────────────────────────────
 *
 * Chromium 153.0.8010.12 (Playwright, http-сервер с COOP/COEP и без), Node 26.8.2:
 * без изоляции общий буфер достаётся через `new WebAssembly.Memory({ shared: true })`,
 * `Atomics.wait` на нём на главном потоке — `TypeError`, `Atomics.notify` — 0 (разрешён),
 * `postMessage` в выделенный **и** в shared worker — `DataCloneError` у отправителя;
 * с изоляцией выделенный воркер получает буфер, shared worker — `messageerror`.
 * `Promise` и `AbortSignal` в списке переноса — `DataCloneError` (переносим из троих только
 * `MessagePort`). В воркере `localStorage` — `undefined`, `self.fonts` — объект,
 * `requestAnimationFrame` работает и без холста (10 кадров за ~140 мс). Модульный воркер
 * с 404 даёт на странице простое `Event` без `message`. Брошенная в воркере ошибка приходит
 * и сообщением от его обработчика `error`, и событием `error` на странице; отклонённый промис
 * до страницы не доходит — только сообщением от обработчика `unhandledrejection`.
 *
 * По памяти, запуском не проверялось: Comlink (`await proxy.db` отдельно — обмен, который
 * возвращает копию значения, а не прокси); DevTools Threads; номера глав HTML Standard
 * (воркеры — глава 10, агенты и кластеры — 8.1, structured clone — 2.7); то, что
 * `ResizeObserver` без `device-pixel-content-box` не видит смены DPR (эмуляция в Chromium
 * не сработала ни для какого блока, вывод — по спецификации).
 *
 * ── Что осталось непроверенным ───────────────────────────────────────────────────────
 *
 * Поведение десктопного Chrome с корпоративной политикой, разрешающей SAB без изоляции;
 * Firefox и Safari; ARM против x86 в разделе про переупорядочивание — гонку такого рода
 * нельзя «показать» запуском, её можно только не допустить. Всё это помечено в тексте.
 */

