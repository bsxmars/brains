/**
 * Пул и его воркер. Исполняются тестом `workers.test.ts` в Node через прослойку `Worker` поверх
 * `worker_threads` (строка `POOL_WORKER_CODE` — та же, только `work` подменяется тестовой):
 * два воркера и очередь на три — шесть задач дают пять ответов и один быстрый отказ;
 * `{ error }` доходит до `reject`; `{ fatal }` из `ERRORS_CODE` (асинхронное исключение)
 * отклоняет задачу и заменяет воркер; ошибка загрузки (событие `error`) — то же; зависшая
 * задача снимается таймаутом и воркер заменяется; запоздалое второе сообщение воркера не кладёт
 * его в `#idle` повторно (иначе одному воркеру ушли бы две задачи сразу).
 *
 * До 2026-10-29 пул понимал только `{ result }` / `{ error }`: сообщение `{ __fatal }` из
 * `ERRORS_CODE` разрешалось как `resolve(undefined)`, событие `error` не слушалось, а позднее
 * сообщение вызывало старый обработчик и второй раз клало воркер в `#idle`.
 */
export const POOL_CODE = `class WorkerPool {
  #idle = []; #queue = []; #busy = new Map(); #url; #maxQueue; #seq = 0;

  constructor(url, size, maxQueue = 100) {
    this.#url = url;
    this.#maxQueue = maxQueue;
    for (let i = 0; i < size; i++) this.#idle.push(this.#spawn());
  }

  run(data, { transfer = [], timeout = 10_000 } = {}) {
    if (this.#queue.length >= this.#maxQueue) {
      return Promise.reject(new Error('pool: очередь полна'));  // быстрый отказ
    }
    return new Promise((resolve, reject) => {
      this.#queue.push({ id: ++this.#seq, data, transfer, timeout, resolve, reject });
      this.#next();
    });
  }

  #spawn() {
    const worker = new Worker(this.#url, { type: 'module', name: 'pool' });
    worker.onmessage = ({ data }) => {
      if (data.fatal) return this.#settle(worker, new Error(data.fatal), true);
      const task = this.#busy.get(worker);
      if (!task || data.id !== task.id) return;        // запоздалое сообщение — пропустить
      if ('error' in data) this.#settle(worker, new Error(data.error), false);
      else this.#settle(worker, null, false, data.result);
    };
    worker.onerror = (e) => {                           // не загрузился или упал
      this.#settle(worker, new Error(e.message ?? 'pool: воркер не загрузился'), true);
    };
    return worker;
  }

  #next() {
    if (!this.#idle.length || !this.#queue.length) return;
    const worker = this.#idle.pop();
    const task = this.#queue.shift();
    task.timer = setTimeout(() => {                     // завис — убить и заменить
      this.#settle(worker, new Error('pool: таймаут'), true);
    }, task.timeout);
    this.#busy.set(worker, task);
    worker.postMessage({ id: task.id, data: task.data }, task.transfer);
  }

  #settle(worker, error, broken, result) {              // ровно один исход на задачу
    const task = this.#busy.get(worker);
    this.#busy.delete(worker);
    if (task) {
      clearTimeout(task.timer);
      error ? task.reject(error) : task.resolve(result);
    }
    if (broken) {
      worker.onmessage = worker.onerror = null;         // его поздние события — никуда
      worker.terminate();
      this.#idle = this.#idle.filter((w) => w !== worker);
      this.#idle.push(this.#spawn());
    } else {
      this.#idle.push(worker);
    }
    this.#next();
  }
}`;

