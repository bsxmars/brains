/**
 * Реализация throttle, о которой говорят карточки раздела: без неё проверка `lastArgs`
 * и обнуление `lastArgs = lastThis = null` обсуждались, а кода не было.
 *
 * ⚠️ Проверено `node` на 26.8.2 с подменённым `setTimeout` (ручные часы): на трёх
 * последовательностях демо (`SEQUENCES`, wait 100) вызовы совпали с моделью виджета
 * `simulateThrottle(…, leading: true, trailing: true)` — 0(0) 100(80) 300(300);
 * 0(0) 100(90) 200(180); одиночное событие — ровно один вызов 0(0).
 */
export const THROTTLE_CODE = `function throttle(fn, wait) {
  let timer = null, lastArgs = null, lastThis = null;

  function endOfWindow() {
    if (lastArgs === null) { timer = null; return; }  // окно прошло тихо
    fn.apply(lastThis, lastArgs);                      // trailing: последнее событие окна
    lastArgs = lastThis = null;                        // не держать тяжёлый аргумент
    timer = setTimeout(endOfWindow, wait);             // этот вызов открыл новое окно
  }

  return function (...args) {
    if (timer === null) {                              // окна нет → leading
      fn.apply(this, args);
      timer = setTimeout(endOfWindow, wait);
    } else { lastArgs = args; lastThis = this; }       // внутри окна — только запомнить
  };
}`;

