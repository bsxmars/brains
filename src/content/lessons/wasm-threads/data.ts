/* ──────────────────────────── Общая память и атомарные инструкции ────────────────────────────
 *
 * Модуль не объявляет память, а **импортирует** её: `env.mem`, общую, ровно в одну страницу.
 * Так одну и ту же память получают экземпляры в разных потоках — модуль один, экземпляров
 * столько, сколько воркеров.
 *
 *   bump(addr, n)          n раз атомарно прибавить 1 по адресу — i32.atomic.rmw.add
 *   racy(addr, n)          то же обычными load/add/store — для сравнения
 *   wait(addr, v, ns)      спать, пока по адресу лежит v — memory.atomic.wait32
 *   wake(addr, count)      разбудить ждущих на адресе — memory.atomic.notify
 */

/** Цикл «пока $n ≠ 0: тело; $n -= 1» — общий каркас bump и racy. */
function countdown(inner: number[]): number[] {
  return [
    0x02, 0x40, 0x03, 0x40, //          block, loop
    0x20, 1, 0x45, 0x0d, 1, //          local.get 1, i32.eqz, br_if 1
    ...inner,
    0x20, 1, 0x41, 1, 0x6b, 0x21, 1, // $n -= 1
    0x0c, 0, 0x0b, 0x0b, //             br 0, end, end
    0x0b, //                            end
  ];
}

