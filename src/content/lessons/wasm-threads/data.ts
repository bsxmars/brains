/** Исполняемая запись тех же байтов: источник для читателя, а не второй модуль. */
function byteSource(bytes: number[], exported = false, binding = 'bytes'): string {
  const rows: string[] = [];
  for (let i = 0; i < bytes.length; i += 12) {
    rows.push('  ' + bytes.slice(i, i + 12).map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  }
  return `${exported ? 'export ' : ''}const ${binding} = new Uint8Array([\n${rows.join('\n')}\n]);`;
}

