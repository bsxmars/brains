/* ──────────────────────────── Сборка байтов ────────────────────────────
 *
 * Три крошечных помощника вместо ассемблера. Они не прячут формат, а только считают длины:
 * в двоичном Wasm перед каждой секцией, строкой и телом функции стоит длина в LEB128, и
 * считать её руками — единственное, в чём легко ошибиться. Всё остальное — байты как есть.
 */

/** Беззнаковое LEB128: по 7 бит на байт, старший бит — «дальше ещё байт». */
export function leb(n: number): number[] {
  const out: number[] = [];
  do {
    let byte = n & 0x7f;
    n >>>= 7;
    if (n !== 0) byte |= 0x80;
    out.push(byte);
  } while (n !== 0);
  return out;
}

/** Имя в секциях импорта и экспорта: длина и байты UTF-8 (здесь — только латиница). */
function name(s: string): number[] {
  return [s.length, ...[...s].map((c) => c.charCodeAt(0))];
}

/** Тело функции: длина, затем объявления локальных и инструкции. */
function body(code: number[]): number[] {
  return [...leb(code.length), ...code];
}

/** Секция учебного модуля: номер, имя по спецификации и содержимое без заголовка. */
export interface WasmSection {
  id: number;
  name: string;
  content: number[];
}

/** Собрать модуль: `\0asm`, версия 1, затем секции «номер · длина · содержимое». */
export function assemble(sections: WasmSection[]): number[] {
  return [
    0x00, 0x61, 0x73, 0x6d, // магия: \0 a s m
    0x01, 0x00, 0x00, 0x00, // версия 1, четыре байта little-endian
    ...sections.flatMap((s) => [s.id, ...leb(s.content.length), ...s.content]),
  ];
}

