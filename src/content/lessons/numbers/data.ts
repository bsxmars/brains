/**
 * Учебная реализация: биты double и точное десятичное значение.
 * Печатается на странице, исполняется виджетом `double-lab` и тестом — против `Float64Array`,
 * `toFixed` и `BigInt` на сотнях тысяч чисел.
 */
export const DOUBLE_CODE = `// Разобрать double на три поля. DataView видит те же 8 байт, что лежат в памяти.
function decodeDouble(x) {
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, x);                    // старший байт — первым: в нём знак
  const hi = view.getUint32(0);
  const lo = view.getUint32(4);
  const sign = hi >>> 31;                   // 1 бит
  const exponent = (hi >>> 20) & 0x7ff;     // 11 бит
  const mantissa = (BigInt(hi & 0xfffff) << 32n) | BigInt(lo); // 52 бита
  return { sign, exponent, mantissa };
}

// Собрать обратно: те же поля — в те же биты.
function encodeDouble({ sign, exponent, mantissa }) {
  const view = new DataView(new ArrayBuffer(8));
  view.setUint32(0, (sign << 31) | (exponent << 20) | Number(mantissa >> 32n));
  view.setUint32(4, Number(mantissa & 0xffffffffn));
  return view.getFloat64(0);
}

// Что значат поля: |x| = m · 2^e, где m — целое. Обычное число:
// мантисса с неявной единицей впереди. Порядок 0 — ноль и самые
// маленькие (субнормальные) числа: без неявной единицы.
function fieldsToExact({ exponent, mantissa }) {
  if (exponent === 0x7ff) return null;      // Infinity или NaN
  if (exponent === 0) return { m: mantissa, e: -1074 };
  return { m: mantissa | (1n << 52n), e: exponent - 1075 };
}

// Точное десятичное значение — все цифры, без округления.
// m · 2^e при e < 0 — это m · 5^(−e) / 10^(−e): деление на степень
// десяти только сдвигает запятую, а цифры считает BigInt.
function exactDecimal(x) {
  if (Number.isNaN(x)) return 'NaN';
  const fields = decodeDouble(x);
  const sign = fields.sign ? '-' : '';
  const exact = fieldsToExact(fields);
  if (!exact) return sign + 'Infinity';
  const { m, e } = exact;
  if (e >= 0) return sign + (m << BigInt(e)).toString();
  const digits = (m * 5n ** BigInt(-e)).toString().padStart(-e + 1, '0');
  const int = digits.slice(0, e);
  const frac = digits.slice(e).replace(/0+$/, '');
  return sign + int + (frac ? '.' + frac : '');
}

// Соседний double дальше от нуля. Биты |x| — это 63-битное целое, и соседние
// по величине числа — соседние целые: перенос из мантиссы сам попадёт в порядок.
// Для конечных x; у самого большого double сосед — Infinity.
function nextAway(x) {
  const { sign, exponent, mantissa } = decodeDouble(x);
  const next = ((BigInt(exponent) << 52n) | mantissa) + 1n;
  return encodeDouble({ sign, exponent: Number(next >> 52n), mantissa: next & 0xfffffffffffffn });
}`;

