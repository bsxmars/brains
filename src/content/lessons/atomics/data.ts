export const WAIT_LOOP_CODE = `// Писатель один раз публикует данные: store(flag, 0, 1), затем notify(flag, 0).
// Флажок после публикации не сбрасывается и данные больше не меняются.
async function waitUntilReady(flag) {
  while (Atomics.load(flag, 0) === 0) {
    const { value } = Atomics.waitAsync(flag, 0, 0);
    await value;  // value бывает и строкой, и промисом
  }
  // Здесь читатель может использовать опубликованные данные.
}`;

