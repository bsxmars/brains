export const CAS_CODE = `function atomicMax(cells, i, value) {
  let seen = Atomics.load(cells, i);
  while (value > seen) {
    const before = Atomics.compareExchange(cells, i, seen, value);
    if (before === seen) return;   // там было то, что мы видели, — записали мы
    seen = before;                 // кто-то успел раньше — пробуем снова с его числом
  }
}`;

export const CAS_NOTE =
  '`compareExchange` — основа всего, для чего готовой операции нет. Готового «записать максимум» в `Atomics` нет, и его собирают циклом. Прочитать значение, решить, что записать, и записать **при условии, что значение не изменилось**. Если между чтением и записью другой поток успел своё, `compareExchange` ничего не запишет и вернёт его число — тогда попытка повторяется. Так же собирают любую операцию «прочитать — подумать — записать».';

