export const LITMUS_WORKER_CODE = `// role.mjs
import { workerData } from 'node:worker_threads';

const { role, mode, rounds } = workerData;
const cells = new Int32Array(workerData.buffer);
const read = mode === 'Atomics' ? (i) => Atomics.load(cells, i) : (i) => cells[i];
const write = mode === 'Atomics' ? (i, v) => Atomics.store(cells, i, v) : (i, v) => { cells[i] = v; };

for (let round = 1; round <= rounds; round++) {
  if (role === 'писатель') {
    while (Atomics.load(cells, 2) !== round - 1) {}   // ждём, пока читатель заберёт прошлое
    write(0, round);                                  // сначала данные
    write(1, round);                                  // потом флажок
  } else {
    while (read(1) !== round) {}                      // ждём флажок
    if (read(0) !== round) Atomics.add(cells, 3, 1);  // флажок есть, а данных ещё нет
    Atomics.store(cells, 2, round);
  }
}`;

