/**
 * Тест кладёт три файла рядом (`mutex.mjs`, `pair.mjs`, `main.mjs`) и запускает `main.mjs`:
 * без замка пара расходится с 400 000, с замком — `400000 400000`.
 */
export const MUTEX_CODE = `// mutex.mjs
const UNLOCKED = 0, LOCKED = 1;

export function lock(m) {
  // занять замок, если свободен; если занят — уснуть, пока его не отпустят
  while (Atomics.compareExchange(m, 0, UNLOCKED, LOCKED) !== UNLOCKED) {
    Atomics.wait(m, 0, LOCKED);
  }
}

export function unlock(m) {
  Atomics.store(m, 0, UNLOCKED);
  Atomics.notify(m, 0, 1);         // разбудить одного из ждущих
}`;

export const MUTEX_WORKER_CODE = `// pair.mjs — воркер: два поля, которые должны меняться вместе
import { workerData } from 'node:worker_threads';
import { lock, unlock } from './mutex.mjs';

const m = new Int32Array(workerData.buffer, 0, 1);
const pair = new Int32Array(workerData.buffer, 4, 2);
for (let i = 0; i < 100_000; i++) {
  if (workerData.useLock) lock(m);
  pair[0] = pair[0] + 1;           // обычные записи — под замком их никто не застанет
  pair[1] = pair[0];
  if (workerData.useLock) unlock(m);
}`;

export const MUTEX_MAIN_CODE = `// main.mjs
import { Worker } from 'node:worker_threads';

const buffer = new SharedArrayBuffer(12);   // замок + два поля
for (const useLock of [false, true]) {
  new Int32Array(buffer).fill(0);
  const workers = [1, 2, 3, 4].map(() =>
    new Worker(new URL('./pair.mjs', import.meta.url), { workerData: { buffer, useLock } }));
  await Promise.all(workers.map((w) => new Promise((done) => w.on('exit', done))));
  const pair = new Int32Array(buffer, 4, 2);
  console.log(useLock ? 'с замком:' : 'без замка:', pair[0], pair[1]);
}`;

