  '`Atomics.add` спасает одно число. Когда вместе должны меняться **два** поля — баланс и журнал, размер и содержимое, — нужен замок: если все участники соблюдают этот протокол, критическую секцию выполняет только один поток. `lock` пытается сменить 0 на 1 через `compareExchange`. Получилось — замок наш; нет — поток засыпает на `wait` и пробует снова, когда его разбудят. `unlock` возвращает 0 и будит одного ждущего. Без замка четыре воркера по сто тысяч дали 208 849 вместо 400 000, с замком — ровно 400 000.';

