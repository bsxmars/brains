const cfg = { mode: 'dark' };                           // поле: string
setMode(cfg.mode);                                      // ts(2345)
const cfgC = { mode: 'dark' } as const;                 // поле: 'dark', readonly
const cfgS = { mode: 'dark' } satisfies { mode: Mode }; // поле: 'dark'
setMode(cfgC.mode);                                     // OK
setMode(cfgS.mode);                                     // OK`;

