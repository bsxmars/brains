export const SEARCH_CODE = `// Поиск по курсу: слова всех заголовков — в один trie, а для каждого
// слова — список заголовков, где оно стоит (обратный индекс).
function buildIndex(entries) {
  const trie = createTrie();
  const where = new Map();                 // слово → [{ id, at, start, end }]
  entries.forEach((entry, id) => {
    const re = /[\\p{L}\\p{N}]+/gu;
    let m;
    let at = 0;                            // номер слова в заголовке
    while ((m = re.exec(entry.text))) {
      const word = m[0].toLowerCase();
      insert(trie, word);
      if (!where.has(word)) where.set(word, []);
      where.get(word).push({ id, at: at++, start: m.index, end: m.index + m[0].length });
    }
  });
  return { trie, where, entries };
}

// Каждое слово запроса — начало слова заголовка или (typos) слово
// с опечаткой. Заголовок подходит, если нашлись все слова запроса.
function search(index, query, typos) {
  const terms = query.toLowerCase().match(/[\\p{L}\\p{N}]+/gu) ?? [];
  let visited = 0;
  let hits = null;                         // id → находка
  for (const term of terms) {
    const cost = new Map();                // слово словаря → цена
    const pre = withPrefix(index.trie, term);
    visited += pre.visited;
    for (const w of pre.words) cost.set(w, 0);
    if (typos) {
      const k = term.length < 3 ? 0 : term.length < 6 ? 1 : 2;
      const fz = searchTrie(index.trie, term, k, true);
      visited += fz.visited;
      for (const f of fz.found) if (!cost.has(f.word)) cost.set(f.word, f.distance);
    }
    const best = new Map();                // id → лучшее место этого слова
    for (const [word, c] of cost) {
      for (const p of index.where.get(word)) {
        const old = best.get(p.id);
        const whole = c === 0 && word === term;
        if (!old || c < old.cost || (c === old.cost && (whole > old.whole
            || (whole === old.whole && p.at < old.at)))) {
          best.set(p.id, { ...p, cost: c, whole });
        }
      }
    }
    const next = new Map();
    for (const [id, b] of best) {
      if (hits && !hits.has(id)) continue;
      const h = hits ? hits.get(id) : { id, cost: 0, at: Infinity, whole: 0, marks: [] };
      next.set(id, { id, cost: h.cost + b.cost, at: Math.min(h.at, b.at),
        whole: h.whole + (b.whole ? 1 : 0), marks: [...h.marks, [b.start, b.end]] });
    }
    hits = next;
  }
  return { hits: hits ? [...hits.values()] : [], visited };
}`;

