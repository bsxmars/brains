export const WITHIN_CODE = `// Расстояние, если оно не больше k, иначе k + 1. Нужно не «сколько»,
// а «годится ли»: считаем только полосу |i − j| ≤ k и выходим,
// как только вся строка таблицы больше k — дальше будет только хуже.
function levenshteinWithin(a, b, k) {
  const FAR = k + 1;
  let cells = 0;
  if (Math.abs(a.length - b.length) > k) return { distance: FAR, cells };
  let prev = [];
  for (let j = 0; j <= b.length; j++) prev[j] = j <= k ? j : FAR;
  for (let i = 1; i <= a.length; i++) {
    const cur = new Array(b.length + 1).fill(FAR);
    if (i <= k) cur[0] = i;
    let rowMin = cur[0];
    const from = Math.max(1, i - k);
    const to = Math.min(b.length, i + k);
    for (let j = from; j <= to; j++) {
      cells++;
      cur[j] = Math.min(FAR, prev[j] + 1, cur[j - 1] + 1,
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      rowMin = Math.min(rowMin, cur[j]);
    }
    if (rowMin > k) return { distance: FAR, cells };   // ранний выход
    prev = cur;
  }
  return { distance: prev[b.length], cells };
}`;

