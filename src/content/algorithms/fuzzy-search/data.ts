export const TRIE_CODE = `// Узел trie — одна буква пути от корня. next: буква → ребёнок,
// end: здесь кончается слово словаря.
function createTrie() {
  return { root: { next: new Map(), end: false }, nodes: 1 };
}

function insert(trie, word) {
  let node = trie.root;
  for (const ch of word) {
    let child = node.next.get(ch);
    if (!child) {
      child = { next: new Map(), end: false };
      node.next.set(ch, child);
      trie.nodes++;
    }
    node = child;
  }
  node.end = true;
}

// Слова с префиксом prefix, не больше limit штук.
// visited — сколько узлов пришлось тронуть: это и есть работа.
function withPrefix(trie, prefix, limit = Infinity) {
  let node = trie.root;
  let visited = 1;
  for (const ch of prefix) {            // 1. спуск по буквам префикса
    node = node.next.get(ch);
    if (!node) return { words: [], visited };
    visited++;
  }
  const words = [];
  function walk(n, path) {              // 2. обход поддерева
    if (n.end) words.push(path);
    for (const [ch, child] of n.next) {
      if (words.length >= limit) return;
      visited++;
      walk(child, path + ch);
    }
  }
  walk(node, prefix);
  return { words: words.slice(0, limit), visited };
}`;

