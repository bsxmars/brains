export const LEV_CODE = `// Левенштейн: сколько вставок, удалений и замен превращают a в b.
// Таблица та же, что у LCS, только с заменой; храним две строки.
function levenshtein(a, b) {
  let prev = [];
  for (let j = 0; j <= b.length; j++) prev[j] = j;
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(
        prev[j] + 1,                                     // удалить a[i-1]
        cur[j - 1] + 1,                                  // вставить b[j-1]
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1),   // заменить или совпало
      );
    }
    prev = cur;
  }
  return prev[b.length];
}

// Дамерау (вариант OSA): ещё и перестановка двух соседних букв за 1.
// Нужна строка таблицы на два шага назад.
function damerau(a, b) {
  let prev2 = null;
  let prev = [];
  for (let j = 0; j <= b.length; j++) prev[j] = j;
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1,
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) {
        cur[j] = Math.min(cur[j], prev2[j - 2] + 1);     // «ри» ↔ «ир»
      }
    }
    prev2 = prev;
    prev = cur;
  }
  return prev[b.length];
}`;

