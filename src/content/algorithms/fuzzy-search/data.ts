export const BK_CODE = `// BK-дерево: дети узла разложены по расстоянию до слова узла.
// Работает с любой метрикой dist — функцией, где верно неравенство треугольника.
function bkInsert(tree, word, dist) {
  if (!tree.root) { tree.root = { word, kids: new Map() }; return; }
  let node = tree.root;
  for (;;) {
    const d = dist(word, node.word);
    if (d === 0) return;
    const next = node.kids.get(d);
    if (!next) { node.kids.set(d, { word, kids: new Map() }); return; }
    node = next;
  }
}

function bkSearch(tree, word, k, dist) {
  const found = [];
  let calls = 0;
  const stack = tree.root ? [tree.root] : [];
  while (stack.length) {
    const node = stack.pop();
    const d = dist(word, node.word);
    calls++;
    if (d <= k) found.push({ word: node.word, distance: d });
    // Слово на расстоянии ≤ k от запроса лежит от узла на d − k … d + k.
    for (const [dk, child] of node.kids) {
      if (dk >= d - k && dk <= d + k) stack.push(child);
    }
  }
  return { found, calls };
}`;

