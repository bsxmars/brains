export const G_CODE = `// G-Counter: только растёт. У каждого участника своя ячейка,
// и прибавляет он только в свою.
function gInc(c, client, n = 1) {
  return { ...c, [client]: (c[client] ?? 0) + n };
}
const gValue = (c) => Object.values(c).reduce((s, n) => s + n, 0);

// Слияние — максимум по каждой ячейке.
function gMerge(a, b) {
  const out = { ...a };
  for (const k in b) out[k] = Math.max(out[k] ?? 0, b[k]);
  return out;
}

// PN-Counter: умеет и убывать. Это два G-Counter — плюсы и минусы.
const pnInc = (c, client) => ({ p: gInc(c.p, client), n: c.n });
const pnDec = (c, client) => ({ p: c.p, n: gInc(c.n, client) });
const pnValue = (c) => gValue(c.p) - gValue(c.n);
const pnMerge = (a, b) => ({ p: gMerge(a.p, b.p), n: gMerge(a.n, b.n) });`;

