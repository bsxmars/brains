export const SEQ_CODE = `// Последовательность-CRDT в духе RGA. У каждого символа — id [client, clock]
// и origin: id соседа слева в момент вставки. clock — часы Лампорта.
function createDoc(client) {
  return { client, clock: 0, items: [], pending: [] };
}

const sameId = (a, b) => a[0] === b[0] && a[1] === b[1];
const indexOf = (doc, id) => doc.items.findIndex((it) => sameId(it.id, id));
const visible = (doc) => doc.items.filter((it) => !it.deleted);
const text = (doc) => visible(doc).map((it) => it.char).join('');

// Кто из двух id встаёт левее, если оба вставлены за одним соседом:
// больший clock (вставка видела больше), при равном — меньший client.
const goesFirst = (a, b) => (a[1] !== b[1] ? a[1] > b[1] : a[0] < b[0]);

function insert(doc, index, char) {
  const left = visible(doc)[index - 1];
  const op = { type: 'ins', id: [doc.client, doc.clock + 1], origin: left ? left.id : null, char };
  receive(doc, op);
  return op;
}

function remove(doc, index) {
  const op = { type: 'del', id: visible(doc)[index].id };
  receive(doc, op);
  return op;
}

// Применить свою или чужую операцию. Если ей не на что опереться
// (нет соседа слева или удаляемого символа), она ждёт в pending.
function receive(doc, op) {
  doc.pending.push(op);
  for (let i = 0; i < doc.pending.length; i++) {
    if (integrate(doc, doc.pending[i])) {
      doc.pending.splice(i, 1);
      i = -1;                       // применилась — пересмотреть ждущих
    }
  }
}

function integrate(doc, op) {
  if (op.type === 'del') {
    const i = indexOf(doc, op.id);
    if (i < 0) return false;
    doc.items[i].deleted = true;    // надгробие: символ остаётся в списке
    return true;
  }
  if (indexOf(doc, op.id) >= 0) return true;        // повтор — уже есть
  let i = op.origin ? indexOf(doc, op.origin) : -1;
  if (op.origin && i < 0) return false;             // соседа слева ещё нет
  i++;
  // Пропустить тех, кто встал за тем же соседом и идёт первым по правилу,
  // вместе с их «потомками»: у тех clock ещё больше.
  while (i < doc.items.length && goesFirst(doc.items[i].id, op.id)) i++;
  doc.items.splice(i, 0, { id: op.id, char: op.char, deleted: false });
  doc.clock = Math.max(doc.clock, op.id[1]);
  return true;
}`;

