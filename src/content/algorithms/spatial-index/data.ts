export const KNN_CODE = `// Квадрат расстояния от точки до прямоугольника: 0 внутри, иначе до ближайшей стороны или угла.
// Ни одна фигура внутри MBR не может быть ближе, чем сам MBR, — на этом держится весь поиск.
function boxDist(x, y, b) {
  const dx = Math.max(b.minX - x, 0, x - b.maxX);
  const dy = Math.max(b.minY - y, 0, y - b.maxY);
  return dx * dx + dy * dy;
}

// k ближайших: в одной очереди лежат и узлы, и фигуры, порядок — по расстоянию.
// Фигура, дошедшая до верха очереди, ближе всего, что ещё не раскрыто, — её можно отдавать.
function rKnn(tree, x, y, k, stats) {
  const queue = createHeap();
  queue.push(tree.root, 0);
  const found = [];
  while (queue.size() && found.length < k) {
    const { item, dist } = queue.pop();
    if (!item.children) { found.push({ id: item.id, dist }); continue; }
    stats.nodes.push(item);
    for (const c of item.children) {
      stats.checks++;
      queue.push(c, boxDist(x, y, c));
    }
  }
  return found;
}

// Двоичная куча на массиве: наверху — запись с наименьшим dist.
function createHeap() {
  const a = [];
  const less = (i, j) => a[i].dist < a[j].dist;
  const swap = (i, j) => { const t = a[i]; a[i] = a[j]; a[j] = t; };
  return {
    size: () => a.length,
    push(item, dist) {
      a.push({ item, dist });
      for (let i = a.length - 1; i > 0 && less(i, (i - 1) >> 1); i = (i - 1) >> 1) swap(i, (i - 1) >> 1);
    },
    pop() {
      const top = a[0], last = a.pop();
      if (a.length) {
        a[0] = last;
        for (let i = 0; ; ) {
          const l = 2 * i + 1, r = l + 1;
          let j = i;
          if (l < a.length && less(l, j)) j = l;
          if (r < a.length && less(r, j)) j = r;
          if (j === i) break;
          swap(i, j);
          i = j;
        }
      }
      return top;
    },
  };
}`;

