export const GRID_CODE = `// Равномерная сетка: поле режется на клетки cell × cell, у каждой — свой список.
// Прямоугольник на стыке клеток попадает в список каждой из них.
function buildGrid(shapes, cell) {
  const cols = Math.ceil(1000 / cell);
  const at = (v) => Math.min(cols - 1, Math.max(0, Math.floor(v / cell)));
  const buckets = Array.from({ length: cols * cols }, () => []);
  for (const s of shapes) {
    for (let cy = at(s.minY); cy <= at(s.maxY); cy++) {
      for (let cx = at(s.minX); cx <= at(s.maxX); cx++) buckets[cy * cols + cx].push(s);
    }
  }
  return { cell, cols, at, buckets };
}

// Клетки под рамкой находятся делением, без проверок. Проверяются только фигуры в них.
function gridSearch(grid, box, stats) {
  const { cell, cols, at, buckets } = grid;
  const seen = new Set();
  const found = [];
  for (let cy = at(box.minY); cy <= at(box.maxY); cy++) {
    for (let cx = at(box.minX); cx <= at(box.maxX); cx++) {
      stats.nodes.push({ minX: cx * cell, minY: cy * cell, maxX: (cx + 1) * cell, maxY: (cy + 1) * cell });
      for (const s of buckets[cy * cols + cx]) {
        if (seen.has(s.id)) continue;     // уже проверена в соседней клетке
        seen.add(s.id);
        stats.checks++;
        if (intersects(s, box)) found.push(s.id);
      }
    }
  }
  return found;
}`;

