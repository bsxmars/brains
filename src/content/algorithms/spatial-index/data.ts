export const RTREE_CODE = `// Упрощённое R-дерево: узел хранит до M детей и свой ограничивающий прямоугольник (MBR).
// В листе дети — фигуры, во внутреннем узле — другие узлы. Все листья на одной глубине.
const M = 9;   // как maxEntries по умолчанию в rbush
const m = 4;   // меньше m детей у нового узла быть не может

function createNode(children, leaf) {
  const node = { leaf, children, minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
  for (const c of children) extend(node, c);
  return node;
}
function extend(a, b) {
  a.minX = Math.min(a.minX, b.minX); a.minY = Math.min(a.minY, b.minY);
  a.maxX = Math.max(a.maxX, b.maxX); a.maxY = Math.max(a.maxY, b.maxY);
}
function area(a) {
  return (a.maxX - a.minX) * (a.maxY - a.minY);
}
// Площадь прямоугольника, который накрыл бы и a, и b.
function unionArea(a, b) {
  return (Math.max(a.maxX, b.maxX) - Math.min(a.minX, b.minX)) *
         (Math.max(a.maxY, b.maxY) - Math.min(a.minY, b.minY));
}

function createRTree() {
  return { root: createNode([], true) };
}

// Вставка: спуск туда, где рамка узла вырастет меньше всего; на равных — в меньший узел.
function rInsert(tree, item) {
  if (!tree.root.children.length) tree.root = createNode([], true);
  const path = [];
  let node = tree.root;
  for (;;) {
    path.push(node);
    extend(node, item);
    if (node.leaf) break;
    let best = null, bestGrow = Infinity, bestArea = Infinity;
    for (const c of node.children) {
      const a = area(c), grow = unionArea(c, item) - a;
      if (grow < bestGrow || (grow === bestGrow && a < bestArea)) {
        best = c; bestGrow = grow; bestArea = a;
      }
    }
    node = best;
  }
  node.children.push(item);
  // Переполненный узел делится надвое; родитель получает лишнего ребёнка и может переполниться сам.
  for (let i = path.length - 1; i >= 0 && path[i].children.length > M; i--) {
    const [a, b] = quadraticSplit(path[i]);
    if (i === 0) tree.root = createNode([a, b], false);
    else path[i - 1].children.splice(path[i - 1].children.indexOf(path[i]), 1, a, b);
  }
}

// Поиск рамкой: в поддерево заходим, только если его MBR задевает рамку.
// MBR соседей могут перекрываться — тогда заходить приходится в несколько.
function rSearch(node, box, found, stats) {
  stats.nodes.push(node);
  for (const c of node.children) {
    stats.checks++;
    if (!intersects(c, box)) continue;
    if (node.leaf) found.push(c.id);
    else rSearch(c, box, found, stats);
  }
  return found;
}`;

