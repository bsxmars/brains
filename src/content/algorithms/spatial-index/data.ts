export const REMOVE_CODE = `// Удаление: найти лист с этой фигурой, убрать её и подняться, пересчитывая рамки.
// Опустевший узел уходит из родителя. Недобор (меньше m детей) не чинится — как и в rbush.
function rRemove(tree, item) {
  const path = findLeaf(tree.root, item, []);
  if (!path) return false;
  const leaf = path[path.length - 1];
  leaf.children.splice(leaf.children.indexOf(item), 1);
  for (let i = path.length - 1; i >= 0; i--) {
    const node = path[i];
    if (!node.children.length && i > 0) {
      path[i - 1].children.splice(path[i - 1].children.indexOf(node), 1);
      continue;
    }
    const fresh = createNode(node.children, node.leaf);
    node.minX = fresh.minX; node.minY = fresh.minY; node.maxX = fresh.maxX; node.maxY = fresh.maxY;
  }
  return true;
}

// Фигуру ищут по ссылке и только там, где MBR узла целиком её накрывает.
function findLeaf(node, item, path) {
  path.push(node);
  if (node.leaf) {
    if (node.children.includes(item)) return path;
  } else {
    for (const c of node.children) {
      const covers = c.minX <= item.minX && c.minY <= item.minY && item.maxX <= c.maxX && item.maxY <= c.maxY;
      if (covers && findLeaf(c, item, path)) return path;
    }
  }
  path.pop();
  return null;
}

// Сдвиг: сначала удалить по старым координатам, потом поменять и вставить заново.
function rMove(tree, item, dx, dy) {
  rRemove(tree, item);
  item.minX += dx; item.maxX += dx;
  item.minY += dy; item.maxY += dy;
  rInsert(tree, item);
}`;

