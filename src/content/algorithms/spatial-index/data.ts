export const QUAD_CODE = `// Квадродерево для точек. Узел — квадрат; пока в нём не больше cap точек, он лист.
// Лишняя точка делит лист на четыре равных квадрата. maxDepth — предохранитель:
// глубже узел не делится, сколько бы точек в нём ни было.
function createQuad(minX, minY, size, depth) {
  return { minX, minY, maxX: minX + size, maxY: minY + size, size, depth, points: [], kids: null };
}

// Номер четверти: 0 — левая верхняя, 1 — правая верхняя, 2 и 3 — нижние.
function quarter(node, p) {
  const half = node.size / 2;
  return (p.minX >= node.minX + half ? 1 : 0) + (p.minY >= node.minY + half ? 2 : 0);
}

function quadInsert(node, p, cap, maxDepth) {
  while (node.kids) node = node.kids[quarter(node, p)];
  node.points.push(p);
  if (node.points.length > cap && node.depth < maxDepth) {
    const half = node.size / 2;
    const d = node.depth + 1;
    node.kids = [
      createQuad(node.minX, node.minY, half, d),
      createQuad(node.minX + half, node.minY, half, d),
      createQuad(node.minX, node.minY + half, half, d),
      createQuad(node.minX + half, node.minY + half, half, d),
    ];
    const moved = node.points;
    node.points = [];
    for (const q of moved) quadInsert(node, q, cap, maxDepth);
  }
}

// Поиск рамкой: в квадрат, который не задевает рамку, не заходим вовсе.
function quadSearch(node, box, found, stats) {
  stats.nodes.push(node);
  if (!node.kids) {
    for (const p of node.points) {
      stats.checks++;
      if (intersects(p, box)) found.push(p.id);
    }
    return found;
  }
  for (const kid of node.kids) {
    stats.checks++;
    if (intersects(kid, box)) quadSearch(kid, box, found, stats);
  }
  return found;
}`;

