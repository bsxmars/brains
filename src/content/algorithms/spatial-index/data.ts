export const SHAPES_CODE = `// Одно зерно — одни и те же фигуры в демо, в тесте и на стенде.
function mulberry32(seed) {
  return function () {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Поле 1000 × 1000. layout: 'uniform' — равномерно, 'clusters' — шесть сгустков,
// 'pile' — каждая вторая точка в одном и том же месте (500, 500).
// size = 0 — точки, иначе прямоугольники со сторонами от 2 до 2 + size.
function makeShapes(n, seed, layout, size) {
  const rnd = mulberry32(seed);
  const centers = [];
  for (let i = 0; i < 6; i++) centers.push([150 + rnd() * 700, 150 + rnd() * 700]);
  const clamp = (v) => Math.min(999, Math.max(0, v));
  const shapes = [];
  for (let id = 0; id < n; id++) {
    let x = rnd() * 1000;
    let y = rnd() * 1000;
    if (layout === 'clusters') {
      const [cx, cy] = centers[id % 6];
      x = clamp(cx + (rnd() + rnd() + rnd() - 1.5) * 60);
      y = clamp(cy + (rnd() + rnd() + rnd() - 1.5) * 60);
    }
    if (layout === 'pile' && id % 2 === 0) x = y = 500;
    const w = size ? 2 + rnd() * size : 0;
    const h = size ? 2 + rnd() * size : 0;
    shapes.push({ id, minX: x, minY: y, maxX: x + w, maxY: y + h });
  }
  return shapes;
}`;

export const BRUTE_CODE = `// Фигура и запрос — прямоугольники { minX, minY, maxX, maxY }; у точки min = max.
// Касание считается пересечением — так же, как в rbush и flatbush.
function intersects(a, b) {
  return a.minX <= b.maxX && b.minX <= a.maxX && a.minY <= b.maxY && b.minY <= a.maxY;
}

// Перебор: каждая фигура проверяется один раз. stats.checks — число проверок.
function bruteSearch(shapes, box, stats) {
  const found = [];
  for (const s of shapes) {
    stats.checks++;
    if (intersects(s, box)) found.push(s.id);
  }
  return found;
}`;

