export const SPLIT_CODE = `// Квадратичное разбиение Гуттмана: перебор всех пар детей — отсюда «квадратичное».
function quadraticSplit(node) {
  const rest = node.children.slice();
  // 1. Семена — пара, которая вместе накрыла бы больше всего пустоты.
  let s1 = 0, s2 = 1, worst = -Infinity;
  for (let i = 0; i < rest.length; i++) {
    for (let j = i + 1; j < rest.length; j++) {
      const waste = unionArea(rest[i], rest[j]) - area(rest[i]) - area(rest[j]);
      if (waste > worst) { worst = waste; s1 = i; s2 = j; }
    }
  }
  const a = createNode([rest[s1]], node.leaf);
  const b = createNode([rest[s2]], node.leaf);
  rest.splice(s2, 1);
  rest.splice(s1, 1);
  // 2. Остальные по одному: сперва тот, кому сильнее не всё равно, куда идти.
  while (rest.length) {
    if (a.children.length + rest.length === m) { for (const c of rest) { a.children.push(c); extend(a, c); } break; }
    if (b.children.length + rest.length === m) { for (const c of rest) { b.children.push(c); extend(b, c); } break; }
    let pick = 0, diff = -1;
    for (let i = 0; i < rest.length; i++) {
      const d = Math.abs((unionArea(a, rest[i]) - area(a)) - (unionArea(b, rest[i]) - area(b)));
      if (d > diff) { diff = d; pick = i; }
    }
    const c = rest.splice(pick, 1)[0];
    const ga = unionArea(a, c) - area(a), gb = unionArea(b, c) - area(b);
    const to = ga < gb || (ga === gb && area(a) <= area(b)) ? a : b;
    to.children.push(c);
    extend(to, c);
  }
  return [a, b];
}`;

