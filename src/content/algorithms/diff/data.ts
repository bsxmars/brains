export const LCS_CODE = `// t[i][j] — длина наибольшей общей подпоследовательности
// у первых i элементов a и первых j элементов b.
function lcsTable(a, b) {
  const t = [];
  for (let i = 0; i <= a.length; i++) t.push(new Array(b.length + 1).fill(0));
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      t[i][j] = a[i - 1] === b[j - 1]
        ? t[i - 1][j - 1] + 1                    // совпали — берём оба
        : Math.max(t[i - 1][j], t[i][j - 1]);    // иначе лучшее из двух
    }
  }
  return t;   // ответ — в правом нижнем углу: t[a.length][b.length]
}`;

