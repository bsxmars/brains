export const MYERS_CODE = `// Кратчайший скрипт правок: только «удалить» и «вставить».
// x — позиция в a, y — позиция в b, диагональ k = x − y.
function myers(a, b) {
  const n = a.length, m = b.length;
  const v = { 1: 0 };      // v[k] — самый дальний x на диагонали k
  const trace = [];        // trace[d] — снимок v после шага d
  for (let d = 0; d <= n + m; d++) {
    for (let k = -d; k <= d; k += 2) {
      // На диагональ k приходят сверху (вставка, с k + 1)
      // или слева (удаление, с k − 1) — берём того, кто ушёл дальше.
      const down = k === -d || (k !== d && v[k - 1] < v[k + 1]);
      let x = down ? v[k + 1] : v[k - 1] + 1;
      let y = x - k;
      // Змейка: пока элементы равны, идём по диагонали бесплатно.
      while (x < n && y < m && a[x] === b[y]) { x++; y++; }
      v[k] = x;
      if (x >= n && y >= m) {
        trace.push({ ...v });
        return { d, script: backtrack(trace, a, b), trace };
      }
    }
    trace.push({ ...v });
  }
}

// Обратный путь: из (n, m) к (0, 0) по снимкам v.
function backtrack(trace, a, b) {
  let x = a.length, y = b.length;
  const script = [];
  for (let d = trace.length - 1; d > 0; d--) {
    const v = trace[d - 1], k = x - y;     // v — каким он был перед шагом d
    const down = k === -d || (k !== d && v[k - 1] < v[k + 1]);
    const prevK = down ? k + 1 : k - 1;
    const prevX = v[prevK], prevY = prevX - prevK;
    while (x > prevX && y > prevY) { x--; y--; script.push(['=', a[x]]); }
    if (down) { y--; script.push(['+', b[y]]); }
    else { x--; script.push(['-', a[x]]); }
  }
  while (x > 0) { x--; script.push(['=', a[x]]); }   // начальная змейка
  return script.reverse();
}`;

