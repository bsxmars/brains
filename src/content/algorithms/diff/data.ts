export const LIS_CODE = `// Наибольшая возрастающая подпоследовательность за O(n log n).
// Возвращает индексы элементов arr, а не сами значения.
function lis(arr) {
  const tails = [];               // tails[len] — индекс наименьшего хвоста
                                  // цепочки длины len + 1
  const prev = new Array(arr.length);   // предшественник в цепочке
  for (let i = 0; i < arr.length; i++) {
    // двоичный поиск: первая цепочка, чей хвост не меньше arr[i]
    let lo = 0, hi = tails.length;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (arr[tails[mid]] < arr[i]) lo = mid + 1; else hi = mid;
    }
    if (lo > 0) prev[i] = tails[lo - 1];
    tails[lo] = i;                // arr[i] — новый, меньший хвост длины lo + 1
  }
  // Восстановить цепочку с конца по ссылкам prev.
  const seq = new Array(tails.length);
  for (let len = tails.length, i = tails.at(-1); len-- > 0; i = prev[i]) seq[len] = i;
  return seq;
}`;

