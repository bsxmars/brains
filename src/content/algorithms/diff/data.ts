export const VUE_MOVES_CODE = `// Какие узлы переставит Vue: края, затем LIS по середине.
// Ключи уникальны; возвращает ключи, которые двигаются, и новые.
function vueMoves(oldKeys, newKeys) {
  let i = 0, e1 = oldKeys.length - 1, e2 = newKeys.length - 1;
  while (i <= e1 && i <= e2 && oldKeys[i] === newKeys[i]) i++;       // с начала
  while (i <= e1 && i <= e2 && oldKeys[e1] === newKeys[e2]) e1--, e2--; // с конца
  const moved = [], mounted = [];
  // Середина: для каждого нового узла — его индекс в старом списке
  // (+1, чтобы 0 значил «узла не было»).
  const oldIndex = new Map(oldKeys.map((k, idx) => [k, idx]));
  const toOld = [];
  for (let j = i; j <= e2; j++) {
    const o = oldIndex.get(newKeys[j]);
    toOld.push(o === undefined ? 0 : o + 1);
  }
  // Кто в возрастающей цепочке старых индексов — стоит правильно.
  // Новые узлы (нули) в цепочку не берём: их всё равно вставлять.
  const old = [];
  toOld.forEach((o, j) => { if (o > 0) old.push(j); });
  const stay = new Set(lis(old.map((j) => toOld[j])).map((idx) => old[idx]));
  // Справа налево: якорь — уже поставленный правый сосед.
  for (let j = toOld.length - 1; j >= 0; j--) {
    const key = newKeys[i + j];
    if (toOld[j] === 0) mounted.push(key);
    else if (!stay.has(j)) moved.push(key);
  }
  return { moved, mounted };
}`;

export const REACT_MOVES_CODE = `// Какие узлы переставит React: один проход слева направо.
function reactMoves(oldKeys, newKeys) {
  const oldIndex = new Map(oldKeys.map((k, idx) => [k, idx]));
  let lastPlacedIndex = 0;       // самый правый старый индекс среди оставленных
  const moved = [], mounted = [];
  for (const key of newKeys) {
    const o = oldIndex.get(key);
    if (o === undefined) mounted.push(key);              // новый узел
    else if (o < lastPlacedIndex) moved.push(key);       // стоял левее — двигаем
    else lastPlacedIndex = o;                            // остаётся, отметка правее
  }
  return { moved, mounted };
}`;

