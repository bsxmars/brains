export const TINYLFU_CODE = `// W-TinyLFU, упрощённый. Три части, каждая — LRU на Map (от давнего к свежему):
// окно на 1 % места, «испытательная» и «защищённая» части основной памяти.
class WTinyLFU {
  constructor(max) {
    this.windowMax = Math.max(1, Math.round(max * 0.01));
    this.mainMax = max - this.windowMax;
    this.protectedMax = Math.round(this.mainMax * 0.8);
    this.window = new Map();
    this.probation = new Map(); // вошли в основную память, но ещё не доказали, что нужны
    this.protected = new Map(); // попадали, уже будучи в основной памяти
    this.sketch = new CountMinSketch(max * 16, max * 10);
  }

  get(key) {
    this.sketch.increment(key); // считаем каждое обращение: и попадание, и промах
    if (this.window.has(key)) return touch(this.window, key);
    if (this.protected.has(key)) return touch(this.protected, key);
    if (!this.probation.has(key)) return undefined;
    const value = this.probation.get(key); // второе попадание: повышение
    this.probation.delete(key);
    this.protected.set(key, value);
    if (this.protected.size > this.protectedMax) {
      const [demoted, v] = this.protected.entries().next().value;
      this.protected.delete(demoted); // давний из защищённых — обратно на испытание
      this.probation.set(demoted, v);
    }
    return value;
  }

  set(key, value) {
    for (const part of [this.window, this.probation, this.protected]) {
      if (part.has(key)) { part.set(key, value); touch(part, key); return; }
    }
    this.window.set(key, value); // новичок всегда входит через окно
    if (this.window.size <= this.windowMax) return;

    const [candidate, candidateValue] = this.window.entries().next().value;
    this.window.delete(candidate); // выпал из окна — просится в основную память
    if (this.probation.size + this.protected.size < this.mainMax) {
      this.probation.set(candidate, candidateValue);
      return;
    }
    const pool = this.probation.size > 0 ? this.probation : this.protected;
    const victim = pool.keys().next().value; // кого вытеснил бы LRU
    // Допуск: кандидат входит, только если его спрашивали чаще, чем жертву.
    if (this.sketch.estimate(candidate) > this.sketch.estimate(victim)) {
      pool.delete(victim);
      this.probation.set(candidate, candidateValue);
    }
    // иначе уходит сам кандидат, а основная память не тронута
  }
}

// Переставить ключ в конец своей части и вернуть значение.
function touch(part, key) {
  const value = part.get(key);
  part.delete(key);
  part.set(key, value);
  return value;
}`;

