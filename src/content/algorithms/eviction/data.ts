export const PLAIN_LRU =
  'Как стопка книг на столе. Взяли книгу — положили сверху. Нужно место — убрали нижнюю: её дольше всех не трогали. LRU (least recently used, «давно не использованный») ставит на то, что недавнее прошлое похоже на ближайшее будущее.';

export const LRU_CODE = `// LRU на Map. Map помнит порядок вставки: первый ключ — самый давний.
class LRU {
  constructor(max, { ttl = 0, now = () => performance.now() } = {}) {
    this.max = max;
    this.ttl = ttl; // 0 — без срока
    this.now = now;
    this.map = new Map(); // key → { value, start }
    this.oldest = this.map.keys(); // один итератор на всю жизнь кеша
  }

  get(key) {
    const entry = this.map.get(key);
    if (entry === undefined) return undefined;
    this.map.delete(key); // вынуть из середины порядка
    if (this.isStale(entry)) return undefined; // протухла: удалена, ответ «нет»
    this.map.set(key, entry); // вернуть в конец — теперь самая свежая
    return entry.value;
  }

  set(key, value) {
    this.map.delete(key);
    this.map.set(key, { value, start: this.now() });
    if (this.map.size > this.max) {
      // Итератор стоит за последним вытесненным: всё живое — впереди него,
      // и первый живой ключ — самый давний.
      this.map.delete(this.oldest.next().value);
    }
  }

  isStale(entry) {
    return this.ttl > 0 && this.now() - entry.start > this.ttl;
  }
}`;

