export const SIEVE_CODE = `// SIEVE (NSDI 2024): очередь без перестановок, бит «спрашивали» и стрелка.
class Sieve {
  constructor(max) {
    this.max = max;
    this.map = new Map(); // key → узел
    this.head = null; // новые входят в голову
    this.tail = null; // старые копятся у хвоста
    this.hand = null; // стрелка: где продолжить поиск жертвы
  }

  get(key) {
    const node = this.map.get(key);
    if (node === undefined) return undefined;
    node.visited = true; // попадание ничего не двигает — только ставит бит
    return node.value;
  }

  set(key, value) {
    const node = this.map.get(key);
    if (node) { node.value = value; node.visited = true; return; }
    if (this.map.size >= this.max) this.evict();
    const fresh = { key, value, visited: false, prev: null, next: this.head };
    if (this.head) this.head.prev = fresh;
    this.head = fresh;
    if (!this.tail) this.tail = fresh;
    this.map.set(key, fresh);
  }

  evict() {
    let node = this.hand ?? this.tail; // стрелка идёт от хвоста к голове
    while (node.visited) {
      node.visited = false; // второй шанс сгорел
      node = node.prev ?? this.tail; // дошли до головы — снова с хвоста
    }
    this.hand = node.prev; // в следующий раз — с этого места
    this.unlink(node);
    this.map.delete(node.key);
  }

  unlink(node) {
    if (node.prev) node.prev.next = node.next; else this.head = node.next;
    if (node.next) node.next.prev = node.prev; else this.tail = node.prev;
  }
}`;

