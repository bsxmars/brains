export const LFU_CODE = `// LFU за O(1): ключи разложены по корзинам частот.
class LFU {
  constructor(max) {
    this.max = max;
    this.values = new Map(); // key → value
    this.counts = new Map(); // key → сколько раз спрашивали
    this.buckets = new Map(); // частота → { keys: Set от давнего к свежему, oldest: итератор }
    this.minFreq = 0; // частота самой «бедной» непустой корзины
  }

  get(key) {
    if (!this.values.has(key)) return undefined;
    this.bump(key);
    return this.values.get(key);
  }

  set(key, value) {
    if (this.values.has(key)) {
      this.values.set(key, value);
      this.bump(key);
      return;
    }
    if (this.values.size >= this.max) this.evict();
    this.values.set(key, value);
    this.counts.set(key, 1);
    this.bucket(1).keys.add(key);
    this.minFreq = 1; // новичок всегда самый редкий
  }

  // Переложить ключ из корзины f в корзину f + 1.
  bump(key) {
    const f = this.counts.get(key);
    this.take(f, key);
    if (this.minFreq === f && !this.buckets.has(f)) this.minFreq = f + 1;
    this.counts.set(key, f + 1);
    this.bucket(f + 1).keys.add(key);
  }

  // Самый редкий, а среди равных — самый давний.
  evict() {
    const victim = this.buckets.get(this.minFreq).oldest.next().value;
    this.take(this.minFreq, victim);
    this.values.delete(victim);
    this.counts.delete(victim);
  }

  take(f, key) {
    const b = this.buckets.get(f);
    b.keys.delete(key);
    if (b.keys.size === 0) this.buckets.delete(f); // пустая корзина не нужна
  }

  bucket(f) {
    if (!this.buckets.has(f)) {
      const keys = new Set();
      this.buckets.set(f, { keys, oldest: keys.values() }); // итератор — как в LRU
    }
    return this.buckets.get(f);
  }
}`;

export const LFU_NOTE =
  'Наивный LFU ищет минимум частоты перебором — `O(n)` на каждое вытеснение. Здесь перебора нет, потому что частоты меняются только на единицу. Новый ключ всегда попадает в корзину 1, и `minFreq` становится 1. Попадание перекладывает ключ из корзины `f` в `f + 1`, и минимум может сдвинуться только на ту же единицу. Жертва — первый ключ самой бедной корзины. Внутри корзины порядок вставки делает её маленьким LRU: из равных по частоте уходит самый давний. У каждой корзины свой итератор — по той же причине, что в LRU. Схема описана в статье Шаха, Митры и Матани (2010); там вместо `Set` двусвязные списки.';

