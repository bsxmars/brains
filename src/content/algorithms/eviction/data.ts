export const TRACE_CODE = `// Генератор с зерном: одна и та же трасса при каждом запуске.
function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Закон Ципфа: ключ номер k спрашивают пропорционально 1 / (k + 1)^s.
function zipf(keys, s, random) {
  const cdf = [];
  let sum = 0;
  for (let k = 1; k <= keys; k++) cdf.push((sum += 1 / k ** s));
  return () => {
    const x = random() * sum;
    let lo = 0, hi = keys - 1;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (cdf[mid] < x) lo = mid + 1; else hi = mid;
    }
    return lo;
  };
}

function makeTrace(kind, { length = 20000, seed = 1, keys = 1000, s = 0.9, loop = 120, burst = 1500 } = {}) {
  const pick = zipf(keys, s, mulberry32(seed));
  const trace = [];
  let fresh = 1e6; // ключи, которых больше никто не спросит
  while (trace.length < length) {
    const i = trace.length;
    if (kind === 'zipf') trace.push(pick());
    if (kind === 'loop') trace.push(i % loop); // по кругу, чуть больше кеша
    if (kind === 'shift') trace.push(pick() + (i < length / 2 ? 0 : keys)); // горячее сменилось
    if (kind === 'scan') {
      // 2500 обычных запросов, затем проход по 1500 новым ключам
      if (i % (2500 + burst) < 2500) trace.push(pick());
      else trace.push(fresh++);
    }
  }
  return trace;
}

function simulate(cache, trace, windows = 40) {
  const size = Math.ceil(trace.length / windows);
  const curve = [];
  let hits = 0, windowHits = 0;
  trace.forEach((key, i) => {
    if (cache.get(key) !== undefined) { hits++; windowHits++; }
    else cache.set(key, key); // промах: «сходили в источник» и положили
    if ((i + 1) % size === 0 || i === trace.length - 1) {
      curve.push(windowHits / ((i % size) + 1));
      windowHits = 0;
    }
  });
  return { hitRate: hits / trace.length, curve };
}`;

