export const SKETCH_CODE = `// Count-min sketch: d строк по w счётчиков по 4 бита (0…15).
// Ключ попадает в одну ячейку каждой строки; оценка — минимум по строкам.
class CountMinSketch {
  constructor(width, sampleSize, depth = 4) {
    this.bits = Math.ceil(Math.log2(width)); // ширина — степень двойки
    this.rows = Array.from({ length: depth }, () => new Uint8Array(2 ** this.bits));
    this.sampleSize = sampleSize; // после стольких добавлений — сброс
    this.additions = 0;
  }

  index(key, row) {
    let h = 0x811c9dc5; // FNV-1a по строке ключа
    const s = String(key);
    for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193);
    h = Math.imul(h ^ (h >>> 16), SEEDS[row]); // своя «соль» у каждой строки
    return (h ^ (h >>> 13)) >>> (32 - this.bits);
  }

  estimate(key) {
    let min = 15;
    this.rows.forEach((row, r) => { min = Math.min(min, row[this.index(key, r)]); });
    return min;
  }

  increment(key) {
    let added = false;
    this.rows.forEach((row, r) => {
      const i = this.index(key, r);
      if (row[i] < 15) { row[i]++; added = true; }
    });
    if (added && ++this.additions >= this.sampleSize) this.reset();
  }

  // Старение: все счётчики пополам. Старая слава тает, новая успевает её догнать.
  reset() {
    for (const row of this.rows) for (let i = 0; i < row.length; i++) row[i] >>= 1;
    this.additions = Math.floor(this.additions / 2);
  }
}

const SEEDS = [0x9e3779b1, 0x85ebca6b, 0xc2b2ae35, 0x27d4eb2f];`;

