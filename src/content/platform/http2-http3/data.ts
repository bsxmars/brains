export const QUIC_CODE = `// RFC 9000 §16: длину числа задают два старших бита первого байта —
// 00 → 1 байт, 01 → 2, 10 → 4, 11 → 8. Остальные биты — само число.
function readVarint(b, at) {
  const len = 2 ** (b[at] >> 6);
  let value = b[at] & 0x3f;
  for (let i = 1; i < len; i++) value = value * 256 + b[at + i];
  return [value, at + len];
}

const LONG_TYPES = ['Initial', '0-RTT', 'Handshake', 'Retry'];
const toHex = (bytes) => bytes.map((x) => x.toString(16).padStart(2, '0')).join('');

// Длинный заголовок (RFC 9000 §17.2) — у пакетов рукопожатия.
// Номер пакета и младшие 4 бита первого байта зашифрованы, их не читаем.
function readLongHeader(b) {
  let at = 5;
  const dcid = b.slice(at + 1, at + 1 + b[at]);
  at += 1 + b[at];
  const scid = b.slice(at + 1, at + 1 + b[at]);
  at += 1 + b[at];
  const type = LONG_TYPES[(b[0] >> 4) & 3];
  let tokenLength = 0, length;
  if (type === 'Initial') [tokenLength, at] = readVarint(b, at);
  at += tokenLength;
  [length, at] = readVarint(b, at);       // номер пакета + зашифрованные данные
  return {
    long: (b[0] & 0x80) !== 0,
    type,
    version: b[1] * 2 ** 24 + b[2] * 65536 + b[3] * 256 + b[4],
    dcid: toHex(dcid),
    scid: toHex(scid),
    tokenLength,
    length,
    headerBytes: at,
  };
}`;

