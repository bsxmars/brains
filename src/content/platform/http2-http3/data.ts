// следующими байтами по 7 бит, старший бит — «дальше ещё байт».
function encodeInt(value, n, high = 0) {
  const max = 2 ** n - 1;
  if (value < max) return [high | value];
  const out = [high | max];
  value -= max;
  while (value >= 128) {
    out.push((value % 128) + 128);
    value = Math.floor(value / 128);
  }
  out.push(value);
  return out;
}

