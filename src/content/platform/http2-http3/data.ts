export const FRAME_CODE = `const FRAME_TYPES = ['DATA', 'HEADERS', 'PRIORITY', 'RST_STREAM', 'SETTINGS',
  'PUSH_PROMISE', 'PING', 'GOAWAY', 'WINDOW_UPDATE', 'CONTINUATION'];

// Заголовок кадра — всегда 9 байт:
// длина (3 байта) · тип (1) · флаги (1) · бит R + номер потока (31 бит)
function readFrameHeader(b, at) {
  return {
    length: b[at] * 65536 + b[at + 1] * 256 + b[at + 2],
    type: FRAME_TYPES[b[at + 3]] ?? 'UNKNOWN',
    flags: b[at + 4],
    stream: (b[at + 5] & 0x7f) * 2 ** 24 + b[at + 6] * 65536 + b[at + 7] * 256 + b[at + 8],
  };
}

// Поток байтов одной стороны → кадры. Клиент сначала шлёт
// 24-байтовое приветствие «PRI * HTTP/2.0…», его пропускаем.
const PREFACE = 'PRI * HTTP/2.0\\r\\n\\r\\nSM\\r\\n\\r\\n';

function splitFrames(b) {
  let at = String.fromCharCode(...b.slice(0, 24)) === PREFACE ? 24 : 0;
  const frames = [];
  while (at + 9 <= b.length) {
    const h = readFrameHeader(b, at);
    frames.push({ ...h, at, payload: b.slice(at + 9, at + 9 + h.length) });
    at += 9 + h.length;
  }
  return frames;
}

const u32 = (p, i) => p[i] * 2 ** 24 + p[i + 1] * 65536 + p[i + 2] * 256 + p[i + 3];
const SETTINGS = ['', 'HEADER_TABLE_SIZE', 'ENABLE_PUSH', 'MAX_CONCURRENT_STREAMS',
  'INITIAL_WINDOW_SIZE', 'MAX_FRAME_SIZE', 'MAX_HEADER_LIST_SIZE'];

// Что лежит в теле служебных кадров.
function readPayload(f) {
  const p = f.payload;
  if (f.type === 'SETTINGS') {
    const out = [];
    for (let i = 0; i + 6 <= p.length; i += 6) {
      const id = p[i] * 256 + p[i + 1];
      out.push([SETTINGS[id] || \`0x\${id.toString(16)}\`, u32(p, i + 2)]);
    }
    return { ack: (f.flags & 1) === 1, settings: out };
  }
  if (f.type === 'WINDOW_UPDATE') return { increment: u32(p, 0) % 2 ** 31 };
  if (f.type === 'RST_STREAM') return { error: u32(p, 0) };
  if (f.type === 'GOAWAY') return { lastStream: u32(p, 0) % 2 ** 31, error: u32(p, 4) };
  return {};
}

// Где в кадре блок HPACK. Перед ним бывают: длина дополнения (флаг 0x8),
// 5 байт приоритета (HEADERS с флагом 0x20), номер обещанного потока
// (PUSH_PROMISE, 4 байта). В конце — само дополнение.
function headerBlockOf(f) {
  let p = f.payload, pad = 0;
  if (f.flags & 0x08) { pad = p[0]; p = p.slice(1); }
  if (f.type === 'HEADERS' && f.flags & 0x20) p = p.slice(5);
  if (f.type === 'PUSH_PROMISE') p = p.slice(4);
  return p.slice(0, p.length - pad);
}`;

