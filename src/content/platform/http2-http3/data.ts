export const HPACK_DECODE_CODE = `// Хаффман (RFC 7541, приложение B): частым символам — короткие коды.
// Код канонический: коды одной длины идут подряд по порядку символов,
// поэтому таблицу восстанавливает список «какие символы какой длины».
// Здесь длины 5–15 бит: весь печатный ASCII, кроме «\\». Остальные
// байты (и «\\») кодируются 19–30 битами — в примере их нет.
const HUFFMAN_BY_LENGTH = {
  5: '012aceiost', 6: ' %-./3456789=A_bdfghlmnpru',
  7: ':BCDEFGHIJKLMNOPQRSTUVWYjkqvwxyz', 8: '&*,;XZ',
  10: '!"()?', 11: "'+|", 12: '#>', 13: '\\0$@[]~', 14: '^}', 15: '<\`{',
};
const HUFFMAN = new Map();                    // «длина:код» → символ
let nextCode = 0, prevLen = 5;
for (const [len, chars] of Object.entries(HUFFMAN_BY_LENGTH)) {
  nextCode *= 2 ** (len - prevLen);
  prevLen = Number(len);
  for (const ch of chars) HUFFMAN.set(\`\${len}:\${nextCode++}\`, ch);
}

function decodeHuffman(bytes) {
  let out = '', code = 0, len = 0;
  for (const byte of bytes) {
    for (let bit = 7; bit >= 0; bit--) {
      code = code * 2 + ((byte >> bit) & 1);
      len++;
      const ch = HUFFMAN.get(\`\${len}:\${code}\`);
      if (ch !== undefined) { out += ch; code = 0; len = 0; }
      else if (len > 15) throw new Error('символ вне таблицы примера');
    }
  }
  // Хвост — до семи единиц: начало кода конца строки (EOS).
  if (len > 7 || code !== 2 ** len - 1) throw new Error('неверное дополнение');
  return out;
}

// Строка: бит H (Хаффман или нет) + длина 7-битным префиксом + байты.
function decodeString(b, at) {
  const huffman = (b[at] & 0x80) !== 0;
  let len;
  [len, at] = decodeInt(b, at, 7);
  const raw = b.slice(at, at + len);
  const text = huffman ? decodeHuffman(raw) : String.fromCharCode(...raw);
  return [text, at + len, huffman];
}

// Блок заголовков → поля. Первые биты байта говорят, что за запись.
function decodeHeaderBlock(b, table) {
  const fields = [];
  for (let at = 0; at < b.length; ) {
    const start = at, first = b[at];
    if ((first & 0xe0) === 0x20) {            // 001xxxxx — новый размер таблицы
      [table.maxSize, at] = decodeInt(b, at, 5);
      evict(table);
      fields.push({ kind: 'size', size: table.maxSize, bytes: [start, at] });
      continue;
    }
    const f = { kind: 'indexed', index: 0, name: '', value: '' };
    if (first & 0x80) {                       // 1xxxxxxx — запись таблицы целиком
      [f.index, at] = decodeInt(b, at, 7);
      [f.name, f.value] = entryAt(table, f.index);
    } else {
      // 01xxxxxx — литерал, который запомнят обе стороны;
      // 0001xxxx — «никогда не запоминать»; 0000xxxx — просто литерал.
      f.kind = first & 0x40 ? 'incremental' : first & 0x10 ? 'never' : 'literal';
      [f.index, at] = decodeInt(b, at, first & 0x40 ? 6 : 4);
      if (f.index) f.name = entryAt(table, f.index)[0];
      else [f.name, at, f.nameHuffman] = decodeString(b, at);
      [f.value, at, f.valueHuffman] = decodeString(b, at);
      if (f.kind === 'incremental') addEntry(table, f.name, f.value);
    }
    f.bytes = [start, at];
    fields.push(f);
  }
  return fields;
}`;

