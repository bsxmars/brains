/* ──────────────────── Раздел 4 · политика изоляции ресурсов ──────────────────── */

/**
 * Серверная политика изоляции ресурсов (Resource Isolation Policy) по web.dev.
 *
 * ⚠️ Это **исполняемый** код, а не иллюстрация: его печатает тема, его же компилирует демо
 * (`widgets/fetch-metadata-policy`) и его же гоняет `tests/unit/xs-leaks.test.ts`. На стенде
 * та же строка стояла перед ответами сервера и решала по заголовкам, которые прислал
 * настоящий Chromium. Поэтому здесь чистый JS без типов: `new Function` его понимает как есть.
 */
export const RIP_CODE = `// Адреса, которые задуманы для чужих сайтов: виджет, OAuth, картинки для писем.
const PUBLIC_PATHS = ['/embed/', '/.well-known/'];

// req: { method, path, headers } — имена заголовков в нижнем регистре, как в Node.
function isolationPolicy(req) {
  const site = req.headers['sec-fetch-site'];
  const mode = req.headers['sec-fetch-mode'];
  const dest = req.headers['sec-fetch-dest'];

  // (1) Заголовков нет: старый браузер, не браузер вовсе — или сайт на http.
  if (site === undefined) return { allow: true, rule: 'no-metadata' };

  // (2) Свой источник, свой сайт или адрес, набранный руками.
  if (site === 'same-origin' || site === 'same-site' || site === 'none') {
    return { allow: true, rule: 'own-site' };
  }

  // (3) Чужой сайт, но это переход: ссылка, закладка, фрейм. Не <object> и не <embed>.
  if (mode === 'navigate' && req.method === 'GET' && dest !== 'object' && dest !== 'embed') {
    return { allow: true, rule: 'navigation' };
  }

  // (4) Сознательно открытые адреса.
  if (PUBLIC_PATHS.some((prefix) => req.path.startsWith(prefix))) {
    return { allow: true, rule: 'public-path' };
  }

  // (5) Всё остальное с чужого сайта: картинки, скрипты, fetch, POST-формы.
  return { allow: false, rule: 'cross-site' };
}`;

