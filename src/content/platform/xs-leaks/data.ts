/**
 * Данные темы «XS-Leaks: как чужой сайт узнаёт о вас, ничего не прочитав».
 *
 * Тема написана здесь. До неё предмет занимал одну карточку в «Безопасности фронтенда»
 * («Побочные каналы», раздел «Origin и правило одного источника») и строку «отдельная тема»
 * в её «за кадром». SOP, CORS, SameSite, кликджекинг и базовые заголовки разобраны там
 * и здесь не повторяются; Resource Timing и `Timing-Allow-Origin` — в «Сети и кешировании»,
 * ORB и граница сайта — в «Устройстве браузера». Сюда вынесено то, чего там нет: чем
 * утечка одного бита отличается от чтения ответа и какой механизм закрывает какой канал.
 *
 * ── Что тема сознательно НЕ делает ───────────────────────────────────────────────────────
 * Классы утечек описаны словами: какой бит утекает и что его закрывает. Воспроизведений
 * утечек на стенде нет — ни в демо, ни в проверках. Контроль «работает / не работает» снят
 * на поведении самих защитных заголовков: с заголовком и без него, на одном и том же стенде.
 *
 * ── Стенд (сентябрь 2026) ────────────────────────────────────────────────────────────────
 * Chromium **153.0.8010.12** (Playwright 1.63, headless), свой `node:https` на 49431
 * с самоподписанным сертификатом и `node:http` на 49432, Node 26.8.2. Три хоста —
 * `a.test`, `sub.a.test`, `b.test` — через `--host-resolver-rules=MAP *.test 127.0.0.1`:
 * два порта на `localhost` дали бы cross-origin, но same-site, и кросс-сайтового поведения
 * на них не увидеть. `a.test` и `sub.a.test` — один сайт, `b.test` — чужой.
 * Сервер пишет в журнал `Sec-Fetch-*` каждого запроса; ни одного таймерного замера.
 *
 *   (1) Fetch Metadata — таблица `SEC_FETCH_ROWS`, двенадцать запросов по https. Тот же
 *       сценарий по **http**: 12 из 12 запросов пришли **без единого** `Sec-Fetch-*` —
 *       заголовки шлются только потенциально доверенным источникам (`HTTP_NOTE`).
 *   (1b) `RIP_CODE` стоял перед ответами сервера и решал по заголовкам настоящего браузера:
 *       картинка `/avatar.png` на странице `b.test` — 403 и `onerror`; `/embed/logo.png`
 *       там же — `load`; ссылка с `b.test` — страница открылась; та же картинка на своей
 *       странице — `load`; по http — `load` веткой «заголовков нет» (`RIP_STAND`).
 *   (2) CORP — `CORP_ROWS`: `<img>` и `fetch(…, { mode: 'no-cors' })` с каждой страницы.
 *   (3) COOP — `COOP_ROWS`: `window.opener` в открытом окне и `closed` у ссылки на него.
 *   (4) `frame-ancestors` и `X-Frame-Options` — `FRAME_ROWS`: «показан» значит, что скрипт
 *       внутри фрейма выполнился и дошёл до сервера запросом; «запрос дошёл» — что сервер
 *       получил сам запрос документа. Отрицательный случай ждёт факта с потолком 1.5 с —
 *       это предел ожидания, а не замер.
 *
 * ── Что по источникам, без запуска ───────────────────────────────────────────────────────
 * Разделение HTTP-кеша по сайту верхнего уровня (Chrome Developers, «Gaining security and
 * privacy by partitioning the cache»; Chromium 86+) — стендом не проверялось: проверка
 * требовала бы пробы кеша. `Vary` на ответах политики и режим «сначала только журнал» —
 * рекомендации web.dev, а не замер. Firefox и WebKit не снимались.
 */

