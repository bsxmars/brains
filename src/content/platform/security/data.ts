export const SERVER_CODE = `func withCORS(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		origin := r.Header.Get("Origin")
		h := w.Header()

		// (1) Vary ставится ВСЕГДА — даже когда origin не подошёл и
		//     Allow-Origin мы не выставим. Иначе прокси закэширует
		//     «ответ без CORS-заголовков» и раздаст его всем.
		h.Add("Vary", "Origin")

		// (2) Точное сравнение по конечному списку. Не префикс, не regexp,
		//     не HasSuffix. Пустой Origin сюда НЕ попадает.
		if _, ok := allowedOrigins[origin]; ok && origin != "" {
			h.Set("Access-Control-Allow-Origin", origin) // никогда "*"
			h.Set("Access-Control-Allow-Credentials", "true")
			h.Set("Access-Control-Expose-Headers", "X-Request-Id")
		}

		// (3) Признак preflight — метод OPTIONS И Access-Control-Request-Method.
		if r.Method == http.MethodOptions && r.Header.Get("Access-Control-Request-Method") != "" {
			h.Add("Vary", "Access-Control-Request-Method")
			h.Add("Vary", "Access-Control-Request-Headers")
			h.Set("Access-Control-Allow-Methods", "GET, POST, PATCH, DELETE")
			h.Set("Access-Control-Allow-Headers", "Content-Type, Authorization, X-CSRF-Token")
			h.Set("Access-Control-Max-Age", "600")
			w.WriteHeader(http.StatusNoContent)
			return // дальше по цепочке не идём: бизнес-логика вернула бы 405
		}

		next.ServeHTTP(w, r)
	})
}`;

