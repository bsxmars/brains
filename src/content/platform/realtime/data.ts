export const FRAME_CODE = `// frame.js — кадр WebSocket по RFC 6455, §5.2. Только Uint8Array: работает и в Node, и в браузере
export const OP = { continuation: 0x0, text: 0x1, binary: 0x2, close: 0x8, ping: 0x9, pong: 0xa };

export function encodeFrame({ opcode, payload, mask = null, fin = true }) {
  const len = payload.length;
  const ext = len < 126 ? 0 : len < 65536 ? 2 : 8;       // сколько байт займёт длина
  const head = new Uint8Array(2 + ext + (mask ? 4 : 0));
  head[0] = (fin ? 0x80 : 0) | opcode;                    // FIN и опкод
  head[1] = (mask ? 0x80 : 0) | (ext === 0 ? len : ext === 2 ? 126 : 127);
  if (ext === 2) new DataView(head.buffer).setUint16(2, len);
  if (ext === 8) new DataView(head.buffer).setBigUint64(2, BigInt(len));
  if (mask) head.set(mask, 2 + ext);                      // четыре байта маски
  const frame = new Uint8Array(head.length + len);
  frame.set(head);
  for (let i = 0; i < len; i++) {
    frame[head.length + i] = mask ? payload[i] ^ mask[i % 4] : payload[i];
  }
  return frame;
}

/** Разбирает кадр с начала буфера; \`null\` — кадр пришёл не целиком, ждём ещё байты. */
export function decodeFrame(bytes) {
  if (bytes.length < 2) return null;
  const fin = (bytes[0] & 0x80) !== 0;
  const opcode = bytes[0] & 0x0f;
  const masked = (bytes[1] & 0x80) !== 0;
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.length);
  let len = bytes[1] & 0x7f;
  let at = 2;
  if (len === 126) {
    if (bytes.length < 4) return null;
    len = view.getUint16(2);
    at = 4;
  } else if (len === 127) {
    if (bytes.length < 10) return null;
    len = Number(view.getBigUint64(2));
    at = 10;
  }
  if (bytes.length < at + (masked ? 4 : 0) + len) return null;
  const mask = masked ? bytes.slice(at, at + 4) : null;
  if (masked) at += 4;
  const payload = new Uint8Array(len);
  for (let i = 0; i < len; i++) payload[i] = mask ? bytes[at + i] ^ mask[i % 4] : bytes[at + i];
  return { fin, opcode, masked, mask, payload, size: at + len };
}

/** Тело кадра close: код — два байта, следом причина в UTF-8. */
export function closePayload(code, reason = '') {
  const text = new TextEncoder().encode(reason);
  const out = new Uint8Array(2 + text.length);
  new DataView(out.buffer).setUint16(0, code);
  out.set(text, 2);
  return out;
}

export function readClose(payload) {
  if (payload.length < 2) return { code: 1005, reason: '' };  // 1005: кода в кадре не было
  const code = (payload[0] << 8) | payload[1];
  return { code, reason: new TextDecoder().decode(payload.subarray(2)) };
}`;

