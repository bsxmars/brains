export const CLIENT_CODE = `// client.js — переподключение: экспонента, полный джиттер и heartbeat
export function nextDelay(attempt, { base = 500, cap = 30_000, random = Math.random } = {}) {
  const ceiling = Math.min(cap, base * 2 ** attempt);   // 0,5 с → 1 с → 2 с … но не выше cap
  return Math.floor(random() * ceiling);                // полный джиттер: где угодно от 0 до потолка
}

export function connect(url, { onMessage, beat = 25_000, grace = 10_000, ...backoff } = {}) {
  let ws, attempt = 0, stopped = false, retry, heartbeat, waiting;

  function open() {
    const socket = (ws = new WebSocket(url));
    socket.onopen = () => {
      heartbeat = setInterval(() => {
        socket.send('ping');                            // ping-кадра в браузерном API нет
        waiting ??= setTimeout(() => drop(socket, 4000), grace);
      }, beat);
    };
    socket.onmessage = (e) => {
      attempt = 0;                                      // сервер отвечает — счёт попыток заново
      if (e.data === 'pong') {
        clearTimeout(waiting);
        waiting = undefined;
        return;
      }
      onMessage?.(e.data);
    };
    socket.onclose = (e) => drop(socket, e.code);
  }

  function drop(socket, code) {
    if (socket !== ws) return;                          // этот сокет уже заменён
    clearInterval(heartbeat);
    clearTimeout(waiting);
    waiting = ws = undefined;
    socket.onclose = socket.onmessage = null;           // close немого сервера не ждём:
    if (socket.readyState === WebSocket.OPEN) socket.close(code);  // он придёт нескоро или никогда
    if (stopped || code === 4401) return;               // выключили сами / сервер: «не возвращайся»
    retry = setTimeout(open, nextDelay(attempt++, backoff));
  }

  open();
  return {
    send: (data) => ws?.send(data),
    stop() {
      stopped = true;
      clearTimeout(retry);
      ws?.close(1000);
    },
  };
}`;

