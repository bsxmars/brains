/**
 * Данные темы «Docker Compose: несколько сервисов».
 *
 * Конспекта-источника у темы нет: материал собран здесь, и потому правило проекта работает
 * в полную силу — **каждое число снято прогоном, а не вспомнено**.
 *
 * ГДЕ СНЯТО. Docker Engine 27.4.0, Docker Compose v2.31.0-desktop.2, macOS (arm64).
 * Образы: `postgres:16-alpine` (PostgreSQL 16.15), `redis:7-alpine` (Redis 7.4.11),
 * `nginx:alpine`. Все проекты назывались с префиксом `lesson-compose-` и убраны
 * командой `docker compose -p <проект> down -v` сразу после замеров.
 *
 * ЧТО СНЯТО И ГДЕ ЛЕЖИТ ЗАПИСЬ.
 *
 *  1. Два прогона одного стека (веб-приложение + база + кеш) на **пустом томе**, отличающиеся
 *     одной строкой в `depends_on`. Запись — вывод
 *     `docker events --format '{{.TimeNano}};{{index .Actor.Attributes "com.docker.compose.service"}};{{.Action}}'`
 *     и логи самих процессов; лежит в `tests/fixtures/compose/`, разбирается
 *     `tests/unit/compose.test.ts`. Числа ниже — из этой записи, а не из памяти.
 *  2. Разрешение имён, порты, слои конфигурации, тома и перезапуски — проект
 *     `lesson-compose-c` и соседние; вывод каждой команды приведён в соответствующих
 *     константах дословно.
 *
 * ВТОРОЙ ПРОХОД: ЧТО ДОПИСАНО ПО ДОКУМЕНТАЦИИ, А НЕ ЗАМЕРОМ. Docker при этом проходе
 * не запускался; у дописанного нет чисел, и страница их не приписывает:
 *   — `ENV_ORDER`, первый и последний пункты: `docker compose run -e` сильнее всех, `ENV`
 *     из образа слабее всех — docs.docker.com, «Environment variables precedence»;
 *   — `PROFILE_NOTE`, правила слияния файлов (замена одиночных значений, склейка `ports`,
 *     слияние `environment` по имени и `volumes` по пути в контейнере) — «Merge Compose files»;
 *   — `WATCH_*`: действия `sync`/`rebuild`/`sync+restart`, `up --watch`, учёт `.dockerignore` —
 *     «Use Compose Watch». ⚠️ Не проверено запуском;
 *   — `STOP_NOTE`: `deploy.resources.limits.memory` как лимит памяти сервиса — Compose file
 *     reference, `deploy`. ⚠️ Не проверено запуском.
 *
 * ТРЕТИЙ ПРОХОД: БЛОК «ЗА КАДРОМ» РАСКРЫТ И УДАЛЁН (решение автора курса). Docker не запускался:
 *   — «Сборка образа прямо в файле» → подраздел в «Изоляции, остановке и окружениях»
 *     (`BUILD_CODE`, `BUILD_FACTS`), по документации; правила кеша — ссылкой на тему про Docker;
 *   — «Лимиты и ресурсы» → синтаксис `deploy.resources` (`limits`, `reservations`) дописан
 *     в `STOP_NOTE`; что видит Node под лимитом и чем заявка отличается от потолка — ссылками
 *     на «Память в Node» и Kubernetes, без пересказа;
 *   — «Оркестраторы» → тема уже говорит это в разделе про `depends_on` (карточка про Kubernetes
 *     и readiness-пробу) и в «Смежном на сайте»; пункт снят как дубль.
 *
 * ⚠️ ЧЕГО ЗДЕСЬ НЕТ. Абсолютные миллисекунды машинозависимы: на другой машине и на другом
 * образе базы они будут другими. Поэтому тест закрепляет **отношения и порядок событий**
 * («приложение стартовало раньше, чем база начала принимать соединения»), а не дословные
 * числа — как и требует «Как меряют в этом курсе» в AGENTS.md.
 */

