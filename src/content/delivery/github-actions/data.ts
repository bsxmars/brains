/**
 * Тон — это степень опасности, а не украшение.
 *
 * Значения совпадают с тем, что принимают `Table` (тон ячейки) и `Card` (тон карточки):
 * у таблицы «нейтрального» тона нет вовсе, поэтому строка без вердикта его и не получает,
 * а карточка добирает `neutral` уже на месте.
 */
