/**
 * Учебный вычислитель флага. Напечатан в теме, исполняется демо (`widgets/flag-lab/model/run.ts`)
 * и тестом `tests/unit/feature-flags.test.ts`: хеш — против `imurmurhash` и векторов MurmurHash3,
 * корзины — против векторов flagd-testbed, ответы — через настоящий OpenFeature SDK.
 */
export const FLAG_CODE = String.raw`// MurmurHash3 (x86, 32 бита, seed 0) по байтам UTF-8. Тот же хеш
// раскладывает пользователей по вариантам в flagd (операция fractional).
function murmur3(text) {
  const bytes = new TextEncoder().encode(text);
  const tail = bytes.length & ~3;
  const mixK = (k) => Math.imul(rotl(Math.imul(k, 0xcc9e2d51), 15), 0x1b873593);
  let h = 0;
  let k = 0;
  for (let i = 0; i < tail; i += 4) {
    k = bytes[i] | (bytes[i + 1] << 8) | (bytes[i + 2] << 16) | (bytes[i + 3] << 24);
    h = Math.imul(rotl(h ^ mixK(k), 13), 5) + 0xe6546b64;
  }
  k = 0;
  for (let i = bytes.length - 1; i >= tail; i--) k = (k << 8) | bytes[i];
  if (bytes.length > tail) h ^= mixK(k);
  h ^= bytes.length;
  h = Math.imul(h ^ (h >>> 16), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  return (h ^ (h >>> 16)) >>> 0;
}

function rotl(x, r) {
  return (x << r) | (x >>> (32 - r));
}

// Номер корзины от 0 до total − 1: хеш, растянутый на total делений.
// Соль — ключ флага: у каждого флага свой порядок пользователей.
function bucketOf(flagKey, targetingKey, total) {
  return Math.floor((murmur3(flagKey + targetingKey) * total) / 2 ** 32);
}

// Варианты делят корзины подряд: [['on', 20], ['off', 80]] —
// корзины 0…19 получают on, 20…99 — off.
function pickVariant(flagKey, targetingKey, split) {
  const total = split.reduce((sum, [, weight]) => sum + weight, 0);
  const bucket = bucketOf(flagKey, targetingKey, total);
  let end = 0;
  for (const [variant, weight] of split) {
    end += weight;
    if (bucket < end) return variant;
  }
}

// Условие правила: значение атрибута из списка или окончание строки.
function matches(when, context) {
  const value = context[when.attr];
  if (value === undefined) return false;
  if (when.in) return when.in.includes(value);
  if (when.endsWith) return String(value).endsWith(when.endsWith);
  return false;
}

// Флаг — функция от контекста. Порядок: выключен → правила
// по очереди, первое совпавшее → доли → вариант по умолчанию.
function evaluate(flagKey, flag, context, defaultValue) {
  if (!flag) return { value: defaultValue, reason: 'ERROR', errorCode: 'FLAG_NOT_FOUND' };
  if (flag.disabled) return { value: defaultValue, reason: 'DISABLED' };
  for (const rule of flag.rules ?? []) {
    if (matches(rule.when, context)) {
      return { value: flag.variants[rule.variant], variant: rule.variant, reason: 'TARGETING_MATCH' };
    }
  }
  if (flag.split) {
    if (context.targetingKey === undefined) {
      return { value: defaultValue, reason: 'ERROR', errorCode: 'TARGETING_KEY_MISSING' };
    }
    const variant = pickVariant(flagKey, context.targetingKey, flag.split);
    return { value: flag.variants[variant], variant, reason: 'SPLIT' };
  }
  const variant = flag.defaultVariant;
  return { value: flag.variants[variant], variant, reason: 'STATIC' };
}`;

