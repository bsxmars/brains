export const EDGE_HOST_CODE = `// Хост «как в edge»: на каждую точку присутствия — свой контекст V8 со своим глобальным
// объектом. Внутрь передаются только Web API; require, process и eval туда не попадают.
function createEdgeHost(vm, webApis, workerSource) {
  const contexts = new Map();
  const stats = { created: 0 };

  function contextFor(pop) {
    let ctx = contexts.get(pop);
    if (!ctx) {
      ctx = vm.createContext({ ...webApis }, { codeGeneration: { strings: false, wasm: false } });
      vm.runInContext(workerSource, ctx, { timeout: 50 });   // верхний уровень — один раз
      contexts.set(pop, ctx);
      stats.created += 1;
    }
    return ctx;
  }

  async function handle(pop, request) {
    const ctx = contextFor(pop);
    ctx.request = request;
    try {
      // timeout ограничивает только синхронную часть: время в await не считается
      return await vm.runInContext('worker.fetch(request)', ctx, { timeout: 50 });
    } catch (e) {
      return { error: e.code ?? e.name };
    }
  }

  return { handle, stats };
}
`;

