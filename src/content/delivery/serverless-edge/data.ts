export const COUNT_CODE = `// count.mjs — какие модули грузит холодный старт, а какие — вызовы.
// Запуск: node count.mjs ./handler.mjs
import { registerHooks } from 'node:module';

const seen = { files: 0, bytes: 0, builtins: 0 };
registerHooks({
  load(url, context, nextLoad) {
    const result = nextLoad(url, context);
    if (url.startsWith('node:')) seen.builtins += 1;
    else {
      seen.files += 1;
      seen.bytes += result.source == null ? 0 : Buffer.byteLength(result.source);
    }
    return result;
  },
});

let before = { ...seen };
function step() {
  const d = { files: seen.files - before.files, bytes: seen.bytes - before.bytes, builtins: seen.builtins - before.builtins };
  before = { ...seen };
  return d;
}
const event = (path) => ({ path, body: JSON.stringify({ items: [{ sku: 'A-1', qty: 2 }] }) });

const { handler } = await import(new URL(process.argv[2], \`file://\${process.cwd()}/\`).href);
const init = step();                                   // холодный старт
await handler(event('/orders')); const first = step(); // первый вызов
await handler(event('/orders')); const warm = step();  // тёплый вызов
await handler(event('/export')); const exp = step();   // первый вызов редкой ветки
console.log(JSON.stringify({ init, first, warm, exp }));
`;

