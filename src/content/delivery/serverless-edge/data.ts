export const SCALE_CODE = `// requests: [{ at, dur }] по возрастанию at, мс.
// concurrency — сколько запросов экземпляр берёт одновременно,
// keepWarm — сколько простаивающий экземпляр живёт до выгрузки,
// poolMax — потолок пула соединений в одном экземпляре,
// dbLimit — сколько соединений база даёт этому пользователю.
function simulate(requests, { concurrency, keepWarm, poolMax, dbLimit }) {
  const alive = [];          // живые экземпляры, старые первыми
  const running = [];        // запросы, которые держат соединение
  const out = { coldStarts: 0, peakInstances: 0, peakConns: 0, refused: 0, maxWait: 0, timeline: [] };
  let conns = 0, i = 0;

  const free = (inst, t) => { inst.busy -= 1; if (inst.busy === 0) inst.freeAt = t; };

  function end(t) {                        // 1. запросы, которые закончились к моменту t
    running.sort((a, b) => a.end - b.end || a.n - b.n);
    while (running.length && running[0].end <= t) {
      const r = running.shift(), inst = r.inst;
      const next = inst.waiting.shift();   // соединение уходит следующему в очереди пула
      if (next) {
        out.maxWait = Math.max(out.maxWait, r.end - next.at);
        running.push({ ...next, inst, end: r.end + next.dur });
        running.sort((a, b) => a.end - b.end || a.n - b.n);
      } else inst.idle += 1;
      free(inst, r.end);
    }
  }

  function reclaim(t) {                    // 2. простаивал дольше keepWarm — выгружен
    for (const inst of [...alive]) {
      if (inst.busy === 0 && t - inst.freeAt >= keepWarm) {
        alive.splice(alive.indexOf(inst), 1);
        conns -= inst.conns;               // соединения умирают вместе с экземпляром
      }
    }
  }

  function arrive(req) {                   // 3. новый запрос
    let inst = alive.find((x) => x.busy < concurrency);
    if (!inst) {                           // места нет — холодный старт
      inst = { busy: 0, conns: 0, idle: 0, waiting: [], freeAt: req.at };
      alive.push(inst);
      out.coldStarts += 1;
    }
    inst.busy += 1;
    if (inst.idle > 0) inst.idle -= 1;                       // взял соединение из пула
    else if (inst.conns < poolMax) {
      if (conns >= dbLimit) { out.refused += 1; free(inst, req.at); return; }
      inst.conns += 1; conns += 1;                           // открыл новое
    } else { inst.waiting.push(req); return; }               // пул исчерпан — ждёт
    running.push({ ...req, inst, end: req.at + req.dur });
  }

  for (;;) {
    const req = requests[i];
    const expiry = alive.filter((x) => x.busy === 0).map((x) => x.freeAt + keepWarm);
    const t = Math.min(req ? req.at : Infinity, ...running.map((r) => r.end), ...expiry);
    if (t === Infinity) break;
    end(t);
    reclaim(t);
    if (req && req.at === t) { arrive({ ...req, n: i }); i += 1; }
    out.peakInstances = Math.max(out.peakInstances, alive.length);
    out.peakConns = Math.max(out.peakConns, conns);
    const last = out.timeline[out.timeline.length - 1];
    if (last && last.t === t) out.timeline.pop();
    const waiting = alive.reduce((s, x) => s + x.waiting.length, 0);
    out.timeline.push({ t, instances: alive.length, conns, running: running.length, waiting });
  }
  return out;
}
`;

