export const LATENCY_CODE = `// Время ответа функции, которая ходит в базу. Всё в миллисекундах.
// userRtt — круг от пользователя до функции, dbRtt — круг от функции до базы,
// queries — запросы к базе один за другим, setupTrips — кругов на новое соединение
// (0, если оно уже открыто в пуле), stream — отдаёт ли функция шапку сразу.
function latency({ userRtt, dbRtt, queries, setupTrips, stream }) {
  const setup = setupTrips * dbRtt;
  const db = queries * dbRtt;
  const total = userRtt + setup + db;
  const ttfb = stream ? userRtt : total;   // первые байты: сразу или после базы
  return { setup, db, total, ttfb };
}

// Edge стоит рядом с пользователем, регион — рядом с базой.
// near — круг до ближайшей точки присутствия, far — от пользователя до региона базы,
// local — от функции до базы внутри региона.
function compare({ near, far, local, queries, setupTrips, stream }) {
  return {
    edge: latency({ userRtt: near, dbRtt: far, queries, setupTrips, stream }),
    region: latency({ userRtt: far, dbRtt: local, queries, setupTrips, stream }),
  };
}
`;

