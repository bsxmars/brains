export const CRONJOB_CODE = `apiVersion: batch/v1
kind: CronJob
metadata:
  name: nightly-report
spec:
  schedule: "0 3 * * *"          # каждый день в 03:00
  timeZone: Europe/Moscow        # без него — часовой пояс контроллера
  concurrencyPolicy: Forbid      # прошлый ещё идёт — новый не запускать
  startingDeadlineSeconds: 600   # опоздал больше чем на 10 минут — пропустить
  jobTemplate:
    spec:
      backoffLimit: 2            # сколько раз повторить упавший под
      activeDeadlineSeconds: 900 # и сколько всего можно работать
      template:
        spec:
          restartPolicy: OnFailure   # у Job только OnFailure или Never
          containers:
            - name: report
              image: registry.example.com/shop/report:1.4.0`;

export const CRONJOB_NOTE =
  'Главное отличие `Job` от `Deployment` — в слове «успешно». Под Deployment должен работать вечно, и его выход — авария. Под Job должен выйти с кодом 0, и тогда работа сделана: повторять нечего. Поэтому у Job нельзя `restartPolicy: Always`, а вместо вечных перезапусков — счётчик `backoffLimit`.';

export const CRONJOB_SETTINGS =
  'У `CronJob` три настройки, которые стоит ставить сразу. `concurrencyPolicy` решает, что делать, если прошлый запуск ещё идёт: `Allow` (по умолчанию) запустит второй рядом, `Forbid` пропустит новый, `Replace` оборвёт старый. `startingDeadlineSeconds` — на сколько запуск может опоздать и всё ещё состояться. Без него контроллер после простоя считает пропуски от последнего запуска и, насчитав больше ста, не запускает ничего и пишет ошибку; с ним считает только внутри этого окна. И документация прямо предупреждает: в редких случаях запуск случается **дважды или ни разу** — задача обязана это выдерживать. Отработавшие Job остаются в кластере для чтения логов: по умолчанию три успешных и один упавший.';

