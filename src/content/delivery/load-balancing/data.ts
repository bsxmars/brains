export const PICK_CODE = `// Учебная модель выбора бэкенда в nginx: взвешенный круг и least_conn.
// peers — массив { name, weight, current, conns } в порядке строк server;
// current и conns меняет сам выбор.

// Плавный взвешенный круг (smooth weighted round-robin):
// каждый ход все копят свой вес, лидер отдаёт сумму весов.
function smoothWeighted(peers) {
  let best = null;
  let total = 0;
  for (const p of peers) {
    p.current += p.weight;
    total += p.weight;
    if (best === null || p.current > best.current) best = p; // ничья — у первого
  }
  best.current -= total;
  return best;
}

// Наименьшее число соединений с поправкой на вес: conns / weight.
// Сравнение без деления: a.conns * b.weight < b.conns * a.weight.
// Ничья — плавный круг среди тех, кто вровень.
function leastConn(peers) {
  let best = null;
  for (const p of peers) {
    if (best === null || p.conns * best.weight < best.conns * p.weight) best = p;
  }
  const tied = peers.filter((p) => p.conns * best.weight === best.conns * p.weight);
  return tied.length > 1 ? smoothWeighted(tied) : best;
}`;

