export const RING_CODE = `// crc32 — та же функция, которой хеширует nginx
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
const utf8 = (s) => [...new TextEncoder().encode(s)];

// hash $key: 15 бит crc32 по модулю числа бэкендов
function modN(key, servers) {
  const h = (crc32(utf8(key)) >>> 16) & 0x7fff;
  return servers[h % servers.length];
}

// hash $key consistent: у каждого бэкенда vnodes точек на круге.
// Точка — crc32 от «хост \\0 порт» и четырёх байт предыдущей точки:
// так nginx получает 160 непохожих точек из одного адреса.
function buildRing(servers, vnodes) {
  const ring = [];
  for (const server of servers) {            // 'app:52801'
    const [host, port] = server.split(':');
    let prev = 0;
    for (let i = 0; i < vnodes; i++) {
      const prevBytes = [prev & 255, (prev >>> 8) & 255, (prev >>> 16) & 255, prev >>> 24];
      prev = crc32([...utf8(host), 0, ...utf8(port), ...prevBytes]);
      ring.push({ hash: prev, server });
    }
  }
  return ring.sort((a, b) => a.hash - b.hash);
}

// Ключ идёт к первой точке не меньше своего хеша; за последней — снова первая.
function ringLookup(ring, key) {
  const h = crc32(utf8(key));
  let lo = 0;
  let hi = ring.length;
  while (lo < hi) {                          // бинарный поиск
    const mid = (lo + hi) >> 1;
    if (ring[mid].hash < h) lo = mid + 1;
    else hi = mid;
  }
  return ring[lo % ring.length].server;
}`;

