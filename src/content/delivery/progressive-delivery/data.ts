  'Интервал Уилсона выбран не для красоты. Школьная формула «p ± 1.96·√(p(1−p)/n)» при нуле ошибок даёт интервал нулевой ширины, «0% ± 0», то есть полную уверенность после десяти запросов. Для малых долей и малых n она врёт, и это показано в сравнительной статье Brown, Cai и DasGupta. У Уилсона при нуле ошибок из 100 верхняя граница 3.7%, а не ноль. Интервал для p95 строится иначе, через порядковые статистики: сколько наблюдений лежит ниже истинной p95 — биномиальная величина. Отсюда жёсткое следствие: **меньше 73 запросов — у p95 нет верхней границы вообще**, и при 73 ею служит самое медленное наблюдение. Формула `wilson` совпадает с примерами из статьи Newcombe (1998), а оба интервала накрывают истину примерно в 95% случаев — это проверено моделированием.';

