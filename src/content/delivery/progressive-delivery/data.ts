export const BUCKET_CODE = String.raw`
// Кто попадает в новую версию: без хранилища и без случайности.
// Хеш от «соль:id» даёт номер корзины 0…9999, и пользователь внутри,
// если номер меньше доли. Соль — имя выката или флага: у каждого свои первые 5%.

function fnv1a(text) {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

// Перемешивание из MurmurHash3 (fmix32). Без него строки, которые отличаются
// только последним символом, получают связанные номера корзин — это видно в тесте.
function hash32(text) {
  let h = fnv1a(text);
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

const BUCKETS = 10000; // доля с точностью до сотой процента

function bucketOf(salt, id) {
  return hash32(salt + ':' + id) % BUCKETS;
}

function inRollout(salt, id, percent) {
  // Порог растёт с долей, а номер корзины у пользователя постоянный:
  // кто был внутри при 5%, остаётся внутри при 10%.
  return bucketOf(salt, id) < Math.round((percent * BUCKETS) / 100);
}

// Флаг функции: выключатель отдельно от раскатки. Выключили — функции нет ни у кого;
// включили обратно — она у тех же людей: доля и соль не менялись.
// Флага нет (сервис флагов не ответил) — безопасное значение: выключено.
function flagOn(flag, id) {
  if (!flag || flag.killed) return false;
  return inRollout(flag.key, id, flag.percent);
}
`;

/** Статистика анализа: интервалы и решение. Напечатано в теме. */
export const STATS_CODE = String.raw`
// Доверительный интервал Уилсона для доли: x ошибок из n запросов.
// Wilson, JASA 22 (1927); сравнение с другими интервалами —
// Brown, Cai, DasGupta, Statistical Science 16 (2001).
function wilson(x, n, z) {
  if (n === 0) return { p: NaN, lo: 0, hi: 1 };
  const p = x / n;
  const z2 = z * z;
  const denom = 1 + z2 / n;
  const center = (p + z2 / (2 * n)) / denom;
  const half = (z / denom) * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n));
  return { p, lo: Math.max(0, center - half), hi: Math.min(1, center + half) };
}

// Квантиль q и интервал для неё без предположений о распределении.
// Сколько наблюдений лежит ниже истинной p95 — биномиальная величина B(n, 0.95),
// поэтому границы интервала — наблюдения с рангами n·q ∓ z·√(n·q·(1−q)).
// Не хватает рангов — границы нет (NaN), и решать по ней нельзя.
function quantile(sorted, q, z) {
  const n = sorted.length;
  if (n === 0) return { v: NaN, lo: NaN, hi: NaN };
  const spread = z * Math.sqrt(n * q * (1 - q));
  const l = Math.floor(n * q - spread);
  const u = Math.ceil(n * q + spread);
  return {
    v: sorted[Math.ceil(q * n) - 1],
    lo: l >= 1 ? sorted[l - 1] : NaN,
    hi: u <= n ? sorted[u - 1] : NaN,
  };
}

const ANALYSIS = { z: 1.96, minRequests: 200, errorMargin: 0.01, q: 0.95, latencyRatio: 1.2 };

// Три ответа вместо двух: «хуже» — только если хуже весь интервал,
// «не хуже» — только если не хуже весь интервал. Иначе — ждать данных.
function judge(lo, hi, limit) {
  if (lo > limit) return 'rollback';
  if (hi <= limit) return 'continue';
  return 'wait';
}

// Доля ошибок канарейки против базы: предел — доля базы плюс допуск.
function judgeErrors(base, canary, cfg) {
  const c = Object.assign({}, ANALYSIS, cfg);
  const ci = wilson(canary.errors, canary.n, c.z);
  const limit = base.n ? base.errors / base.n + c.errorMargin : NaN;
  if (base.n < c.minRequests || canary.n < c.minRequests) {
    return { verdict: 'wait', ci, limit, why: 'мало запросов' };
  }
  const verdict = judge(ci.lo, ci.hi, limit);
  return { verdict, ci, limit, why: verdict === 'wait' ? 'интервал накрывает предел' : '' };
}

// p95 задержки канарейки против p95 базы, умноженной на допуск.
function judgeLatency(base, canary, cfg) {
  const c = Object.assign({}, ANALYSIS, cfg);
  const sortedBase = Float64Array.from(base.lat).sort();
  const sortedCanary = Float64Array.from(canary.lat).sort();
  const b = quantile(sortedBase, c.q, c.z);
  const ci = quantile(sortedCanary, c.q, c.z);
  const limit = b.v * c.latencyRatio;
  if (base.n < c.minRequests || canary.n < c.minRequests) {
    return { verdict: 'wait', ci, base: b.v, limit, why: 'мало запросов' };
  }
  // Нет верхней границы — «не хуже» не доказано; нет нижней — «хуже» тоже.
  const lo = Number.isNaN(ci.lo) ? -Infinity : ci.lo;
  const hi = Number.isNaN(ci.hi) ? Infinity : ci.hi;
  const verdict = judge(lo, hi, limit);
  return { verdict, ci, base: b.v, limit, why: verdict === 'wait' ? 'интервал накрывает предел' : '' };
}

// Общее решение: любой откат — откат; продолжать — только если обе метрики за.
function decide(base, canary, cfg) {
  const errors = judgeErrors(base, canary, cfg);
  const latency = judgeLatency(base, canary, cfg);
  const both = [errors.verdict, latency.verdict];
  const verdict = both.includes('rollback') ? 'rollback' : both.every((v) => v === 'continue') ? 'continue' : 'wait';
  return { verdict, errors, latency };
}
`;

/** Служебная часть: поток запросов с сидом. В теме не печатается, её исполняют демо и тест. */
export const SIM_CODE = String.raw`
// Служебная часть: синтетический поток запросов. Генератор свой, с сидом:
// тот же сид даёт тот же поток, и на сервере, и в браузере, и в тесте.

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const TRAFFIC = { seed: 7, perMinute: 2000, users: 100000, median: 120, sigma: 0.5 };

// Сценарий: доля ошибок базы и новой версии, во сколько раз новая медленнее.
function createTraffic(scenario, opts) {
  const o = Object.assign({}, TRAFFIC, opts);
  const rnd = mulberry32(o.seed);
  const stats = { base: { n: 0, errors: 0, lat: [] }, next: { n: 0, errors: 0, lat: [] } };
  let minute = 0;

  // route(id) → 'base' | 'next'. Из генератора на каждый запрос берутся
  // ровно четыре числа, куда бы он ни ушёл: смена доли не сдвигает поток.
  function tick(route) {
    for (let i = 0; i < o.perMinute; i++) {
      const id = 'u' + Math.floor(rnd() * o.users);
      const roll = rnd();
      const u1 = rnd() || 1e-12;
      const u2 = rnd();
      const g = Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
      const side = route(id);
      const s = stats[side];
      const next = side === 'next';
      s.n++;
      if (roll < (next ? scenario.nextErr : scenario.baseErr)) s.errors++;
      s.lat.push(o.median * Math.exp(o.sigma * g) * (next ? scenario.nextSlow : 1));
    }
    minute++;
  }

  return { stats, tick, minute: () => minute };
}
`;

/** План выката по шагам: как канарейка идёт от 5% к 100% и когда откатывается. Напечатано в теме. */
export const PLAN_CODE = String.raw`
// План выката по шагам — в форме шагов Argo Rollouts:
// { setWeight: 5 } ставит долю, { pause: { duration: '10m' } } держит её.
function minutesOf(duration) {
  if (duration === undefined) return null; // пауза без срока: ждёт человека
  if (typeof duration === 'number') return duration / 60; // число — секунды
  const m = /^(\d+)(s|m|h)$/.exec(duration);
  if (!m) throw new Error('не понимаю длительность ' + duration);
  return Number(m[1]) * { s: 1 / 60, m: 1, h: 60 }[m[2]];
}

function stagesOf(steps) {
  const stages = [];
  let weight = 0;
  for (const step of steps) {
    if ('setWeight' in step) weight = step.setWeight;
    else if ('pause' in step) stages.push({ weight, minutes: minutesOf(step.pause.duration) });
    else throw new Error('шаг не из модели: ' + Object.keys(step).join(', '));
  }
  return stages;
}

// Тот же план из полей Flagger (по его документации): доля растёт на stepWeight
// раз в interval, пока не дойдёт до maxWeight.
function flaggerSteps(analysis) {
  const steps = [];
  for (let w = analysis.stepWeight; w <= analysis.maxWeight; w += analysis.stepWeight) {
    steps.push({ setWeight: w }, { pause: { duration: analysis.interval } });
  }
  return steps;
}

// Каждую минуту — анализ накопленных чисел. Откат — сразу, как только он доказан.
// Шаг дальше — только когда пауза вышла и анализ сказал «не хуже».
// Не хватило данных — пауза тянется до extraMinutes, а потом выкат встаёт и ждёт человека.
function runPlan(steps, scenario, opts) {
  const o = Object.assign({ salt: 'web-rollout', extraMinutes: 10 }, opts);
  const traffic = createTraffic(scenario, o.traffic);
  const rows = [];
  for (const stage of stagesOf(steps)) {
    if (stage.minutes === null) {
      rows.push({ weight: stage.weight, minute: traffic.minute(), verdict: 'hold', why: 'пауза без срока' });
      return { outcome: 'hold', rows };
    }
    let spent = 0;
    let last = null;
    while (spent < stage.minutes + o.extraMinutes) {
      traffic.tick((id) => (inRollout(o.salt, id, stage.weight) ? 'next' : 'base'));
      spent++;
      last = decide(traffic.stats.base, traffic.stats.next, o.analysis);
      if (last.verdict === 'rollback') break;
      if (spent >= stage.minutes && last.verdict === 'continue') break;
    }
    const row = {
      weight: stage.weight,
      minute: traffic.minute(),
      extra: Math.max(0, spent - stage.minutes),
      verdict: last.verdict === 'wait' ? 'hold' : last.verdict,
      canary: { n: traffic.stats.next.n, errors: traffic.stats.next.errors },
      decision: last,
    };
    rows.push(row);
    if (row.verdict !== 'continue') return { outcome: row.verdict === 'rollback' ? 'rolledBack' : 'hold', rows };
  }
  return { outcome: 'promoted', rows };
}
`;

/** Совместимость версии кода со схемой БД: на ней стоит «расширяй, потом сужай». Напечатано в теме. */
export const SCHEMA_CODE = String.raw`
// Версия кода работает на схеме, если все столбцы, которые она читает и пишет,
// существуют, а все обязательные (NOT NULL без умолчания) она заполняет.
function compatible(code, schema) {
  const missing = [...new Set(code.reads.concat(code.writes))].filter((c) => !(c in schema));
  const unfilled = Object.keys(schema).filter((c) => schema[c] === 'required' && !code.writes.includes(c));
  return { ok: missing.length === 0 && unfilled.length === 0, missing, unfilled };
}
`;

