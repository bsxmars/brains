export const RELAY_SCENE_CODE = `// cs.js — контент-скрипт «переводчика» на https://example.com/*
window.addEventListener('message', (event) => {
  if (event.source !== window) return;           // фреймы отсекли
  chrome.runtime.sendMessage(event.data)         // передали фону как есть,
    .then((text) => window.postMessage({ text }, '*'));  // ответ — обратно в окно
});

// sw.js — фон: у него host_permissions на сайты пользователя
chrome.runtime.onMessage.addListener((msg, sender, reply) => {
  fetch(msg.url).then((r) => r.text()).then(reply);
  return true;
});`;

