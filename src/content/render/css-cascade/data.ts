/**
 * Данные урока «Каскад и вычисление стилей».
 *
 * Источник — конспект `Study/js/14-css-cascade.md`. Всё, что про кадр целиком (стадии
 * style → layout → paint → composite, forced synchronous layout, что дешевле двигать),
 * осталось в уроке «Кадр браузера»: здесь разбирается только то, что происходит **внутри**
 * шага style.
 *
 * ## Что проверено запуском
 *
 * Движок — Chromium 153.0.8010.12 (headless, `@playwright/test` 1.63), сентябрь 2026.
 * Проверялось на временных страницах вне проекта, значения снимались `getComputedStyle`:
 *
 *  - **сортировщик главного демо сверен с браузером на всех 256 наборах кандидатов** —
 *    расхождений ноль. То есть шесть критериев, как они запрограммированы в
 *    `widgets/cascade-referee`, дают ровно тот цвет, который получает живой элемент.
 *    ⚠️ Сверка гонялась **на отдельной странице**: те же правила, слои и порядок, но без
 *    окружения курса. На самой странице урока ту же сверку делает виджет — строкой «сходится»;
 *    её и надо считать показанием, если когда-нибудь разойдётся;
 *
 *  - **ловушка, на которой демо уже один раз соврало** (найдена на собранной странице,
 *    Chromium 153). У подопытного элемента стоял `transition: color .2s`. Во время идущего
 *    перехода `getComputedStyle` возвращает **интерполированное** значение, а не результат
 *    каскада: замер читал прежний цвет, отставая ровно на одно изменение, и демо показывало
 *    красное «сходится: нет» при полностью правильном разборе. Измерено: с переходом новый
 *    цвет появляется в чтении через ~400 мс, без перехода — в первом же чтении. Поэтому
 *    переходов на измеряемых свойствах в демо этого урока нет. Ирония по теме: transition
 *    стоит на верхнем этаже лестницы origin, выше любого `!important`, — демо про каскад
 *    мерило анимацию поверх каскада;
 *  - переворот порядка слоёв для `!important`: слой, объявленный раньше, сильнее; unlayered —
 *    слабее всех важных;
 *  - для обычных объявлений правила вне слоёв сильнее любого слоя;
 *  - позиция слоя задаётся первым упоминанием имени, а не порядком блоков в файле;
 *  - инлайн против важного: `style="color: orange"` проигрывает `.note { color: purple !important }`,
 *    `style="color: orange !important"` — выигрывает;
 *  - граница shadow DOM: `:host { color: … !important }` изнутри перебивает
 *    `#host { color: … !important }` из документа;
 *  - специфичность: `:is()` и `:not()` берут самый специфичный аргумент (даже если совпал
 *    другой), `:where()` обнуляет всё внутри, `:not(.a, .b)` слабее `:not(.a):not(.b)`,
 *    `li.x:nth-child(1 of .y)` даёт ровно `(0,3,1)`, `&` во вложенности эквивалентен
 *    `:is(родительский список)`;
 *  - defaulting: `display: initial` → `inline`, `display: revert` → `block`, `display: unset` →
 *    `inline`; на ссылке `color: initial` → `rgb(0, 0, 0)`, `color: unset` → цвет родителя,
 *    `color: revert` → `rgb(0, 0, 238)` и `text-decoration-line: revert` → `underline`;
 *  - `revert-layer` возвращает значение предыдущего слоя;
 *  - IACVT: `padding: 8px; padding: var(--gap)` при `--gap: 10` даёт `0px`, фолбэк
 *    `var(--gap, 4px)` не спасает, а `@property` с `syntax: '<length>'` — спасает (`8px`);
 *  - `!important` внутри `@keyframes` игнорируется, а `!important` на элементе делает
 *    анимацию цвета невидимой; переход при этом честно интерполирует к важному значению;
 *  - `@import` внутри блочного `@layer { … }` молча отбрасывается: в правилах слоя его нет;
 *  - `opacity` не наследуется (у потомка computed `1`), `line-height`, заданный числом,
 *    наследуется числом, а заданный процентами — уже пикселями;
 *  - presentational hint: `img { width: 100% }` бьёт `width="300"` без всякого `!important`;
 *  - `container-type: inline-size` вместе с `width: fit-content` схлопывает элемент в `0px`,
 *    тогда как тот же блок без контейнера даёт `16px`.
 *
 * ## Две правки против конспекта — обе проверены
 *
 *  1. Конспект: «`getPropertyValue('--x')` возвращает строку **с ведущим пробелом**».
 *     В Chromium 153 это уже не так: `--gap:   10px  ;` читается как `"10px"` — пробелы
 *     обрезаны с обеих сторон. `.trim()` остаётся безвредной привычкой, но фактом не является.
 *  2. Конспект: «у элемента без бокса `width` вернёт `auto`, а не число». Точнее: resolved
 *     value откатывается к **computed**, то есть к тому, что объявлено. При `width: 50%`
 *     вернётся `"50%"`, при `padding-left: 10%` — `"10%"`; `auto` возвращается только там,
 *     где `auto` и написано.
 *
 * ## Что проверке в браузере не поддаётся и помечено как таковое
 *
 * Внутренности Blink — invalidation sets, bloom-фильтр предков, бакеты по key selector,
 * matched properties cache, момент флаша внутри `getComputedStyle` — из прикладного кода
 * не наблюдаются. Всё это идёт по design doc и конспекту, с оговоркой в тексте. Цена
 * паттернов (`:has()`, container queries, ширина инвалидации) — тем более: её меряют
 * профайлером на своей странице, а не берут из урока.
 *
 * ## Область видимости: снято отдельно (Chromium 153.0.8010.12)
 *
 * `@scope` поддерживается, и он вводит критерий каскада, которого нет в разборщике демо, —
 * **близость области**. Порядок, снятый экспериментом: происхождение и важность → слои →
 * специфичность → близость → порядок появления. Проверки: при равной специфичности ближняя
 * область бьёт дальнюю (`#c` над `#b` над `#a`); дальняя с `p#t` бьёт ближнюю с `p`, то есть
 * специфичность выше близости; правило сильного слоя из дальней области бьёт слабый слой
 * ближней; `!important` из дальней бьёт обычное из ближней; при равной близости решает
 * последнее объявление. Отдельно: `:scope p` из дальней области выигрывает у `p` из ближней —
 * `:scope` добавляет разряд специфичности. Нижняя граница `@scope (A) to (B)` исключает `B`
 * и всё под ним — элемент внутри `B` остаётся без объявления.
 *
 * ⚠️ В демо `widgets/cascade-referee` близости **нет**: его `CriterionKey` перечисляет шесть
 * критериев, а сортировщик сверен с браузером на 256 наборах. Вносить седьмой значило бы
 * переделывать демо и пересверять всё заново, поэтому близость живёт отдельным подразделом
 * и помечена как не участвующая в разборщике.
 *
 * ## Второй проход (сентябрь 2026): порядок и повторы
 *
 * Подразделы раздела 1 выстроены в порядке критериев: этажи → `@starting-style` (верхний этаж)
 * → критерии 2 и 3 → слои. Близость области (`@scope`) переехала в конец раздела 2: она стоит
 * между специфичностью и порядком и опирается на то, что `:scope` добавляет разряд, — объяснять
 * её до специфичности значило ссылаться вперёд. Внутри темы убраны дубли: два факта про слои
 * из `IMPORTANT_FACTS` (слиты в `LAYER_ORDER_RULES` вместе со своими проверками), три карточки
 * `SPEC_FACTS` (списки, вложенность и «255 классов» — у каждого рядом своя карточка с кодом),
 * тёмная панель «тот же механизм, что в Кадре браузера» (дом — «Кадр браузера», раздел «Чтение
 * и запись»; здесь выжимка в `GCS_FACTS`) и заметка о `getComputedStyle` во вводной.
 * Из «за кадром» удалён пункт про проверку селекторов справа налево: он дублировал `MATCH_FACTS`.
 * Фактов проход не менял.
 *
 * ## `@starting-style` и `@container style()` — снято отдельно (Chromium 153.0.8010.12)
 *
 * `@starting-style`: два одинаковых элемента с `transition: color`, отличие — наличие правила.
 * С ним на первом кадре стоит стартовый цвет, без него — сразу конечный, то есть перехода
 * при появлении не происходит. Переход с `display: none` на `block` состоялся, и стартовый
 * цвет применился. ⚠️ Отдельно проверено, что `transition-behavior: allow-discrete`
 * к стартовым стилям **отношения не имеет**: в случае без этого флага стартовое значение
 * сработало так же — флаг отвечает только за анимацию самого дискретного свойства.
 *
 * `@container style(--x: …)`: правило переключается при смене переменной на предке (живая
 * инвалидация, а не разовый матч); **`container-type` для style-запроса не нужен** — сработало
 * на предке без него, в отличие от размерных запросов; обёртка `@container` специфичности
 * не добавляет — `.c` внутри неё проиграл такому же `.c` снаружи по порядку объявления.
 */

