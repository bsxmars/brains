export const FIT_CODE = `function fitCanvas(canvas) {
  const dpr = window.devicePixelRatio;
  const { width, height } = canvas.getBoundingClientRect();  // CSS-пиксели
  canvas.width = Math.round(width * dpr);                    // буфер — в точках экрана
  canvas.height = Math.round(height * dpr);
  const ctx = canvas.getContext('2d');
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);   // дальше рисуем в CSS-пикселях
  return ctx;
}`;

