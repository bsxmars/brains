/**
 * Файл воркера. Демо собирает его из этой строки в `Blob` и запускает как есть; тест отдаёт
 * его с сервера как `/spinner.js`. `drawSpinner` демо зовёт и на главном потоке — для волчка-соседа.
 */
export const SPINNER_WORKER_CODE = `// spinner.js — воркер рисует сам, своим циклом кадров
function drawSpinner(ctx, frame, color) {
  const { width: w, height: h } = ctx.canvas;
  const a = frame * 0.12;                 // угол растёт с каждым кадром
  ctx.clearRect(0, 0, w, h);
  ctx.lineWidth = h * 0.12;
  ctx.lineCap = 'round';
  ctx.strokeStyle = color;
  ctx.beginPath();
  ctx.arc(w / 2, h / 2, h * 0.32, a, a + Math.PI * 1.4);
  ctx.stroke();
}

self.onmessage = ({ data }) => {
  const ctx = data.canvas.getContext('2d');
  let frame = 0;
  function tick() {
    frame++;
    drawSpinner(ctx, frame, data.color);
    // отметка кадра: страница прочтёт её, когда освободится
    self.postMessage({ frame, at: performance.timeOrigin + performance.now() });
    requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
};`;

