/**
 * Учебная модель растеризации вертикальной полосы: покрытие пикселя. Её печатает `CodeBlock`,
 * исполняет демо (`widgets/canvas-lab/model/run.ts`) и тест — против `STAND_COLUMNS` и против
 * `PROBE_CODE`, исполненного в Chromium заново.
 */
export const RASTER_CODE = `// Какую долю квадрата пикселя [i, i + 1) закрывает полоса [a, b).
function coverage(a, b, i) {
  return Math.max(0, Math.min(b, i + 1) - Math.max(a, i));
}

// Полоса фигуры по горизонтали в CSS-пикселях. Обводка лежит
// по обе стороны от линии пути, заливка — вправо от x.
function band(kind, x, width) {
  return kind === 'fill' ? [x, x + width] : [x - width / 2, x + width / 2];
}

// Альфа каждого столбца буфера: покрытие × 255.
// scale — масштаб контекста, то есть DPR после fitCanvas.
function rasterColumns(kind, x, width, scale, cols = 18) {
  const [left, right] = band(kind, x, width).map((v) => v * scale);
  const alpha = [];
  for (let i = 0; i < cols; i++) {
    alpha.push(Math.round(255 * coverage(left, right, i)));
  }
  return alpha;
}

// Размер буфера для элемента cssWidth × cssHeight на экране с данным DPR.
function bufferSize(cssWidth, cssHeight, dpr) {
  return { width: Math.round(cssWidth * dpr), height: Math.round(cssHeight * dpr) };
}

// Куда сдвинуть линию пути, чтобы обводка легла на целые пиксели буфера.
// Работает, когда width * scale — целое: 1px при DPR 1, 2, 3.
function crispX(x, width, scale) {
  const w = width * scale;                         // толщина в точках буфера
  const left = Math.round(x * scale - w / 2);      // левый край — на целое
  return (left + w / 2) / scale;
}`;

