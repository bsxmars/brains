/**
 * Исполняется тестом со стабами `document` как напечатано: без API, с API и с отказом `ready`.
 * Прежний вариант делал `await t?.ready` после `t.ready.catch(…)` — и бросал при любом пропуске:
 * `.catch` возвращает новый промис, а `ready` остаётся отклонённым. Поймано этим тестом.
 */
export const BASIC_CODE = `function withTransition(update) {
  if (!document.startViewTransition) {   // браузер без API: изменение без анимации
    update()
    return null
  }
  const t = document.startViewTransition(update)
  t.ready.catch(() => {})                // отказ ready — не ошибка приложения
  return t
}

const t = withTransition(() => list.append(list.firstElementChild))
await t?.updateCallbackDone   // DOM в новом состоянии
// t.ready — снимки сняты, псевдоэлементы построены: место для своих element.animate().
// Ждать его без обработчика нельзя: .catch выше вернул НОВЫЙ промис, а ready остался прежним
await t?.finished             // анимация кончилась или пропущена, оверлей снят`;

