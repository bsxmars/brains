export const CLUSTER_CODE = `// Кластеры сразу для всех уровней: от крупного масштаба к мелкому,
// каждый уровень собирается из меток предыдущего. Так устроен supercluster.
function buildClusters(points, radius = 40, maxZoom = 16) {
  // Координаты — доли мира от 0 до 1: одинаковы на любом уровне
  let level = points.map((p, i) => {
    const { x, y } = project(p.lng, p.lat, 0);
    return { x: x / TILE, y: y / TILE, count: 1, id: i };
  });
  const levels = { [maxZoom + 1]: level };
  for (let z = maxZoom; z >= 0; z--) {
    const r = radius / (TILE * 2 ** z); // radius пикселей уровня z в долях мира
    const nearby = gridIndex(level, r);
    const taken = new Set();
    const next = [];
    for (const p of level) {
      if (taken.has(p)) continue;
      taken.add(p);
      const group = nearby(p).filter((q) => !taken.has(q));
      if (group.length === 0) {
        next.push(p);                   // соседей нет — метка остаётся как была
        continue;
      }
      let count = p.count, wx = p.x * p.count, wy = p.y * p.count;
      for (const q of group) {
        taken.add(q);
        count += q.count;
        wx += q.x * q.count;
        wy += q.y * q.count;
      }
      next.push({ x: wx / count, y: wy / count, count }); // центр, взвешенный по числу точек
    }
    levels[z] = level = next;
  }
  return levels;
}

// Соседи в круге радиуса r: сетка с клеткой r, смотрим свою клетку и восемь вокруг
function gridIndex(items, r) {
  const cells = new Map();
  const key = (cx, cy) => cx + ':' + cy;
  for (const it of items) {
    const k = key(Math.floor(it.x / r), Math.floor(it.y / r));
    if (!cells.has(k)) cells.set(k, []);
    cells.get(k).push(it);
  }
  return (p) => {
    const cx = Math.floor(p.x / r), cy = Math.floor(p.y / r);
    const out = [];
    for (let dx = -1; dx <= 1; dx++)
      for (let dy = -1; dy <= 1; dy++)
        for (const q of cells.get(key(cx + dx, cy + dy)) ?? [])
          if ((q.x - p.x) ** 2 + (q.y - p.y) ** 2 <= r * r) out.push(q);
    return out;
  };
}`;

