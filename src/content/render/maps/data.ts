export const MERCATOR_CODE = `const TILE = 256;      // сторона тайла, пикселей
const R = 6378137;     // радиус Земли в Web Mercator (EPSG:3857), метров
// Широта, на которой мир становится квадратом: 85.0511…°
const MAX_LAT = (2 * Math.atan(Math.exp(Math.PI)) - Math.PI / 2) * 180 / Math.PI;

// Долгота и широта → пиксели мира на уровне z. Мир — квадрат TILE · 2^z.
function project(lng, lat, z) {
  const size = TILE * 2 ** z;
  const phi = Math.max(-MAX_LAT, Math.min(MAX_LAT, lat)) * Math.PI / 180;
  const x = (lng + 180) / 360 * size;
  const y = (1 - Math.log(Math.tan(Math.PI / 4 + phi / 2)) / Math.PI) / 2 * size;
  return { x, y };
}

// Обратно: пиксели мира → долгота и широта
function unproject(x, y, z) {
  const size = TILE * 2 ** z;
  const lng = x / size * 360 - 180;
  const lat = Math.atan(Math.sinh(Math.PI * (1 - 2 * y / size))) * 180 / Math.PI;
  return { lng, lat };
}

// В какой тайл попала точка и в какой пиксель внутри него
function tileOf(lng, lat, z) {
  const { x, y } = project(lng, lat, z);
  const last = 2 ** z - 1;
  const tx = Math.min(last, Math.floor(x / TILE));
  const ty = Math.min(last, Math.floor(y / TILE));
  return { z, x: tx, y: ty, px: Math.floor(x - tx * TILE), py: Math.floor(y - ty * TILE) };
}

// Сколько метров на местности в одном пикселе карты
function metersPerPixel(lat, z) {
  return 2 * Math.PI * R * Math.cos(lat * Math.PI / 180) / (TILE * 2 ** z);
}`;

