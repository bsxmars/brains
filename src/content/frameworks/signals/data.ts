/** Шаг 1: сигнал — значение, версия и подписчики; чтение подписывает. */
export const STEP_SIGNAL = `let current = null                  // кто сейчас вычисляется: computed или эффект
let batchDepth = 0
const pending = []                  // эффекты, помеченные «грязно», в порядке пометки

function track(source) {
  if (!current) return              // читают вне вычисления — подписывать некого
  if (!current.sources.has(source)) source.observers.add(current)
  current.sources.set(source, source.version)   // какую версию источника видели
}

function signal(value) {
  const s = {
    kind: 'signal', version: 0, observers: new Set(),
    get() {
      track(s)
      return value
    },
    set(next) {
      if (Object.is(next, value)) return   // то же значение — никого не будим
      value = next
      s.version++
      for (const o of [...s.observers]) markStale(o)   // push: «грязно» вниз
      if (batchDepth === 0) flush()
    },
  }
  return s
}`;

/** Шаг 2: push — пометить всё, что ниже, ничего не считая. */
export const STEP_PUSH = `function markStale(node) {
  if (node.stale) return            // уже помечен: ромб не обходится дважды
  node.stale = true
  if (node.kind === 'effect') pending.push(node)
  else for (const o of [...node.observers]) markStale(o)
}`;

/** Шаг 3: pull — `computed` досчитывается при чтении, сверяя версии источников. */
export const STEP_PULL = `function computed(fn) {
  const c = {
    kind: 'computed', fn, version: 0, stale: true, ran: false, value: undefined,
    sources: new Map(), observers: new Set(),
    get() {
      refresh(c)                    // pull: досчитать, если надо, — и только теперь
      track(c)
      return c.value
    },
  }
  return c
}

function refresh(node) {
  if (!node.stale) return
  node.stale = false
  if (node.ran && !sourcesChanged(node)) return   // пометка была, изменения нет
  const next = run(node)
  node.ran = true
  if (node.kind === 'computed' && !Object.is(next, node.value)) {
    node.value = next
    node.version++                  // читатели увидят новую версию
  }
}

function sourcesChanged(node) {
  for (const [source, seen] of node.sources) {
    if (source.kind === 'computed') refresh(source)   // вверх по графу, в порядке чтения
    if (source.version !== seen) return true
  }
  return false
}

function run(node) {
  for (const source of node.sources.keys()) source.observers.delete(node)
  node.sources.clear()              // зависимости соберутся заново: ветка if могла смениться
  const prev = current
  current = node
  try {
    return node.fn()
  } finally {
    current = prev
  }
}`;

/** Шаг 4: эффект, слив очереди и пакет. */
export const STEP_EFFECT = `function effect(fn) {
  const e = { kind: 'effect', fn, stale: true, ran: false, disposed: false, sources: new Map() }
  refresh(e)                        // первый прогон — сразу
  return function dispose() {
    e.disposed = true
    for (const source of e.sources.keys()) source.observers.delete(e)
    e.sources.clear()
  }
}

function flush() {
  while (pending.length) {
    const e = pending.shift()
    if (!e.disposed) refresh(e)     // сверить версии и, если надо, перезапустить
  }
}

function batch(fn) {
  batchDepth++
  try {
    return fn()
  } finally {
    if (--batchDepth === 0) flush()
  }
}`;

/** Шаг 5: рендерер без виртуального DOM — эффект на каждое изменчивое место. */
export const STEP_DOM = `function createRenderer(dom) {
  function text(read) {
    const node = dom.createText('')
    effect(() => dom.setText(node, String(read())))   // эффект привязан к узлу
    return node
  }

  function h(tag, props, ...children) {
    const node = dom.createElement(tag)
    for (const [name, value] of Object.entries(props ?? {})) {
      if (typeof value === 'function') effect(() => dom.setAttribute(node, name, value()))
      else dom.setAttribute(node, name, value)
    }
    for (const child of children) {
      if (typeof child === 'function') dom.append(node, text(child))
      else if (typeof child === 'string') dom.append(node, dom.createText(child))
      else dom.append(node, child)
    }
    return node
  }

  function render(component, parent) {
    dom.append(parent, component())   // компонент — один вызов функции, и всё
  }

  return { h, render }
}`;

/** То, что исполняют демо и тест: шаги подряд плюс экспорт. */
export const MINI_SIGNALS_CODE = [STEP_SIGNAL, STEP_PUSH, STEP_PULL, STEP_EFFECT, STEP_DOM].join('\n\n') +
  '\n\nreturn { signal, computed, effect, batch, createRenderer }';

/** Наивный push: каждый узел пересчитывается в момент оповещения и сразу толкает дальше. */
export const NAIVE_SIGNALS_CODE = `let current = null

function track(source) {
  if (current && !current.sources.has(source)) {
    current.sources.add(source)
    source.observers.add(current)
  }
}

function notify(source) {
  for (const o of [...source.observers]) o.update()   // push: сразу и до конца
}

function run(node) {
  for (const s of node.sources) s.observers.delete(node)
  node.sources.clear()
  const prev = current
  current = node
  try {
    return node.fn()
  } finally {
    current = prev
  }
}

function signal(value) {
  const s = {
    observers: new Set(),
    get() { track(s); return value },
    set(next) {
      if (Object.is(next, value)) return
      value = next
      notify(s)
    },
  }
  return s
}

function computed(fn) {
  const c = {
    fn, sources: new Set(), observers: new Set(), value: undefined,
    get() { track(c); return c.value },
    update() {                      // жадно: пересчёт в момент оповещения
      const next = run(c)
      if (Object.is(next, c.value)) return
      c.value = next
      notify(c)
    },
  }
  c.value = run(c)                  // и сразу при создании
  return c
}

function effect(fn) {
  const e = { fn, sources: new Set(), update: () => run(e) }
  run(e)
  return () => { for (const s of e.sources) s.observers.delete(e); e.sources.clear() }
}

const batch = (fn) => fn()          // откладывать нечего: каждая запись уже всё сделала

return { signal, computed, effect, batch }`;

