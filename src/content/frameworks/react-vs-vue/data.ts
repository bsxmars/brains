/**
 * Данные урока «React против Vue».
 *
 * Тема стоит на двух разборах: устройство ре-рендера React — в «Ре-рендеринге в React»,
 * устройство `track`/`trigger` и очереди — в «Реактивности Vue». Здесь ни то, ни другое не
 * пересказывается; здесь обе модели решают **одну задачу**, и разговор идёт о числах,
 * о переносе кода и о тайминге.
 *
 * ── Второй проход: что здесь своё, а что выжимка ─────────────────────────────────────
 *
 * Своё: сравнение (раздел «Различие»), демо и цена моделей, перенос кода и таблица
 * соответствия тайминга. Выжимкой со ссылкой стали две вещи, у которых есть дом:
 *   порядок `sync → pre → render → post → onUpdated → nextTick` — дом в «Реактивности Vue»,
 *     раздел «Планировщик» (там же демо, которое этот порядок прогоняет);
 *   эффекты React на сервере — дом в «Ре-рендеринге в React», подраздел «Первый рендер».
 * Из «Тонких мест» убраны четыре пункта, дословно повторявшие текст разделов («одинаковые
 * числа — не одинаковая работа», «точечность зависит от источника данных», «память графа —
 * не константа», «меньше работы — не быстрее»).
 *
 * ⚠️ Исправлено (проверено запуском, Node 26.8.2, `vue` 3.5.42 + `@vue/server-renderer`):
 * Прежняя `TIMING_REACT_RUN_NOTE` (теперь `TIMING_SSR_NOTE`) утверждала, что на сервере React ведёт себя «обратно по знаку»
 * против Vue. Прогон `renderToString` показал, что асимметрии нет: у Vue на сервере
 * выполняются `setup` и `render`, а `onBeforeMount`, `onMounted` и `watchEffect` с
 * `flush: 'post'` — нет; у React — тело компонента, а эффекты нет. Ловушка переноса
 * остаётся, но она общая для обеих сторон.
 *
 * ⚠️ Исправлено (третий проход, React 19.3.0 из `node_modules` курса, собран `esbuild`,
 * обе сборки, Chromium 153.0.8010.12 под Playwright): строка `TIMING_ROWS` про `useEffect`.
 * Было: «отдельной задачей, **после** отрисовки». Метки из `useLayoutEffect` — микрозадача,
 * `requestAnimationFrame`, следующая задача через `MessageChannel`, — по 15 повторов:
 * после клика и нажатия клавиши `useEffect` идёт **раньше микрозадачи**, то есть в той же
 * задаче, что и коммит, и раньше `rAF` — 15 из 15; компонент, смонтированный по клику, —
 * так же. После `setTimeout`/`MessageChannel` — отдельная задача, до и после `rAF` примерно
 * поровну; первый `createRoot().render()` — отдельная задача, до `rAF` 14 из 15. Стало:
 * «после клика или клавиши — в той же задаче, до отрисовки; иначе — отдельной задачей, кадр
 * может успеть раньше». В `TIMING_NOTE` «начнёт мерцать» → «может замерцать». Подробности
 * опыта — шапка `render/react-rerender/data.ts`.
 *
 * Для сведения: перемер памяти (Node 26.8.2, `@vue/reactivity` 3.5.42, `--expose-gc`, три
 * поля на объект) дал на 20 000 объектов ×2,2 без чтений и ×15 после чтения всех полей одним
 * эффектом — против ×1,8 и ×11,4 в `MEMORY_ROWS`, снятых на Node 24.11. Порядок и вывод
 * совпадают, числа версиезависимы; таблица не тронута.
 *
 * ── Третий проход: «за кадром» ───────────────────────────────────────────────────────
 *
 * Компиляторы, сигналы и серверный рендер вынесены в отдельные темы (ссылки в «Смежном»),
 * блока «за кадром» больше нет; что уже разобрано (React Compiler — «Ре-рендеринг в React», флаги патча —
 * «Vue 3 изнутри: рендерер и patch»), стало ссылками в таблице и в «Смежном». Пункт
 * «Экосистема и всё нетехническое» снят: он сообщал о границе темы, а не о предмете.
 *
 * ── Чем и как мерилось ───────────────────────────────────────────────────────────────
 *
 * React 19.3.0 и Vue 3.5.42 (те же версии, что стоят в проекте), Node 24.11, jsdom.
 * Дерево одно и то же с обеих сторон: `App` → `Filter`, `Counter`, `List` → `Row`×N,
 * `Status`; три поля состояния, производное значение и список из пяти строк. Данные задачи
 * физически одни на обе половины — `@/widgets/two-models/model/task.ts`.
 *
 * Единица работы:
 *   React — вызов функции компонента (счётчик в теле);
 *   Vue   — прогон render-функции, снятый через `onMounted` + `onUpdated`.
 * Что `onUpdated` срабатывает ровно один раз на один прогон render-функции, проверено
 * отдельным замером: тот же компонент с render-функцией, где счётчик стоит буквально
 * в теле, даёт то же число.
 *
 * Монтирование считается с обеих сторон. Иначе «добавить строку» выглядело бы у Vue дешевле,
 * чем есть: у React новая строка стоит вызова функции, и у Vue она тоже чего-то стоит.
 *
 * Правки документа — `MutationObserver` (`childList` + `characterData`, без атрибутов),
 * считаются записи. Каждое действие мерилось **со свежего монтирования**: первый заход гонял
 * три действия подряд на одном дереве, и состояние перетекало — «добавить» мерилось при уже
 * включённом фильтре.
 *
 * ── Что осталось непроверенным ───────────────────────────────────────────────────────
 *
 * Время. Ни одного утверждения вида «X быстрее Y» в уроке нет, и это не осторожность ради
 * приличия: в jsdom нет ни разметки, ни отрисовки, а без них цифра миллисекунд означала бы
 * только скорость самого jsdom.
 */

