/**
 * Сквозной пример — React. Без JSX: `h` — это `React.createElement`, так листинг исполняется
 * тестом без сборщика. `boundary` включает границу `Suspense` вокруг абзаца со временем.
 */
export const REACT_ORDER_CODE = `function Order({ stamp, theme, boundary }) {
  const [clicks, setClicks] = useState(0);
  const built = h('p', null, 'Собран в ', h('time', null, stamp));
  return h('section', { className: theme },
    h('h3', null, 'Заказ №42'),
    boundary ? h(Suspense, null, built) : built,
    h('button', { onClick: () => setClicks(clicks + 1) }, 'Нажато: ', clicks),
  );
}`;

