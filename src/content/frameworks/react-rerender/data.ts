export const EFFECTS_TIMING =
  '`useLayoutEffect` выполняется внутри коммита, в той же задаче, что и правка DOM. Кадр ещё не нарисован, поэтому то, что эффект подвинет или перемерит, пользователь увидит уже в готовом виде. Когда выполнится `useEffect`, зависит от того, что вызвало обновление. После клика или нажатия клавиши React выполняет его **в той же задаче**, сразу за коммитом, — то есть тоже до отрисовки. Во всех остальных случаях — первый рендер приложения, ответ сервера, таймер, даже движение мыши — эффект уходит в отдельную задачу, и кадр между ними может нарисоваться, а может и нет. Поэтому измерение, перенесённое из `useLayoutEffect` в `useEffect`, иногда даёт один кадр без правки — это и есть «скачок контента», и коварен он тем, что случается не каждый раз. Код, которому нужна геометрия до кадра, пишут в `useLayoutEffect`.';

