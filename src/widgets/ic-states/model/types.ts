/** Состояние площадки inline cache и цена обращения в этом состоянии. */
export interface IcState {
  /** Сколько форм видела площадка — подпись переключателя. */
  label: string;
  /** Имя состояния из терминологии V8. */
  state: string;
  /** Замер в миллисекундах на фиксированном числе чтений. */
  ms: number;
  /** Что происходит при обращении. */
  what: string;
  /** Что из этого может (или не может) компилятор. */
  opt: string;
  note: string;
  tone: 'ok' | 'err';
}
