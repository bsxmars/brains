/**
 * Специфичность как тройка чисел: читатель собирает селектор из кусков и смотрит, что
 * получилось в разрядах и кто теперь побеждает.
 *
 * Вклад каждого куска лежит в данных, а не считается разбором строки: писать парсер
 * селекторов ради демо — заводить второй движок. Проверка приходит не из арифметики:
 * виджет строит настоящее правило, кладёт его в документ рядом с правилом-соперником
 * и читает `getComputedStyle`. Если сумма разрядов и живой браузер разойдутся, читатель
 * увидит это сам.
 */
/**
 * Разряды специфичности: идентификаторы, классы, типы. Объявлены здесь, а не взяты
 * у соседнего демо: виджет не импортирует виджет — общее ушло бы уровнем ниже,
 * а три числа того не стоят.
 */
export type Spec = [a: number, b: number, c: number];

/** Кусок селектора: как пишется, что добавляет в разряды и почему. */
export interface SpecPiece {
  id: string;
  /** Текст куска — он же попадёт в готовый селектор. */
  text: string;
  /** Вклад в `(a, b, c)`. */
  spec: Spec;
  /** Что это: id, класс, атрибут, псевдокласс, тип, псевдоэлемент или нулевой вклад. */
  kind: 'id' | 'class' | 'attr' | 'pseudo' | 'type' | 'element' | 'zero';
  /** Пояснение к куску. Разрешена строчная разметка. */
  note: string;
  /** Включён ли при первом показе. */
  on: boolean;
}

/** Правило-соперник: фиксированное, стоит в таблице стилей **позже** собранного. */
export interface SpecRival {
  selector: string;
  spec: Spec;
  /** Токен темы для цвета соперника. */
  token: string;
  note: string;
}
