/**
 * Главное демо урока: «почему победило именно это правило».
 *
 * Кандидаты здесь — не картинка, а настоящие объявления: виджет собирает из них таблицу
 * стилей, вставляет её в документ и применяет к живому элементу на странице. Победителя
 * он вычисляет сам, по шести критериям каскада, а потом сверяет предсказание с тем, что
 * вернул `getComputedStyle`. Расхождение означало бы, что урок врёт, — и оно было бы видно
 * читателю сразу, а не осталось бы ошибкой в тексте.
 *
 * Специфичность лежит в данных числами, а не считается из строки селектора: разбирать CSS
 * в виджете — писать второй движок, а проверка всё равно приходит не из арифметики,
 * а из браузера.
 */

/** Разряды специфичности: идентификаторы, классы, типы. */
export type Spec = [a: number, b: number, c: number];

/** Один кандидат — объявление `color` для подопытного элемента. */
export interface CascadeDecl {
  id: string;
  /** Подпись в списке кандидатов. */
  label: string;
  /**
   * Селектор правила. `null` — объявление из атрибута `style`: у него нет ни селектора,
   * ни специфичности, и выигрывает оно отдельным критерием.
   */
  selector: string | null;
  /** Имя каскадного слоя; `null` — правило вне слоёв. */
  layer: string | null;
  important: boolean;
  /** Специфичность селектора. Для инлайна — нули: критерий 5 до него не доходит. */
  spec: Spec;
  /** Токен темы, который объявление ставит в `color`. Цвет в курсе бывает только токеном. */
  token: string;
  /** Включён ли кандидат при первом показе. */
  on: boolean;
  /** Чем этот кандидат интересен. Разрешена строчная разметка. */
  note: string;
}

/** Порядок слоёв, объявленный statement-формой. Первый в списке — самый слабый для обычных. */
export interface CascadeLayers {
  names: string[];
  /** Строка `@layer …;`, как она стоит в таблице стилей демо. */
  code: string;
}

/** Ключ критерия каскада — порядок объявления совпадает с порядком сортировки. */
export type CriterionKey = 'origin' | 'context' | 'inline' | 'layer' | 'specificity' | 'order';

/** Подпись критерия: номер, короткое имя и что он решает. */
export interface CriterionCopy {
  key: CriterionKey;
  n: string;
  label: string;
  note: string;
}
