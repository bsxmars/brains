/**
 * Конвейер как граф: те же джобы, два разных способа решить, когда каждый может начаться.
 */

export interface JobSpec {
  name: string;
  stage: string;
  /** Длительность джоба, мс — из записанного прогона, а не из головы. */
  ms: number;
  /**
   * `needs`. Три разных состояния, и путать их дорого:
   *   `undefined` — ключа нет вовсе: джоб живёт по стадиям;
   *   `[]`        — пустой список: джоб стартует сразу, ничего не ожидая;
   *   `['a']`     — ждёт перечисленные джобы и только их.
   */
  needs?: string[];
}

/** Джоб, которому посчитали место на шкале времени. */
export interface Placed extends JobSpec {
  start: number;
  end: number;
  /** Чего ждал: имена джобов либо имя стадии. */
  waitedFor: string[];
  /** Ждал ли он стадию целиком — для подписи «ждёт стадию build». */
  stageGated: boolean;
}

export interface Schedule {
  jobs: Placed[];
  /** Когда кончился последний джоб. */
  total: number;
}
