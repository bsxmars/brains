/**
 * Способы «скопировать строку» и то, сколько памяти каждый из них в итоге удерживает.
 *
 * Единственная честная метрика здесь — `heapUsed` после нескольких сборок, а не тип
 * представления: классический `(' ' + s).slice(1)` даёт тип `SLICED`, то есть по типу
 * от настоящего окна в родителя его не отличить.
 */
export interface CopyWay {
  /** Сам приём. */
  code: string;
  /** `heapUsed` после шести `global.gc()`, МБ. */
  mb: number;
  /** Отпустил ли приём родителя. */
  copies: boolean;
  /** Короткая приписка, если случай особенный. */
  note?: string;
}
