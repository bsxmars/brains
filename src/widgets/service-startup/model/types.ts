/**
 * Старт стека Compose, снятый с демона.
 *
 * Здесь нет «нарисованного» времени: каждое событие — строка из `docker events`, а отметка
 * `at` — миллисекунды от момента, когда была введена команда `up`. Демо не изображает докер
 * (в браузере его не запустить), оно **перематывает записанный прогон**, и подпись под демо
 * говорит об этом прямо.
 *
 * Два сценария отличаются одной строкой в `compose.yml` — условием в `depends_on`, — и вся
 * тема держится на том, что видно из разницы их шкал.
 */

/** Что именно случилось. Типы взяты у демона, кроме `ready` и `connect` — см. ниже. */
export type EventKind =
  /** `create` — контейнер создан, но процесса внутри ещё нет. */
  | 'create'
  /** `start` — процесс запущен. Это всё, что знает `depends_on` без условия. */
  | 'start'
  /** `exec_start` пробы: докер спросил сервис, жив ли он. */
  | 'probe'
  /** `health_status: healthy` — проба ответила успехом, и только теперь сервис «готов». */
  | 'healthy'
  /**
   * Строка из лога самого процесса («database system is ready to accept connections»).
   *
   * Демон о ней не знает: в `docker events` такого события нет. Она лежит на шкале как раз
   * затем, чтобы стало видно расстояние между «процесс на самом деле готов» и «докер об этом
   * узнал» — без healthcheck это расстояние бесконечно.
   */
  | 'ready'
  /** Попытка приложения открыть соединение — видна по его собственному логу. */
  | 'connect'
  /** `die` — процесс вышел; код лежит в `exit`. */
  | 'die';

export interface StartupEvent {
  /** Миллисекунды от запуска `docker compose up`. */
  at: number;
  /** Имя сервиса из `compose.yml`. */
  service: string;
  kind: EventKind;
  /** Подпись для шкалы — короткая, на одну строку. */
  label: string;
  /** Код возврата у `die`. */
  exit?: number;
  /** Чем это кончилось: `ok` — хорошо, `err` — плохо. Без тона — просто факт. */
  tone?: 'ok' | 'warn' | 'err';
}

/** Состояние сервиса в конкретный момент — то, что рисуется на дорожке. */
export type ServiceState =
  | 'нет'
  | 'создан'
  | 'стартует'
  | 'принимает соединения'
  | 'healthy'
  | 'вышел'
  | 'упал';

export interface ServiceRow {
  /** Имя сервиса — оно же имя в сети проекта. */
  name: string;
  /** Одна фраза о роли: «база», «кеш», «приложение». */
  role: string;
}

export interface Scenario {
  id: string;
  /** Подпись переключателя. */
  label: string;
  /** Что стоит в `depends_on` — показывается как код рядом со шкалой. */
  depends: string;
  /** Проект, на котором снят прогон, — чтобы число можно было проверить. */
  project: string;
  /** Чем кончилось: строка вердикта под шкалой. */
  verdict: string;
  verdictTone: 'ok' | 'err';
  events: StartupEvent[];
}
