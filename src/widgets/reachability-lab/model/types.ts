/**
 * Типы стенда достижимости: единственное, что в теме про сборщик можно выполнить по-настоящему.
 *
 * ⚠️ **Граница честности задана прямо в типах.** Из JS наблюдаем ровно один факт — что объект
 * **уже собран**: `WeakRef.deref()` вернул `undefined`, финализатор сработал. Обратного факта
 * не существует: «не собрался» — это не «жив», а «за отведённое число попыток сборка до него
 * не дошла». Поэтому здесь нет поля `alive` и нет вердикта «жив»; есть `collected` и есть
 * `attempts`, без которого `collected: false` ничего не значит.
 */

export type ReachCaseKey =
  | 'none'
  | 'variable'
  | 'map'
  | 'weakmap-key'
  | 'weakmap-value'
  | 'ephemeron-cycle'
  | 'listener';

/** Чего тема ждёт от случая. Ожидание — это утверждение урока, а не ответ движка. */
export type Expectation = 'collected' | 'held';

/** Описание случая: что построено, кто держит и почему. Ответа здесь нет — он считается. */
export interface ReachCaseSpec {
  key: ReachCaseKey;
  /** Подпись «пилюли». */
  label: string;
  /** Заголовок случая в панели. */
  title: string;
  /** Исходник графа ссылок — тот же, что строит `buildCase`. */
  code: string;
  /** Кто держит объект по замыслу случая: «никто», «переменная`held`», «ключ жив». */
  holder: string;
  /** Что утверждает тема. Сверяется с тем, что получилось. */
  expects: Expectation;
  /** Разбор со строчной разметкой — выводится через `Md`. */
  why: string;
}

/** Флаг финализации. Объект, а не замыкание: см. `cases.ts`, «ловушка контекста». */
export interface FiredFlag {
  fired: boolean;
}

/**
 * Построенный случай: слабая ссылка на подопытного, флаг финализатора и то, что стенд
 * честно держит в руках.
 *
 * ⚠️ Самого подопытного здесь нет и быть не может. Вернуть его наружу хотя бы раз — значит
 * поселить его в кадре вызывающего, и любой случай стал бы «не собрался».
 */
export interface CaseSetup {
  key: ReachCaseKey;
  /** Слабая ссылка на подопытный объект. */
  ref: WeakRef<object>;
  /** Второй узел, когда он есть: значение записи WeakMap в случае с эфемероном. */
  extra: { label: string; ref: WeakRef<object> } | null;
  /** Всё, что стенд держит сильно: держатель случая плюс сам реестр финализаторов. */
  keep: unknown[];
  /** Сработал ли финализатор. Читается полем, не вызовом: замыкание утащило бы контекст. */
  flag: FiredFlag;
  /** Удалось ли зарегистрировать финализатор — в среде без `FinalizationRegistry` нет. */
  registered: boolean;
}

/** Параметры давления. Сборку из браузера вызвать нельзя — можно только давить и ждать. */
export interface ChaseOptions {
  /** Предел по числу попыток. Именно это число попадает в формулировку «не собрался за N». */
  attempts: number;
  /** Предел по времени, мс: на медленной машине попытки кончатся позже, чем терпение. */
  budgetMs: number;
  /**
   * Сколько блоков мусора выделять за одну попытку.
   *
   * Блок — крупный массив **плюс** россыпь мелких объектов: первый гонит old space и приближает
   * Major GC, без которого не разбираются эфемероны, второй забивает молодое поколение.
   */
  junkBlocks: number;
}

/** Итог сверки с ожиданием темы. Четыре исхода, и три из них — не «да/нет». */
export type Agreement =
  /** Тема ждала сборки, объект собран. Единственный случай, где что-то доказано. */
  | 'proved'
  /** Тема ждала, что объект останется; он и не собрался. Согласуется — но не доказывает. */
  | 'as-expected'
  /** Тема ждала сборки, а её не случилось за N попыток. Вывод не получен. */
  | 'inconclusive'
  /** Тема ждала, что объект останется, а он собран. Это опровержение утверждения. */
  | 'contradicts'
  /** Прогон не состоялся: в среде нет `WeakRef`. */
  | 'unavailable';

export interface ReachResult {
  key: ReachCaseKey;
  /** Прогон состоялся. `false` — в среде нет `WeakRef`, и придуманных ответов здесь не будет. */
  ok: boolean;
  /** `deref()` до давления вернул объект. */
  before: boolean;
  /** `deref()` вернул `undefined` — объект собран. Единственный доказанный факт стенда. */
  collected: boolean;
  /** То же про второй узел, если он у случая есть. */
  extraCollected: boolean | null;
  /** Сколько попыток понадобилось (или сколько сделано, если так и не собрался). */
  attempts: number;
  /** Сколько это заняло, мс. Машинозависимо. */
  ms: number;
  /** Был ли рычаг `globalThis.gc` — в браузере его нет, и это часть ответа. */
  lever: boolean;
  /** Есть ли в среде `FinalizationRegistry`. */
  finalizerSupported: boolean;
  /** Финализатор сработал. Он может не сработать никогда — это не ошибка стенда. */
  finalized: boolean;
  agreement: Agreement;
  /** Формулировка вердикта. «Не собрался за N попыток» — не то же, что «жив». */
  verdict: string;
  /** Что из этого следует, а что нет. Со строчной разметкой. */
  note: string;
  /** Протокол попыток: что выделено, когда уступили потоку, что вернул `deref()`. */
  log: string[];
}
