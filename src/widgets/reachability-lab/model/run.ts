import { buildCase, caseSpec } from './cases';
import type { Agreement, CaseSetup, ChaseOptions, ReachCaseKey, ReachResult } from './types';

/**
 * Давление на аллокатор и опрос слабой ссылки — единственный способ узнать со страницы,
 * собрался объект или нет.
 *
 * ⚠️ **Сборку со страницы вызвать нельзя.** `globalThis.gc` в браузере появляется только при запуске
 * самого браузера с `--js-flags=--expose-gc` (Chromium 153, проверено 2026-10-01), у читателя его нет,
 * и заменителя у него нет. Значит стенд делает единственное, что ему доступно:
 * выделяет мусор, уступает потоку и спрашивает `deref()` — по кругу, с пределом по числу
 * попыток и по времени.
 *
 * ⚠️ **В Node рычаг есть, и он всё равно не работает сам по себе.** Проверено пятью прогонами
 * из пяти (AGENTS.md, «Память, сборщик и строки»): ни один вызов `gc()`, ни два подряд,
 * ни `gc({ type: 'major', execution: 'sync' })` не очищают `WeakRef` на только что брошенный
 * объект. Работает единственный порядок — **сперва уступить потоку, потом звать сборку**.
 * Поэтому цикл ниже устроен именно так: мусор → уступка потоку → `gc()`, если он есть →
 * `deref()`.
 *
 * ⚠️ **`deref()` фиксирует объект до конца текущей задачи.** Это KeptAlive-список, он очищается
 * на границе задачи. Поэтому спрашивать `deref()` второй раз в том же тике бессмысленно:
 * следующая проверка обязана попасть в **новую** задачу — и попадает, потому что каждая
 * попытка начинается с уступки потоку.
 *
 * ⚠️ **Отрицательный результат не доказывает ничего.** «Собрался» доказывает, что пути
 * от корней не было. «Не собрался» не доказывает ни живости, ни утечки: сборка могла просто
 * не дойти. Поэтому наружу идёт не «жив/мёртв», а `collected` вместе с `attempts`, и вердикт
 * звучит «не собрался за N попыток».
 *
 * Функции здесь чистые от Vue и DOM: ровно их зовёт юнит-тест. В процессе `vitest` сборки нет
 * (`environment: 'node'` без `execArgv`), поэтому проверка живёт в отдельном процессе —
 * `execFileSync(process.execPath, ['--expose-gc', …])`, как в `tests/unit/elements-kinds.test.ts`.
 */

/**
 * Пределы прогона. Числа подобраны замером, и замер стоит записать — он же объясняет,
 * почему стенд формулирует отрицательный ответ именно так.
 *
 * Снято в Node 26.8, свежий процесс на каждый прогон (это и есть «первый клик читателя»),
 * **без** `--expose-gc` — то есть в тех же условиях, в каких работает браузер. По три повтора
 * на сочетание:
 *
 * | попыток × блоков | никто не держит | ключ WeakMap | эфемерон |
 * |---|---|---|---|
 * | 24 × 8   | 1/3 | 0/3 | 2/3 |
 * | 24 × 16  | 2/3 | 1/3 | 2/3 |
 * | 120 × 4  | 2/3 | 3/3 | 2/3 |
 * | **60 × 8** | **2/3** | **3/3** | **3/3** |
 *
 * ⚠️ Последняя строка — та, по которой выбраны значения по умолчанию, — **на повторном замере
 * подтвердилась хуже**, и это важнее самой таблицы. Ещё четыре повтора того же сочетания дали
 * 2/4, 3/4 и 2/4; вместе с первыми тремя получается **4/7, 6/7 и 5/7**. Первый замер выглядел
 * как «3/3 — работает», и на трёх повторах так и выглядело бы всегда: доля здесь не свойство
 * стенда, а бросок монеты. Держащие случаи при этом не собрались ни разу (4 из 4) — контроль
 * на месте: стенд не объявляет собранным то, что держат.
 *
 * ⚠️ **Главное, что видно в этих числах: сборка не размазана по попыткам, а квантуется.**
 * Успех приходит на попытке 3, 5, 8, 48 или 70 — там, где V8 сам решил провести полную сборку;
 * между этими точками не происходит ничего, сколько ни дави. Поэтому «не собрался» — это
 * не «мало давили», а «полная сборка так и не случилась», и добавка попыток лечит это лишь
 * отчасти: и при 60, и при 120 попытках примерно треть прогонов случая «никто не держит»
 * не собирается вовсе. Вызвать сборку из браузера нельзя — можно только создать условия
 * и ждать, и вот как выглядит это «нельзя» в цифрах.
 *
 * Под `--expose-gc` та же модель детерминирована полностью: 5 прогонов из 5, собираемые
 * случаи — с первой попытки. Именно поэтому проверка живёт в отдельном процессе с флагом,
 * а не в браузере и не в `vitest`.
 */
export const DEFAULTS: ChaseOptions = {
  attempts: 60,
  budgetMs: 6000,
  junkBlocks: 8,
};

/** Сколько строк протокола показываем: важны первые попытки и последняя. */
const LOG_LIMIT = 10;

/**
 * Размеры одного блока мусора: крупный массив и россыпь мелких объектов.
 *
 * ⚠️ **Оба слагаемых обязательны, и это выяснилось замером, а не рассуждением.** Стенд сперва
 * давил только мелкими объектами — и случай с эфемероном (значение ссылается на собственный
 * ключ) не собирался **ни разу за 24 попытки**, хотя под `--expose-gc` собирался с первой.
 * Причина в том, что мелкие объекты провоцируют Scavenge, а разбор эфемеронов — работа полной
 * пометки: scavenge пару «ключ ↔ значение» не распутывает. Крупные массивы давят на old space
 * и доводят дело до Major GC: с ними тот же случай собирается за 6 попыток, 3 прогона из 3.
 *
 * Размеры названы в элементах, а не в мегабайтах, намеренно: вес элемента зависит от сборки
 * движка (с pointer compression вдвое меньше), и «2 МБ» было бы придуманным числом.
 */
const BIG_SIZE = 1 << 18;
const SMALL_SIZE = 16_384;

/** Куда уходит мусор, чтобы давление нельзя было выбросить целиком. */
let junk = 0;

/** Сколько объектов выделено стендом за всё время. Сток, делающий давление наблюдаемым. */
export function junkSink(): number {
  return junk;
}

/** Есть ли в среде слабые ссылки. Ветка «среды нет» честная: ответ не выдумывается. */
export function weakRefReady(): boolean {
  return typeof WeakRef === 'function';
}

/** Есть ли финализаторы. Их отсутствие стенду не мешает — мешает отсутствие `WeakRef`. */
export function finalizerReady(): boolean {
  return typeof FinalizationRegistry === 'function';
}

/**
 * Рычаг сборки, если он есть.
 *
 * В браузере его нет никогда. В Node он появляется под `--expose-gc` — и это единственная
 * причина, по которой юнит-тест может быть детерминированным там, где страница вынуждена
 * давить и ждать.
 */
export function gcLever(): (() => void) | null {
  const lever = (globalThis as { gc?: () => void }).gc;
  return typeof lever === 'function' ? lever : null;
}

const now = (): number =>
  typeof performance !== 'undefined' && typeof performance.now === 'function' ? performance.now() : Date.now();

/**
 * Уступить поток так, чтобы началась новая **задача**.
 *
 * Именно задача, а не микрозадача: KeptAlive-список очищается на её границе, и `await
 * Promise.resolve()` его бы не очистил. `setTimeout` — тот самый приём из проверенного рецепта.
 */
const yieldToTask = (): Promise<void> => new Promise<void>((resolve) => setTimeout(resolve, 0));

/**
 * Давление на аллокатор — двумя руками сразу.
 *
 * Крупный массив на каждый блок гонит вверх old space и приближает Major GC, без которого
 * эфемероны не разбираются вовсе (см. `BIG_SIZE`). Мелкие объекты забивают молодое поколение
 * и провоцируют Scavenge, которым собираются обычные брошенные объекты. Убрать любую половину —
 * и часть случаев перестанет собираться в браузере, где рычага `gc()` нет.
 *
 * Живыми держатся не больше двух последних блоков: остальное становится мусором сразу,
 * как и задумано, — стенд давит на аллокатор, а не занимает память.
 */
function pressure(blocks: number): void {
  let recent: object[] = [];

  for (let b = 0; b < blocks; b++) {
    const big: object = new Array(BIG_SIZE).fill(b);

    const small: object[] = new Array(SMALL_SIZE);
    for (let i = 0; i < SMALL_SIZE; i++) small[i] = { i, pad: i * 2 };

    recent.push(big, small);
    if (recent.length > 4) recent = [big, small];
    junk += BIG_SIZE + SMALL_SIZE;
  }
}

/** Прогон не состоялся: в среде нет `WeakRef`. Ответ отсутствует, а не выдуман. */
export function unavailable(key: ReachCaseKey): ReachResult {
  return {
    key,
    ok: false,
    before: false,
    collected: false,
    extraCollected: null,
    attempts: 0,
    ms: 0,
    lever: false,
    finalizerSupported: finalizerReady(),
    finalized: false,
    agreement: 'unavailable',
    verdict: 'проверить нечем',
    note: 'В этой среде нет `WeakRef` — факт сборки наблюдать нечем, и придуманного ответа здесь не будет.',
    log: [],
  };
}

/**
 * Гонять давление, пока объект не соберётся или пока не кончатся попытки и время.
 *
 * Возвращает то, что действительно наблюдалось, и ничего сверх этого.
 */
export async function chase(setup: CaseSetup, options: ChaseOptions = DEFAULTS): Promise<ReachResult> {
  const spec = caseSpec(setup.key);
  const lever = gcLever();
  const started = now();

  const log: string[] = [];
  let hidden = 0;
  const write = (line: string): void => {
    if (log.length < LOG_LIMIT) log.push(line);
    else hidden++;
  };

  /** Первый `deref()` — до всякого давления. Он же кладёт объект в KeptAlive до конца задачи. */
  const before = setup.ref.deref() !== undefined;
  write(`deref() до давления → ${before ? 'объект на месте' : 'undefined (?!)'}`);

  const junkLine = `${options.junkBlocks} × (массив ${BIG_SIZE.toLocaleString('ru-RU')} + ${SMALL_SIZE.toLocaleString('ru-RU')} объектов)`;
  let collected = !before;
  let attempts = 0;

  while (!collected && attempts < options.attempts && now() - started < options.budgetMs) {
    attempts++;

    pressure(options.junkBlocks);
    await yieldToTask();
    lever?.();

    collected = setup.ref.deref() === undefined;

    write(
      `попытка ${attempts}: мусор ${junkLine} · уступили потоку${lever ? ' · gc()' : ''} · deref() → ${
        collected ? 'undefined' : 'объект'
      }`,
    );
  }

  if (hidden > 0) {
    log.push(`…ещё ${hidden}; на попытке ${attempts} deref() → ${collected ? 'undefined' : 'объект'}`);
  }

  /**
   * Финализатору нужна своя задача — и не одна: колбэк реестра ставится в очередь уже после
   * сборки и может прийти сильно позже. Две уступки — компромисс между «дали шанс» и «стенд
   * не висит». Не пришёл — так и написано; это не ошибка стенда и не опровержение сборки.
   */
  await yieldToTask();
  await yieldToTask();

  const extraCollected = setup.extra ? setup.extra.ref.deref() === undefined : null;
  const agreement = agree(spec.expects, collected);

  return {
    key: setup.key,
    ok: true,
    before,
    collected,
    extraCollected,
    attempts,
    ms: now() - started,
    lever: lever !== null,
    finalizerSupported: setup.registered,
    finalized: setup.flag.fired,
    agreement,
    verdict: collected ? `собран · попыток понадобилось: ${attempts}` : `не собрался за ${attempts} попыток`,
    note: noteOf(agreement, attempts, lever !== null),
    log,
  };
}

/**
 * Сверка наблюдённого с тем, что утверждает тема.
 *
 * Исходов четыре, и только один из них — доказательство. Свести их к «сошлось / не сошлось»
 * значило бы приравнять «объект собран» к «объект не собрался за 24 попытки».
 */
function agree(expects: 'collected' | 'held', collected: boolean): Agreement {
  if (expects === 'collected') return collected ? 'proved' : 'inconclusive';
  return collected ? 'contradicts' : 'as-expected';
}

function noteOf(agreement: Agreement, attempts: number, lever: boolean): string {
  switch (agreement) {
    case 'proved':
      return 'Объект собран — значит пути к нему от корней не было. Это **единственное**, что стенд умеет доказать, и здесь он это сделал.';
    case 'as-expected':
      return `За ${attempts} попыток объект не собрался. Это согласуется с тем, что говорит тема, но **ничего не доказывает**: «не собрался» и «жив» — разные утверждения, и второе из первого не следует.`;
    case 'inconclusive':
      return lever
        ? `Тема ждёт сборки, а её за ${attempts} попыток не случилось — при том что рычаг \`gc()\` здесь есть. Вывод не получен: либо прогон слишком короткий, либо это расхождение, которое стоит разобрать.`
        : `Тема ждёт сборки, а за ${attempts} попыток её не случилось. Вывод **не получен** — и отрицательный результат здесь не значит ничего: вызвать сборку из браузера нельзя, можно только давить и ждать. Имеет смысл запустить ещё раз.`;
    case 'contradicts':
      return 'Объект собран, хотя случай построен так, чтобы его держали. Собранный объект недостижим — значит **держатель не держит**, и утверждение случая неверно.';
    default:
      return '';
  }
}

/**
 * Полный прогон одного случая: построить граф, погонять давление, вернуть наблюдённое.
 *
 * Это и есть точка входа юнит-теста — и точка входа компонента. Обе стороны спрашивают движок
 * одним и тем же кодом.
 */
export async function runReachCase(
  key: ReachCaseKey,
  partial: Partial<ChaseOptions> = {},
): Promise<ReachResult> {
  if (!weakRefReady()) return unavailable(key);

  return chase(buildCase(key), { ...DEFAULTS, ...partial });
}
