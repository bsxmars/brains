/** Строка вывода демо: тон отделяет «так и было задумано» от «а вот это баг». */
export interface ZalgoOut {
  text: string;
  tone?: 'ok' | 'warn';
}

/** Шаг сценария: где выполнение, чему равен `spinner` и что на стеке. */
export interface ZalgoStep {
  message: string;
  tone?: 'ok' | 'warn' | 'err';
  /** Подсвеченная строка листинга — индекс с нуля; −1 — ни одной (стек размотан). */
  line: number;
  /**
   * Фрагмент кода, который обязан стоять в строке `line`. Нужен только тесту: номер строки
   * задан отдельно от листинга и молча уезжает при его правке, а якорь это ловит.
   */
  anchor?: string;
  /** Значение переменной `spinner` в этот момент — вся интрига демо в нём. */
  spinner: string;
  /** Что сейчас на стеке, одной строкой. */
  stack: string;
  out: ZalgoOut[];
}

/** Состояние кеша: промах (асинхронная ветка) или попадание (синхронная). */
export interface ZalgoMode {
  key: string;
  label: string;
  steps: ZalgoStep[];
  /** Вердикт — показывается, когда шаги пройдены. */
  verdict: string;
  tone: 'ok' | 'err';
}
