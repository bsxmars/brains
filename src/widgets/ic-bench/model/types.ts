/**
 * Типы замера цены обращения к свойству в разных состояниях inline cache.
 *
 * ⚠️ Слово «состояние» здесь — про **число форм в кольце**, которое мы задали сами, а не про
 * состояние площадки, вычитанное из движка. Состояние inline cache из JS не наблюдаемо: ни
 * в браузере, ни в Node без `--allow-natives-syntax` у самого бинарника. Поэтому в типах нет
 * поля «monomorphic/megamorphic как факт от V8» — есть только то, что мы задали на входе
 * (`shapes`), и то, что получили на выходе (`ms`, `ratio`).
 */

/** Подопытный объект: поле `x` читают все случаи, остальные поля различают формы. */
export type Sample = { x: number; [rest: string]: number };

/** Случай замера: сколько разных форм лежит в кольце. */
export interface IcCaseSpec {
  key: string;
  /** Подпись столбика: «1 форма», «5 форм». */
  label: string;
  /** Сколько разных скрытых классов попадёт в кольцо. */
  shapes: number;
  /** Что мы ожидаем от площадки при таком числе форм — наше рассуждение, не ответ движка. */
  what: string;
  tone: 'ok' | 'err';
}

/** Параметры прогона. `ring` обязан быть степенью двойки: по нему считается маска. */
export interface BenchOptions {
  /** Сколько чтений поля в одном замере. */
  iterations: number;
  /** Сколько объектов в кольце. Степень двойки. */
  ring: number;
  /** Сколько замеров каждого случая; наружу идёт медиана. */
  runs: number;
  /** Сколько холостых прогонов до первого замера — числа снимаются с горячего кеша. */
  warmups: number;
}

/** Кольца и маска, подготовленные и прогретые. */
export interface Prepared {
  rings: Sample[][];
  mask: number;
  options: BenchOptions;
}

/** Один круг: все случаи подряд. Круг целиком, а не случай целиком, — см. `benchRound`. */
export interface RoundResult {
  /** Миллисекунды по случаям, в порядке `IC_CASES`. */
  ms: number[];
  /** Накопленные суммы — доказательство, что цикл не выброшен. */
  sums: number[];
}

/** Строка итоговой таблицы. */
export interface IcBenchRow extends IcCaseSpec {
  /** Медиана замеров, мс. Машинозависима. */
  ms: number;
  /** Во сколько раз дороже мономорфного случая. Это и переживает смену железа. */
  ratio: number;
  /** Сумма, накопленная циклом. */
  sum: number;
}

export interface IcBenchResult {
  /** Замер состоялся. `false` — в среде нет `performance.now`, числа не снимались. */
  ok: boolean;
  rows: IcBenchRow[];
  options: BenchOptions;
  /** Все случаи накопили одну и ту же сумму — значит считали одно и то же и никто не выброшен. */
  sumsAgree: boolean;
  /** Сумма, общая для всех случаев (или сумма первого случая, если они разошлись). */
  sum: number;
  /** Главное число: во сколько раз мегаморфный случай дороже мономорфного. */
  headline: number;
  note: string;
}
