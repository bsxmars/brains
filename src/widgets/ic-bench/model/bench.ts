/**
 * Значения по умолчанию.
 *
 * `iterations` подобрано так, чтобы мономорфный случай занимал заметно больше разрешения
 * таймера (в браузерах `performance.now` огрублён), а весь прогон укладывался примерно
 * в секунду-полторы: демо запускает читатель, и поток на это время занят.
 */
export const DEFAULTS: BenchOptions = {
  iterations: 6_000_000,
  ring: 256,
  runs: 5,
  warmups: 3,
};

/* ---------------------------------------------------------------------------------------- *
 * Пять читалок. Тела дословно одинаковы — так и задумано: единственное различие между ними
 * в том, что каждая видит только своё кольцо, то есть своё число форм. Объединять их нельзя
 * (ловушка 1), сокращать через фабрику — тоже.
 * ---------------------------------------------------------------------------------------- */

function readMono(ring: Sample[], n: number, mask: number): number {
  let s = 0;
  for (let i = 0; i < n; i++) s += ring[i & mask].x;
  return s;
}

function readPoly2(ring: Sample[], n: number, mask: number): number {
  let s = 0;
  for (let i = 0; i < n; i++) s += ring[i & mask].x;
  return s;
}

function readPoly4(ring: Sample[], n: number, mask: number): number {
  let s = 0;
  for (let i = 0; i < n; i++) s += ring[i & mask].x;
  return s;
}

function readMega5(ring: Sample[], n: number, mask: number): number {
  let s = 0;
  for (let i = 0; i < n; i++) s += ring[i & mask].x;
  return s;
}

function readMega20(ring: Sample[], n: number, mask: number): number {
  let s = 0;
  for (let i = 0; i < n; i++) s += ring[i & mask].x;
  return s;
}

/** Порядок обязан совпадать с `IC_CASES`: по индексу связываются кольцо, читалка и строка. */
const READERS = [readMono, readPoly2, readPoly4, readMega5, readMega20];

/**
 * Куда уходит результат прогрева.
 *
 * Прогревочные вызовы никто не читает, и без этого стока их разрешено выбросить целиком —
 * тогда «прогрева» бы не было, а числа остались бы холодными. Значение выдаётся наружу
 * `warmupSink()`, поэтому сток наблюдаем и исчезнуть не может.
 */
let sink = 0;

/** Сумма, накопленная прогревом. Нужна только затем, чтобы прогрев нельзя было выбросить. */
export function warmupSink(): number {
  return sink;
}

/** Есть ли в среде часы. Ветка «среды нет» честная: числа не выдумываются, а не показываются. */
export function timerReady(): boolean {
  return typeof performance !== 'undefined' && typeof performance.now === 'function';
}

/**
 * Кольцо из `size` объектов, в котором по кругу чередуются `shapes` разных форм.
 *
 * Значение `x` равно индексу и от формы не зависит — поэтому сумма по кольцу одинакова
 * у всех пяти случаев, и расхождение сумм на странице означало бы поломку замера.
 */
export function makeRing(shapes: number, size: number): Sample[] {
  const ring: Sample[] = [];
  for (let i = 0; i < size; i++) ring.push(SHAPES[i % shapes](i));
  return ring;
}

/** Кольца построены, код прогрет. После этого можно мерить. */
export function prepare(options: BenchOptions = DEFAULTS): Prepared {
  const rings = IC_CASES.map((item) => makeRing(item.shapes, options.ring));
  const mask = options.ring - 1;

  for (let w = 0; w < options.warmups; w++) {
    for (let c = 0; c < READERS.length; c++) {
      sink += READERS[c](rings[c], options.iterations, mask);
    }
  }

  return { rings, mask, options };
}

/**
 * Один круг: все пять случаев подряд, по одному замеру каждому.
 *
 * Кругами, а не «пять замеров одного случая, потом пять другого», намеренно. Машина читателя
 * не изолирована: вкладка уходит в фон, вентилятор раскручивается, частота плавает. Если
 * мерить случаи подряд блоками, весь этот дрейф целиком ложится на разницу между случаями —
 * последний случай выглядел бы дороже просто потому, что он последний. Круги размазывают
 * дрейф по всем случаям поровну, а медиана по кругам его срезает.
 */
export function benchRound(prepared: Prepared): RoundResult {
  const ms: number[] = [];
  const sums: number[] = [];

  for (let c = 0; c < READERS.length; c++) {
    const start = performance.now();
    const sum = READERS[c](prepared.rings[c], prepared.options.iterations, prepared.mask);
    ms.push(performance.now() - start);
    sums.push(sum);
  }

  return { ms, sums };
}

/** Медиана: одиночный выброс на занятой машине не должен решать исход. */
function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
}

/** Свести круги в таблицу: медиана по случаю и кратность к мономорфному. */
export function summarise(rounds: RoundResult[], options: BenchOptions): IcBenchResult {
  const rows: IcBenchRow[] = IC_CASES.map((item, c) => ({
    ...item,
    ms: median(rounds.map((round) => round.ms[c])),
    sum: rounds[0].sums[c],
    ratio: 0,
  }));

  const base = rows[0].ms;
  for (const row of rows) row.ratio = base > 0 ? row.ms / base : 0;

  const sums = rows.map((row) => row.sum);
  const sumsAgree = sums.every((value) => value === sums[0]);

  return {
    ok: true,
    rows,
    options,
    sumsAgree,
    sum: sums[0],
    headline: rows[rows.length - 1].ratio,
    note: sumsAgree
      ? 'Все пять случаев накопили одну и ту же сумму — значит считали одно и то же, и цикл никто не выбросил.'
      : 'Суммы разошлись: случаи посчитали разное, числам верить нельзя.',
  };
}

/** Замер не состоялся: часов в среде нет. Числа не выдуманы, а отсутствуют. */
export function unavailable(options: BenchOptions = DEFAULTS): IcBenchResult {
  return {
    ok: false,
    rows: IC_CASES.map((item) => ({ ...item, ms: 0, ratio: 0, sum: 0 })),
    options,
    sumsAgree: false,
    sum: 0,
    headline: 0,
    note: 'В этой среде нет `performance.now` — мерить нечем, и придуманных чисел здесь не будет.',
  };
}

/**
 * Полный прогон одним вызовом: подготовка, прогрев, круги, сведение.
 *
 * Это и есть точка входа юнит-теста. Тест закрепляет **отношение, а не миллисекунды**:
 * абсолютные числа машинозависимы, и тест, сверяющий их дословно, краснел бы от смены
 * железа, а не от ошибки.
 *
 * ⚠️ Функция синхронная и занимает поток на всё время прогона. Компонент зовёт не её,
 * а `prepare` и `benchRound` по кругам, отпуская поток между ними, — иначе страница
 * замирает и «идёт замер» никто не увидит.
 */
export function runIcBench(partial: Partial<BenchOptions> = {}): IcBenchResult {
  const options = { ...DEFAULTS, ...partial };
  if (!timerReady()) return unavailable(options);

  const prepared = prepare(options);
  const rounds: RoundResult[] = [];
  for (let r = 0; r < options.runs; r++) rounds.push(benchRound(prepared));

  return summarise(rounds, options);
}
