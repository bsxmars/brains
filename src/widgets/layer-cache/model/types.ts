/**
 * Данные демо «что кеш решит пересобрать».
 *
 * ⚠️ Всё, что здесь лежит, — **снятые числа**, а не модель. Демо перематывает уже случившуюся
 * сборку: секунды и байты приехали из `docker build --progress=plain` и `docker history`,
 * а не из формулы. Поэтому у шага нет поля «примерно столько»: если число не снято, шага
 * в данных быть не должно.
 */

/** Состояние слоя в пересборке: взят из кеша или посчитан заново. */
export type LayerState = 'cached' | 'rebuilt';

/** Один шаг сборки — одна инструкция Dockerfile. */
export interface LayerStep {
  /** Инструкция как она написана в файле. */
  instruction: string;
  /** Что она делает — одной фразой, для колонки слоёв. Разрешена строчная разметка. */
  what: string;
  state: LayerState;
  /** Сколько шаг занял в замере, секунды. У шага из кеша это ноль по определению. */
  seconds: number;
  /**
   * Вес слоя в байтах.
   *
   * Ноль — у слоёв, которые не кладут ни одного файла: `WORKDIR`, `ENV`, `USER`, `CMD`
   * меняют только конфиг образа. Это не «мало», а «нисколько», и показывать их надо иначе,
   * чем слой на сто килобайт.
   */
  bytes: number;
}

/** Один прогон: этот Dockerfile при этом изменении. */
export interface BuildRun {
  /** Ключ сценария изменения — см. `ChangeOption.key`. */
  change: string;
  steps: LayerStep[];
  /**
   * Время всей сборки по часам снаружи, секунды.
   *
   * Оно больше суммы шагов: сюда входят передача контекста, разбор Dockerfile и экспорт
   * образа. Сумма шагов отвечает на вопрос «за что заплатили», это число — «сколько ждали».
   */
  total: number;
}

/** Вариант Dockerfile: тот же образ, другой порядок инструкций. */
export interface BuildVariant {
  key: string;
  /** Подпись переключателя. Разметки здесь быть не должно: это текст кнопки. */
  label: string;
  /** Чем этот порядок отличается и чем он за это платит. Разрешена строчная разметка. */
  note: string;
  runs: BuildRun[];
}

/** Что читатель изменил перед пересборкой. */
export interface ChangeOption {
  key: string;
  /** Подпись переключателя. Разметки здесь быть не должно. */
  label: string;
  /** Что именно тронули. Разрешена строчная разметка. */
  note: string;
}
