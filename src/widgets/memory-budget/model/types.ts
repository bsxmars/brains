/**
 * Бюджет памяти контейнера: из чего складывается `rss` и как он соотносится с лимитом.
 *
 * Вся арифметика урока держится на двух числах, которые в мониторинге стоят далеко друг от
 * друга: лимит контейнера и потолок кучи. Поэтому они лежат в одном объекте — чтобы подпись
 * «V8 разрешено больше, чем поду» считалась, а не писалась руками.
 */
export interface BudgetPart {
  /** Подпись доли. */
  label: string;
  mb: number;
  /** Чем эта доля является: куча, вне кучи или неучтённое. */
  kind: 'heap' | 'off-heap' | 'other';
}

export interface Budget {
  label: string;
  /** Лимит контейнера, МБ. Это число видит ядро. */
  limitMb: number;
  /** `heap_size_limit` процесса, МБ. Это число видит V8. */
  heapLimitMb: number;
  /** Откуда взялся потолок: умолчание или явный флаг. */
  heapLimitFrom: string;
  /** Разложение rss. Сумма и есть rss. */
  parts: BudgetPart[];
  tone: 'ok' | 'warn' | 'err';
  verdict: string;
  /** Чем кончилось — с кодом выхода, если случай доведён до падения. */
  outcome?: string;
}
