/** Тон шага: цвет здесь говорит, сколько стоит происходящее. */
export type GcTone = 'ok' | 'warn' | 'err' | 'info';

/** Блок в полупространстве: занятая область известного размера и известной судьбы. */
export interface HeapBlock {
  id: string;
  label: string;
  /** Размер, КБ. Он же задаёт ширину блока на дорожке. */
  size: number;
  /** Живой — то есть достижимый от корней. Мёртвый сборщик не обойдёт вовсе. */
  live: boolean;
}

/** Шаг сценария «что происходит с объектом от аллокации до вечности». */
export interface GcStep {
  phase: string;
  message: string;
  cost: string;
  tone: GcTone;
  /**
   * Активное полупространство — то, в которое идут аллокации (to-space).
   * Второе в этот момент пустует и ждёт следующей сборки (from-space).
   */
  active: 'a' | 'b';
  a: HeapBlock[];
  b: HeapBlock[];
  old: HeapBlock[];
  /** Молодое и старое пространства больших объектов: туда объект попадает минуя копирование. */
  los: HeapBlock[];
  /** Подпись ребра «старое → молодое», когда задействован remembered set. */
  remembered?: string;
  /** Скопировано байт нарастающим итогом, КБ — цена выживания. */
  copied: number;
  /** Освобождено байт нарастающим итогом, КБ — то, что не стоило ничего. */
  freed: number;
}
