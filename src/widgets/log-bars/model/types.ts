/**
 * Полосы на логарифмической шкале.
 *
 * Нужны там, где величины разъезжаются на три порядка. На линейной шкале такой ряд
 * вырождается: три первых значения превращаются в одинаковые ниточки у левого края,
 * и главное — что рост экспоненциальный — как раз и пропадает. На логарифмической
 * равные множители дают равные приращения длины, поэтому экспонента видна как прямая.
 */
export interface LogBar {
  /** Подпись слева. */
  label: string;
  /** Значение на шкале; строго больше нуля. */
  value: number;
  /** Как значение показать человеку — с единицами. */
  text: string;
  tone?: 'ok' | 'warn' | 'err';
}
