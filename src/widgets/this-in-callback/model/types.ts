/**
 * `this` в колбэке — вычислением, а не пересказом.
 *
 * Раздел утверждает восемь вещей о семантике языка («здесь `this` потеряется», «здесь придёт
 * элемент», «здесь объект уцелеет»). Такие утверждения нельзя держать литералом: они расходятся
 * с движком молча. Поэтому демо выполняет каждый случай по-настоящему, а типы ниже описывают
 * **результат прогона**, а не заранее написанный ответ.
 */

/** Восемь способов передать метод в чужой код. */
export type ThisCaseKey =
  | 'torn'
  | 'destructured'
  | 'listener'
  | 'bind'
  | 'arrowField'
  | 'arrowWrapper'
  | 'thisArg'
  | 'handleEvent';

/**
 * Чем кончилось.
 *
 * Трёх исходов, а не двух: между «объект на месте» и «потеряли совсем» лежит самый опасный
 * случай — `this` есть, он просто чужой. Исключения нет, код едет дальше, а запрос уходит
 * не туда.
 */
export type ThisVerdict = 'ok' | 'warn' | 'err';

/** Описание случая: всё, что написано автором, — и ни одного утверждения о результате. */
export interface ThisCase {
  key: ThisCaseKey;
  label: string;
  /** Исходник — те же строки, что исполняются (без строчек записи `this`). */
  code: string[];
  /** Как выглядит точка вызова внутри чужого кода: от неё и зависит `this`. */
  site: string;
  /** Почему движок поступает именно так. Допускается строчная разметка — печатать через `Md`. */
  note: string;
  /** Чем за это платят: у каждого работающего способа своя цена. */
  cost: string;
  /**
   * Чего ждёт урок. Это единственное утверждение, оставшееся литералом, — и ровно его
   * сверяет юнит-тест с тем, что выдал движок.
   */
  expected: ThisVerdict;
  /** Случай выполняется только там, где есть DOM: в Node его проверять нечем. */
  needsDom?: boolean;
}

/** Нестрогая половина случая: то же самое, но вне strict. */
export interface SloppyRun {
  thisValue: string;
  read: string;
  returned: string;
}

/**
 * Итог одного настоящего прогона.
 *
 * ⚠️ `errorName` лежит отдельно от `error` намеренно: имя ошибки нормативно (`TypeError`),
 * а текст сообщения у каждого движка свой. Утверждать в тесте можно только имя, показывать
 * читателю — и то и другое.
 */
export interface ThisRun extends ThisCase {
  /** Что реально оказалось в `this` — описание настоящего значения, а не строка из данных. */
  thisValue: string;
  /** Совпал ли `this` с объектом, которому метод принадлежит. */
  isOwner: boolean;
  /** `this` потерян или подменён: главный признак раздела. */
  lost: boolean;
  /** Что дало обращение к `this` внутри колбэка: `this.base → "/v1"` либо `undefined`. */
  read: string;
  /** Что вернул вызов целиком. */
  returned: string;
  /** Имя ошибки — нормативная часть. Пустая строка — исключения не было. */
  errorName: string;
  /** Дословный текст от движка — для показа, не для утверждений. */
  error: string;
  /** Настоящий исход. Юнит-тест сверяет его с `expected`. */
  verdict: ThisVerdict;
  /** Нестрогая половина — есть только там, где strict меняет ответ. */
  sloppy: SloppyRun | null;
  /** Случай выполнился по-настоящему в DOM. `false` — DOM недоступен, показана пометка. */
  ranInDom: boolean;
  /** Факт, добытый прогоном рядом с основным: списки методов, повторная подписка и прочее. */
  extra: string;
}

/**
 * Старая форма данных раздела — восемь строк с заранее записанным ответом.
 *
 * ⚠️ Оставлена только ради совместимости: на неё ещё ссылается `THIS_OPTIONS`
 * в `src/content/lessons/callbacks/data.ts`. Демо её больше не читает — `value` и `tone`
 * теперь берутся из настоящего прогона (`model/run.ts`), а описание случаев живёт
 * в `model/cases.ts`. Когда `THIS_OPTIONS` уйдёт из урока, уйдёт и этот тип.
 *
 * Пометки `@deprecated` здесь намеренно нет: она зажгла бы предупреждение `ts(6385)`
 * на двух строках `data.ts` — файла, который этот виджет не правит.
 */
export interface ThisOption {
  label: string;
  code: string;
  site: string;
  value: string;
  tone: 'ok' | 'warn' | 'err';
  note: string;
  cost: string;
}
