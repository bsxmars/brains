/**
 * Замер одного поля во времени: подпись, значения и форма роста.
 *
 * `bars` — не украшение: диагноз ставится не по величине поля, а по тому, какой контур растёт
 * быстрее остальных. Три столбика — три замера подряд, нормированные внутри строки.
 */
export interface TriageRow {
  k: string;
  /** Значения крайних замеров, как их видно в логе. */
  v: string;
  /** Относительная высота столбиков, 0–100. */
  bars: number[];
  /** Строка, ради которой случай существует: она растёт. */
  hot: boolean;
}

/** Годится ли здесь heap snapshot — и почему. */
export interface TriageTool {
  works: boolean;
  text: string;
}

/** Случай продовой диагностики: какой контур растёт → что это значит → чем смотреть. */
export interface TriageCase {
  label: string;
  /** Диагноз одной строкой. */
  dx: string;
  tone: 'warn' | 'err';
  rows: TriageRow[];
  why: string;
  tool: TriageTool;
  /** Куда идти дальше: кандидаты и следующий шаг. */
  note: string;
}
