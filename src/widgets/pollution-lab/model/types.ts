/**
 * Prototype pollution вживую: наивный `merge`, вредоносная нагрузка и посторонний объект,
 * у которого вдруг появилось чужое свойство.
 */

/**
 * Защиты, перечисленные в уроке.
 *
 * `filter` — отклонять опасные ключи; `nullProto` — `Object.create(null)` под цель;
 * `freeze` — `Object.freeze(Object.prototype)`.
 */
export type PollutionFix = 'filter' | 'nullProto' | 'freeze';

/** На каком прототипе ставился опыт. */
export type PollutionVictim = 'Object.prototype' | 'stand-in';

/**
 * Итог одного настоящего слияния.
 *
 * ⚠️ `errorName` держится отдельно от `error`: имя ошибки нормативно, текст сообщения
 * у каждого движка свой.
 */
export interface PollutionRun {
  /** Какие защиты были включены. */
  fixes: PollutionFix[];
  /** Код, который исполнился, — собирается под включённые защиты. */
  code: string[];
  /** Вредоносная нагрузка, как она приходит от пользователя. */
  payload: string;
  /** Выражение, которым проверяли посторонний объект. */
  probe: string;
  /**
   * Что вернул посторонний объект. Главный ответ демо: `true` — свойство пришло к тому,
   * кого никто не трогал.
   */
  bystander: string;
  /** Пришло ли свойство постороннему. */
  polluted: boolean;
  /**
   * Собственные ключи цели после слияния.
   *
   * Пустой список при успешной атаке — самое неожиданное здесь: цель не получила **ничего**,
   * всё уехало в прототип.
   */
  targetKeys: string[];
  /** Прототип, который пробовали испортить. */
  victim: PollutionVictim;
  /** Почему прототип именно такой — честная пометка для случая с заморозкой. */
  victimNote: string;
  errorName: string;
  error: string;
  /** Трасса слияния — что читал и писал `merge`. */
  log: string[];
  verdict: string;
  tone: 'ok' | 'err';
}
