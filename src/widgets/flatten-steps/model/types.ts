/**
 * Пошаговое расплющивание дерева конкатенаций.
 *
 * Демо существует ради одного факта, который обычно опускают: flatten **не создаёт новый
 * объект и не меняет тип**. Поэтому тип на каждом шаге лежит в данных явно — и на всех шагах
 * он один и тот же.
 */
export interface FlattenStep {
  /** Подпись шага. */
  title: string;
  /** Выделен ли уже плоский буфер (он появляется раньше, чем в него скопирован первый лист). */
  allocated: boolean;
  /** Сколько листьев уже скопировано в плоский буфер — в порядке `order` виджета. */
  copied: number;
  /** Что лежит в поле `first` узла на этом шаге. */
  first: string;
  /** Что лежит в поле `second`. */
  second: string;
  /** Тип объекта по `%DebugPrint`. */
  type: string;
  message: string;
  tone?: 'info' | 'warn' | 'ok';
}
