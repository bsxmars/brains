/**
 * Разбор потока, разрезанного по опасной границе.
 *
 * Случай описывается только входом: чанки и объяснение, что в этой границе особенного.
 * Результат в данных не хранится намеренно — его считает демо, прогоняя оба разбора через
 * настоящие стримы. Записанный результат однажды разошёлся бы с кодом и врал бы убедительно.
 */
export interface SseCase {
  key: string;
  /** Подпись переключателя — коротко. */
  label: string;
  title: string;
  /** Поток как он приходит: каждый элемент — отдельный чанк, границы между ними и есть тема. */
  chunks: string[];
  /** Что происходит на этой границе. Разрешена строчная разметка. */
  note: string;
  /**
   * Ломается ли здесь наивный разбор.
   *
   * Это утверждение страницы, а не украшение: демо сверяет его с прогоном на каждом показе,
   * а `tests/unit/streams.test.ts` — на каждом `npm test`. Разошлось — покраснеет.
   */
  breaks: boolean;
}
