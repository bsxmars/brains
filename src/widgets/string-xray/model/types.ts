/**
 * «Рентген строки» — из чего состоит объект строки в каждом из представлений.
 *
 * Контракт описывает ровно то, что рисуется: заголовок объекта, ячейки содержимого по одному
 * или два байта, ссылка на чужой буфер и полоса удерживаемой памяти. Последняя и есть главный
 * смысл демо: тип отвечает на вопрос «как устроено», а удержание — «сколько это стоит».
 */

/** Поле в заголовке объекта строки: имя и значение. */
export interface RepField {
  name: string;
  value: string;
}

/** Буфер, на который ссылается узел: чужие байты, которые он удерживает живыми. */
export interface RepParent {
  /** Подпись буфера — «родитель, 100 000 символов». */
  label: string;
  /** Что показать в ячейках буфера; многоточие рисуется само. */
  cells: string[];
  /** Какая часть буфера попадает в саму строку — подсвечивается как окно. */
  window?: { from: number; to: number };
  note: string;
}

export interface StringRep {
  /** Подпись переключателя. */
  label: string;
  /** Код, который к этому представлению приводит. */
  code: string;
  /** Тип из `%DebugPrint`. */
  type: string;
  /** Семейство представления — от него зависит, что рисовать. */
  kind: 'seq' | 'cons' | 'sliced' | 'thin' | 'external';
  /** Байт на кодовую единицу: 1 для Latin-1, 2 для всего остального. */
  bytes: 1 | 2;
  /** Заголовок объекта: длина и ссылки. */
  header: RepField[];
  /** Ячейки собственного содержимого. Пусто у тех, кто байтов не хранит. */
  cells: string[];
  /** Буфер, который строка удерживает живым. */
  parent?: RepParent;
  /** Сколько памяти удерживается: подпись и доля полосы от 0 до 1. */
  holds: { text: string; share: number };
  /** Почему представление именно такое. */
  why: string;
  /** Чем за него платят. */
  cost: string;
  tone: 'ok' | 'warn' | 'err' | 'info';
  /** Чем проверено — или пометка, что проверить не удалось. */
  verified: string;
}
