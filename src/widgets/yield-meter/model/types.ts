/** Чем уступают поток. `micro` — контрольная линия: микрозадача поток не отпускает. */
export type YieldToolKey = 'timeout' | 'channel' | 'micro' | 'scheduler';

export type YieldTone = 'ok' | 'warn' | 'err' | 'info';

/**
 * Описание инструмента: что это, каким кодом и уступка ли это на самом деле.
 *
 * `yields: false` стоит ровно у одного — у `queueMicrotask`. Он меряется вместе со всеми
 * и показывается в той же таблице, но не как вариант: микрозадача не даёт браузеру ни кадра,
 * ни обработки ввода. Его строка нужна для контраста и заодно показывает пол измерения —
 * сколько стоит сама обвязка замера.
 */
export interface YieldToolSpec {
  key: YieldToolKey;
  label: string;
  /** Уступает ли этот способ поток на самом деле. */
  yields: boolean;
  /** Выражение, которое исполняется в цикле замера. Ровно оно, а не пересказ. */
  code: string;
  /** Чем этот способ отличается от соседей. */
  note: string;
  /** Что сказать, если в этой среде такого API нет вовсе. */
  absent: string;
}

/**
 * Результат замера одного инструмента.
 *
 * Все числа сняты, ни одно не записано заранее. `ratio` — единственное, что переживает смену
 * железа: абсолютные `perSecond` и `perYieldMs` зависят от машины, браузера и нагрузки.
 */
export interface YieldMeasure {
  key: YieldToolKey;
  label: string;
  yields: boolean;
  code: string;
  note: string;
  /**
   * Замер состоялся: API нашлось и цикл провернулся.
   *
   * `false` — не ошибка демо, а честный ответ. Ветка существует затем, чтобы модуль можно было
   * импортировать откуда угодно, включая серверный рендер острова и юнит-тест в Node.
   */
  available: boolean;
  /** Почему замера нет. Пусто, если он есть. */
  unavailable: string;
  /** Сколько уступок уложилось в окно. */
  iterations: number;
  /** Сколько окно длилось на самом деле, мс. */
  spanMs: number;
  /** Средняя цена одной уступки, мс: `spanMs / iterations`. */
  perYieldMs: number;
  /** Уступок в секунду — то же число с другой стороны. */
  perSecond: number;
  /** Во сколько раз дороже базы — самого дешёвого **настоящего** способа уступить. */
  ratio: number;
  tone: YieldTone;
}

/** Условия замера. Без них число — не результат, а цифра. */
export interface YieldConditions {
  /** Заказанное окно на инструмент, мс. */
  windowMs: number;
  /** Холостой прогон перед замером, мс. Его результат отбрасывается. */
  warmupMs: number;
  /** Сколько заняли все замеры вместе, мс. */
  totalMs: number;
  /** Вкладка была скрыта — браузер душит таймеры, и числу верить нельзя. */
  hidden: boolean;
}

/** Итог всего прогона. */
export interface YieldReport {
  measured: boolean;
  conditions: YieldConditions;
  rows: YieldMeasure[];
  /**
   * От чего считаются кратности: самый дешёвый способ, который поток **действительно отпускает**.
   *
   * Не «самый дешёвый вообще» — иначе базой стала бы микрозадача, а мерить относительно того,
   * что уступкой не является, значит сравнивать с нулём. У неё самой кратность выходит меньше
   * единицы, и это верный ответ: она дешевле любой уступки ровно потому, что не уступает.
   */
  base: YieldToolKey | null;
  /** Самый дешёвый из померенных вообще — пол измерения. */
  floor: YieldToolKey | null;
  verdict: string;
  tone: YieldTone;
}

/** Параметры прибора. Их задаёт автор темы пропами — модель работает и без них. */
export interface YieldParams {
  windowMs?: number;
  warmupMs?: number;
}
