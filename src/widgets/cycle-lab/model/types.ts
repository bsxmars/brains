/** Как объявлено то, что модули цикла берут друг у друга. */
export type CycleVariant = 'fn' | 'const';

/**
 * Результат одного прогона цикла — снятый с движка, а не записанный заранее.
 *
 * Прогон ровно один на загрузку страницы, и это не ограничение демо, а свойство платформы:
 * модуль исполняется один раз на URL, а результат — успех он или ошибка — остаётся в карте
 * модулей навсегда. Поэтому здесь же лежит и то, что вернула вторая попытка.
 */
export interface CycleRun {
  variant: CycleVariant;
  /** Строки, которые модули успели записать в общий журнал до конца или до падения. */
  trace: string[];
  /** Что сказал движок. `null` — цикл прошёл целиком. */
  error: string | null;
  /** Что вернул повторный `import()` того же URL: тот же namespace или то же исключение. */
  again: string;
  /** Пополнился ли журнал на второй попытке. Ноль означает «тело не перевыполнялось». */
  addedOnSecondTry: number;
  /** Исходники, вычитанные с сервера: на странице показано ровно то, что исполнилось. */
  sources: { name: string; code: string }[];
}
