/**
 * Вид матрицы. Их две, и различаются они не цветом, а тем, что означает «нет».
 *
 *   allow — что операция ещё разрешает («да» / «нет»). Новость здесь — запрет, поэтому
 *           красным горит «нет», а «да» остаётся нейтральным;
 *   see   — кто какие ключи видит при перечислении («✓» / «—»). Новость — видимость,
 *           поэтому зелёным горит «✓».
 */
export type MatrixMode = 'allow' | 'see';

/** Строка матрицы: подпись слева и булевы ячейки по колонкам заголовка. */
export interface MatrixRow {
  name: string;
  cells: boolean[];
}
