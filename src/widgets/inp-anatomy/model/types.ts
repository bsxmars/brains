/**
 * Часть метрики INP.
 *
 * `share` — доля фазы на полосе. Число иллюстративное: у каждого интерфейса раскладка своя,
 * и смысл картинки в том, какая фаза чем лечится, а не в конкретных процентах.
 */
export interface InpPart {
  k: string;
  what: string;
  /** Чем лечится именно эта фаза. */
  fix: string;
  share: number;
  tone: 'err' | 'info' | 'warn';
}
