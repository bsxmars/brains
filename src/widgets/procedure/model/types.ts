/**
 * Шаг процедуры.
 *
 * Поля те же, что лежали в данных уроков с самого начала: номер, что делать и зачем.
 * Виджет ничего не добавляет к содержанию — он меняет способ читать его.
 */
export interface ProcedureStep {
  /** Номер шага: «1», «2». Строкой, потому что он и печатается как есть. */
  n: string;
  /** Что делать. */
  t: string;
  /** Зачем это нужно и что отсекает. Разрешена строчная разметка. */
  why: string;
}
