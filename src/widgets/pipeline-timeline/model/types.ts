/**
 * Конвейер GitHub Actions, снятый с прогона.
 *
 * Здесь нет «нарисованного» времени: каждая отметка — строка `::mark::` из лога `act`, а `start`
 * и `end` — миллисекунды от первого шага прогона. Демо не запускает конвейер (в браузере его
 * не запустить и незачем притворяться), оно **перематывает записанный прогон**, и подпись под
 * демо говорит об этом прямо.
 *
 * Три сценария — это одна и та же работа, разложенная тремя способами: пятью шагами в одном
 * джобе, пятью джобами с `needs` и матрицей из трёх шардов. Вся тема держится на том, что видно
 * из разницы их шкал: где проходит граница и что через неё не проходит.
 */

/** Что именно пересекли, чтобы попасть в этот шаг. */
export type Boundary =
  /** Соседний шаг того же джоба: та же машина, та же файловая система, другой процесс оболочки. */
  | 'step'
  /** Другой джоб: другая машина, пустая рабочая директория, ничего общего, кроме `outputs`. */
  | 'job'
  /** Первый шаг прогона — пересекать нечего. */
  | 'start';

/**
 * Замер, снятый прямо в шаге.
 *
 * `k` — что спрашивали, `v` — что напечатал шаг **дословно**, `ok` — доехало или нет. Значения
 * не пересказаны: строка `[EMPTY]` в `v` означает, что в логе прогона стоит ровно `[EMPTY]`.
 */
export interface Probe {
  k: string;
  v: string;
  ok: boolean;
}

/** Один шаг на шкале. */
export interface DemoStep {
  /** Имя джоба из `jobs:` — оно же дорожка на шкале. */
  job: string;
  /** Имя шага. */
  step: string;
  /** Миллисекунды от первой отметки прогона. */
  start: number;
  end: number;
  /** Что пересекли перед этим шагом. */
  boundary: Boundary;
  /**
   * Чьего конца этот шаг дожидался.
   *
   * Не «предыдущий по времени», а именно тот, из-за которого шаг не мог начаться раньше:
   * соседний шаг своего джоба или последний шаг джоба из `needs`. У параллельных джобов
   * предыдущий по времени — сосед, а не причина, и цена границы, посчитанная от него,
   * получилась бы отрицательной.
   */
  after?: { job: string; step: string };
  /** Во сколько обошлась граница: от конца шага из `after` до начала этого, мс. */
  cost: number;
  /** Подпись кадра — одна строка о том, что здесь происходит. */
  say: string;
  /** Что шаг напечатал про доехавшее состояние. */
  probes?: Probe[];
  /** Что случилось в промежутке перед шагом, если это не только поднятие машины. */
  note?: string;
}

/** Один из трёх способов разложить одну и ту же работу. */
export interface Scenario {
  id: string;
  /** Подпись переключателя. */
  label: string;
  /** Имя файла workflow — по нему прогон можно повторить. */
  workflow: string;
  /** Где лежит запись. */
  fixture: string;
  /** Одна фраза о том, чем эта раскладка отличается от соседних. */
  note: string;
  steps: DemoStep[];
  /** Вердикт под шкалой — появляется на последнем кадре. */
  verdict: string;
  verdictTone: 'ok' | 'err';
}
