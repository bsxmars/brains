/** Готовый фрагментный шейдер, который читатель может собрать как есть — или переписать. */
export interface ShaderPreset {
  /** Подпись на переключателе. */
  label: string;
  /**
   * Полный текст фрагментного шейдера, начиная с `#version 300 es`.
   *
   * ⚠️ Директива обязана быть первой строкой кода читателя, а не приписываться демо сверху:
   * компилятор считает строки от начала переданного текста, и приписанная преамбула сдвинула бы
   * все номера в логе. Пусть читатель видит ровно тот текст, о котором говорит компилятор.
   */
  code: string;
  /** Что автор предлагает заметить. */
  note?: string;
}
