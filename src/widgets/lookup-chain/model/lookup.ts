import type { ChainNode, LookupStep } from './types';

/**
 * Разбор `[[Get]]` по шагам — ровно тот обход, что делает движок.
 *
 * Функция чистая и живёт отдельно от компонента, чтобы её мог прогнать тест: цепочка,
 * нарисованная на странице, обязана совпадать с тем, что реально возвращает объект
 * из `data.ts`. Ошибка в порядке шагов иначе видна только глазами, а глаза устают.
 *
 * Отличие от оригинала одно, и оно по существу. В бандле аксессором был `age` — собственное
 * свойство самого `dog`, и шаг заявлял «вызываем get с this = Receiver, а не с объектом, где
 * нашли», хотя это один и тот же объект и разницы не видно. Здесь аксессор есть и в прототипе
 * (`label` на `Animal.prototype`), и текст шага различает два случая: пока свойство нашлось
 * на месте, `Receiver` совпадает с владельцем, и вся соль — в случае, когда не совпадает.
 */
export function buildLookup(
  chain: ChainNode[],
  key: string,
  values: Record<string, string>,
): LookupStep[] {
  const root = chain[0]?.name ?? 'obj';

  const steps: LookupStep[] = [
    {
      msg: `${root}.${key}: чтение начинается с самого ${root}. Он и есть Receiver — объект, с которого начали.`,
      lvl: -1,
    },
  ];

  for (let i = 0; i < chain.length; i++) {
    const node = chain[i];
    const found = node.keys.includes(key);

    /*
     * ⚠️ Имя операции из спецификации печатается ОДИН раз, на первом звене. Раньше оно стояло
     * в каждом шаге — у длинной цепочки журнал превращался в столбик `[[GetOwnProperty]]`,
     * в котором менялось только имя объекта. Читателю этого уровня имя нужно один раз:
     * чтобы узнать его, встретив в спецификации.
     */
    steps.push({
      msg:
        i === 0
          ? `Смотрим собственные ключи ${node.name} — операция [[GetOwnProperty]] → ${found ? 'ключ есть' : 'ключа нет'}`
          : `Смотрим собственные ключи ${node.name} → ${found ? 'ключ есть' : 'ключа нет'}`,
      lvl: i,
      found,
    });

    if (found) {
      const isAccessor = node.accessors?.includes(key) ?? false;
      steps.push({
        lvl: i,
        found: true,
        res: values[key],
        tone: 'ok',
        msg: isAccessor
          ? i === 0
            ? `Дескриптор — accessor, и найден он на самом ${root}. Вызываем get с this = Receiver; здесь владелец и Receiver — один объект, разницы не видно.`
            : `Дескриптор — accessor. Вызываем get с this = Receiver (${root}), а не с ${node.name}, где свойство нашлось. Иначе унаследованный геттер читал бы поля прототипа вместо полей экземпляра.`
          : `Дескриптор — data. Возвращаем value.${i > 0 ? ' Свойство унаследовано, но вызывается как родное: копирования не было, объект один на всех.' : ''}`,
      });
      return steps;
    }

    steps.push({
      msg: `Переходим по [[Prototype]] в ${chain[i + 1]?.name ?? 'null'}`,
      lvl: i,
    });
  }

  /* ⚠️ Из этого шага убрана фраза «Опечатка не падает громко, а тихо портит всё, что считается
     дальше»: она дословно повторяла карточку под демо. */
  steps.push({
    msg: 'Цепочка кончилась на null. Возвращаем undefined — исключения здесь не будет.',
    lvl: chain.length,
    res: 'undefined',
    tone: 'warn',
  });

  return steps;
}
