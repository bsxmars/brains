/** Узел цепочки прототипов: имя, подпись и собственные ключи. */
export interface ChainNode {
  name: string;
  /** Подпись под именем: «экземпляр», «объект», «конец цепочки». */
  tag: string;
  keys: string[];
  /**
   * Какие из ключей — аксессоры. Нужно не для украшения: именно на аксессоре видно, что
   * геттер вызывается с `this = Receiver`, а не с объектом, где свойство нашлось.
   */
  accessors?: string[];
}

/**
 * Шаг разбора `[[Get]]`.
 *
 * `lvl` адресует узел цепочки: `-1` — поиск ещё не начался, `0…n-1` — индекс узла,
 * `n` — цепочка кончилась на `null`. Магического числа вроде `99` здесь нет намеренно:
 * длину цепочки задают данные урока, а не виджет.
 */
export interface LookupStep {
  msg: string;
  lvl: number;
  /** Нашлось ли свойство на этом узле — красит вердикт под узлом. */
  found?: boolean;
  /** Что вернул `[[Get]]`. Есть только у последнего шага. */
  res?: string;
  tone?: 'ok' | 'warn';
}
