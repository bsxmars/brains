/**
 * `getComputedStyle` возвращает не computed value, а **resolved value** — и определено оно
 * отдельно для каждого свойства: для большинства это computed, для геометрии — used,
 * то есть значение, которое существует только после лейаута.
 *
 * Демо читает свойства с живого элемента прямо на странице читателя и показывает, что
 * вернулось. Ключевой опыт — спрятать элемент: у него пропадает бокс, used value браться
 * неоткуда, и `width` возвращается к computed, то есть к `auto`.
 */

/** Свойство, которое демо читает с подопытного элемента. */
export interface ResolvedProp {
  /** Имя свойства — его же виджет спрашивает у `getComputedStyle`. */
  name: string;
  /** На какой стадии определено resolved value этого свойства. */
  stage: 'computed' | 'used';
  /** Что написано в таблице стилей демо — чтобы было видно, во что оно превратилось. */
  declared: string;
  /** Пояснение. Разрешена строчная разметка. */
  note: string;
}
