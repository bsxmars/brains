/** Строка таблицы гарантий: есть ли она у голого колбэка, есть ли у промиса и за счёт чего. */
export interface GuaranteeRow {
  name: string;
  /** Ответ за колбэк — в этой таблице всегда «нет». */
  cb: string;
  /** Ответ за промис: «да» почти везде, кроме последней строки. */
  pr: string;
  /** Механизм спеки, которым гарантия обеспечена. */
  how: string;
}

/** Строка сравнения «что нужно → чего это стоит на колбэках и на промисах». */
export interface CompareRow {
  need: string;
  cb: string;
  pr: string;
  /** `true`, если на промисах это тоже ручная работа: тогда ячейка не зелёная, а янтарная. */
  manual?: boolean;
}
