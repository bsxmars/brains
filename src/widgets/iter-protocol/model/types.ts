/**
 * Протокол итерации, снятый с движка: один шаг — один вызов, который потребитель делает итератору.
 *
 * Шаг хранит не только вызов и ответ, но и **состояние на момент после вызова**: счётчики,
 * собранные значения, напечатанное. Иначе прокрутка ползунком врала бы: журнал показывал бы
 * прошлое, а счётчики — конец прогона.
 */

/** Ключ сценария. Он же значение переключателя. */
export type IterScenarioKey = 'factory' | 'once' | 'break' | 'destructure';

export type StepTone = 'info' | 'ok' | 'warn' | 'err';

export interface ProtocolStep {
  /** Вызов, как его делает потребитель: `g[Symbol.iterator]()`, `next()`, `return()`. */
  call: string;
  /** Что ответил движок. Строка собрана из настоящего `{ value, done }`, а не написана заранее. */
  result: string;
  /** Почему так. Строчная разметка — выводится через `Md`. */
  note: string;
  tone?: StepTone;
  /** Строка листинга, на которой сейчас стоит протокол. `-1` — ни одной. */
  line: number;
  /** Сколько раз к этому моменту вызван `next()`. Счётчик ведёт сам итератор. */
  next: number;
  /** То же для `return()`. */
  ret: number;
  /** Индекс прохода, к которому относится шаг. */
  pass: number;
  /** Что этот проход собрал к этому моменту: `[0, 1]`. */
  got: string;
  /** Что демонстрируемый код напечатал к этому моменту. */
  out: string[];
}

/** Один заход потребителя: `[...it]`, `for…of`, деструктуризация. */
export interface PassResult {
  /** Подпись прохода: `проход 1 · [...it]`. */
  label: string;
  /** Что проход собрал: `[0, 1, 2]`. */
  got: string;
}

/** Прогон сценария целиком — то, что компонент показывает, а юнит-тест сверяет. */
export interface ProtocolRun {
  key: IterScenarioKey;
  steps: ProtocolStep[];
  passes: PassResult[];
  /** Итоговое число вызовов `next()` за прогон. */
  next: number;
  /** Итоговое число вызовов `return()` за прогон. */
  ret: number;
  /** Что демонстрируемый код напечатал за прогон. */
  out: string[];
  verdict: string;
  tone: StepTone;
}

/** Описание сценария без его исполнения: то, что можно показать до гидратации острова. */
export interface IterScenarioMeta {
  key: IterScenarioKey;
  /** Подпись в переключателе. */
  label: string;
  /** Листинг — тот самый код, который исполняется. */
  code: string[];
  /** Сценарий что-то печатает: у его итератора есть `finally`. */
  prints: boolean;
}
