/** Поля memoryUsage: rss относится ко всему процессу, остальные — к текущему изоляту.
 * Зоны — категории учёта, а не разбиение резидентных страниц rss на непересекающиеся части.
 */
export interface MemoryField {
  key: 'rss' | 'heapTotal' | 'heapUsed' | 'external' | 'arrayBuffers';
  /** Внешний контур, внутри V8 heap или вне его. */
  zone: 'outer' | 'heap' | 'off-heap';
  /** Точный смысл поля. */
  what: string;
  /** На что указывает рост именно этого поля. */
  growth: string;
  /**
   * Ограничивает ли это значение `--max-old-space-size`. Отдельным полем, а не строкой
   * в тексте: ради этого ответа половина урока и написана.
   */
  capped: string;
  /** Замер: по процессу поле или по текущему потоку. Проверено запуском на воркере. */
  scope: string;
  tone?: 'warn' | 'err';
}
