/**
 * Данные демо «живой граф зависимостей».
 *
 * Сам граф виджет не принимает данными и принять не может: он строится из **настоящих**
 * `reactive`, `computed` и `effect` из `@vue/reactivity`, которые живут внутри виджета.
 * Отсюда отсюда и деление: код — в виджете, слова про код — здесь.
 *
 * `id` в обеих структурах не подпись, а ключ: по нему виджет находит настоящее действие
 * и настоящий узел. Придумать новый `id` в `data.ts` нельзя — типы не дадут.
 */

/** Кнопка записи. Каждой соответствует одна строка кода внутри виджета. */
export interface GraphWrite {
  id: 'price-up' | 'qty-up' | 'price-cheap' | 'note' | 'detailed' | 'price-same';
  /** Подпись кнопки — она же выполняемая операция. */
  label: string;
  /** Что должно произойти. Проверяется не на слово: рядом стоят счётчики прогонов. */
  note: string;
}

/** Узел-подписчик: `computed` или эффект. */
export interface GraphNode {
  id: 'total' | 'pricey' | 'e1' | 'e2' | 'e3' | 'e4' | 'e5';
  /** Имя узла на карточке. */
  title: string;
  /** Тело узла одной строкой — ровно то, что выполняется внутри виджета. */
  source: string;
}
