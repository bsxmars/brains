import type { Program, SimResult } from '@/shared/lib/promise-sim';

/**
 * Типы демо «цена резолва»: случай `ResolvePromise(v)`, его дорожки и то, что о них сказали
 * движок и модель.
 *
 * Дорожка — одна цепочка промисов, у которой есть цена в тиках. В простых случаях дорожка
 * одна; в разборе `return` из `.then` их три, и весь смысл именно в том, что они стоят разного.
 */

/** Чем окрашена дорожка: дешёвая, обычная, дорогая. */
export type LaneTone = 'ok' | 'info' | 'warn';

export interface ResolveLane {
  key: string;
  /** Подпись дорожки. Строчная разметка — выводить через `Md`. */
  label: string;
  /** Код примера. Печатает метку попадания там, где результат становится виден. */
  code: string;
  /**
   * Цена в тиках, посчитанная заранее.
   *
   * Это не «источник истины», а третий голос: движок меряет сам, модель считает сама, а `n`
   * говорит, чего мы ждали. Разойдётся с движком — виджет скажет об этом вслух, а не покажет
   * красивое число.
   */
  n: number;
  /** Что здесь происходит и почему цена такая. Строчная разметка. */
  note: string;
  tone: LaneTone;
  /**
   * Тот же пример, записанный операциями спеки.
   *
   * Необязателен намеренно. `promise-sim` не знает отказов и комбинаторов — это записано
   * в её докстринге. Дорожка без `program` показывает только настоящий прогон и честно
   * говорит, что модели для неё нет.
   */
  program?: Program;
}

export interface ResolveCase {
  key: string;
  /** Подпись на переключателе. */
  label: string;
  /** Заголовок случая. Строчная разметка. */
  title: string;
  /** Одна фраза о том, что показывает случай. Строчная разметка. */
  why: string;
  lanes: ResolveLane[];
  /**
   * Прогон «рядом»: те же цепочки, запущенные вместе. Цена в тиках — число, а порядок вывода —
   * следствие, которое видно глазами. Ради него случай и собран.
   */
  order?: {
    code: string;
    /** Ожидаемый порядок — на случай, если среда не дала выполнить код. */
    expected: string[];
    /** Что этот порядок означает. Строчная разметка. */
    note: string;
  };
}

export interface LaneMeasure {
  /** Строки линейки: ступени `tick N` и метка попадания между ними. */
  lines: string[];
  /** Сколько ступеней линейки прошло до попадания. */
  price: number;
  /** `true` — выполнено прямо сейчас; `false` — среда не дала, показан заранее посчитанный вывод. */
  measured: boolean;
}

export interface OrderMeasure {
  lines: string[];
  measured: boolean;
}

export interface LaneReport {
  lane: ResolveLane;
  measure: LaneMeasure;
  /** `null` — модели для этой дорожки нет. */
  model: SimResult | null;
  /** Сошлись ли движок и модель. `none` — сверять не с чем. */
  verdict: 'match' | 'clash' | 'none';
  /** Движок разошёлся с заранее посчитанным `n`. Такое обязано быть видно. */
  drift: boolean;
}

export interface CaseReport {
  key: string;
  lanes: LaneReport[];
  order: OrderMeasure | null;
}
