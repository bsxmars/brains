/**
 * Одна строка водопада — один ресурс **этой самой страницы**.
 *
 * Числа сюда приходят не из `data.ts`, а из `performance.getEntriesByType('resource')`
 * в браузере читателя. Поэтому у строки нет поля «сколько должно быть»: сколько получилось,
 * столько и получилось, и в этом весь смысл демо.
 */
export interface WaterfallRow {
  key: string;
  /** Короткое имя файла — то, что влезает в подпись оси. */
  name: string;
  /** Полный адрес: нужен подсказке и отладке. */
  full: string;
  /** `initiatorType`: script, link, img, fetch, navigation… */
  kind: string;

  /** Начало запроса от `startTime` навигации, мс. */
  start: number;
  /** Разрешение имени, мс. */
  dns: number;
  /** Соединение вместе с TLS, мс. */
  connect: number;
  /** Ожидание ответа: от отправки запроса до первого байта, мс. */
  wait: number;
  /** Передача тела, мс. */
  transfer: number;
  /** Конец, мс от начала навигации. */
  end: number;

  /**
   * Ответ достался без сети.
   *
   * Признак ровно один и он измеримый: `transferSize === 0` при ненулевом `decodedBodySize`.
   * Условный запрос с ответом `304` под него **не подходит** и не должен: там по проводу
   * проехали заголовки, то есть RTT заплачен. Проверено замером: у `304` в этом браузере
   * `transferSize` около 300 байт, а `decodedBodySize` — ноль.
   */
  cached: boolean;
  /** `nextHopProtocol`: http/1.1, h2, h3. Пустая строка — браузер его не сообщил. */
  protocol: string;
  /** Байты по проводу, включая заголовки. */
  transferSize: number;
  /** Байты после распаковки — размер самого ресурса. */
  decodedBodySize: number;

  /**
   * Тайминги скрыты.
   *
   * У кросс-доменного ресурса без заголовка `Timing-Allow-Origin` фазы обнулены: это защита
   * от утечки таймингов между источниками. Такую строку честнее пометить, чем нарисовать
   * нулевой полоской и сделать вид, что ресурс приехал мгновенно.
   */
  opaque: boolean;
}
