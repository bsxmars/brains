/**
 * Задача для самопроверки.
 *
 * Это не квиз с вариантами: в оригинальных бандлах были именно квизы, и их сознательно
 * не переносили. Здесь другое — задачи автора с разбором, где ценность не в «угадал»,
 * а в объяснении, почему ответ именно такой.
 */
export interface SelfCheckItem {
  /** Условие. Разрешена строчная разметка. */
  question: string;
  /** Подсказка — на случай, когда читатель застрял, но сдаваться рано. */
  hint?: string;
  /** Разбор: ответ и почему он такой. */
  answer: string;
}
