/**
 * Демо про чередование чтения и записи.
 *
 * Сами операции демо строит само: они полностью определяются режимом и числом элементов,
 * и списком в данных были бы копией цикла из примера.
 */
export interface ThrashMode {
  key: string;
  label: string;
  /** Код, который даёт именно такую последовательность операций. */
  code: string;
  /** Вывод под счётчиком. Разрешена строчная разметка. */
  note: string;
  tone: 'ok' | 'warn' | 'err';
}

/** Сколько элементов обрабатывает цикл. */
export interface ThrashSize {
  key: string;
  label: string;
  items: number;
}

/** Одна операция цикла: чтение геометрии или запись в стиль. */
export interface ThrashOp {
  kind: 'read' | 'write';
  /** Номер элемента, с которого идёт операция. */
  n: number;
  /** Чтение при грязном дереве — принудительный пересчёт. */
  forced: boolean;
}
