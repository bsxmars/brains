/**
 * Типы демо «одна задача, две модели».
 *
 * Демо состоит из трёх островов: панель действий, пара React и пара Vue. Панель ничего
 * не знает о том, кто её слушает, — она только называет действие. Поэтому единственное
 * общее между островами — эти типы и имя события в `bus.ts`.
 */

/**
 * Действие читателя. Каждое меняет **ровно одно поле состояния из трёх** — в этом весь смысл
 * задачи: видно, кто пересчитал только изменившееся, а кто всё поддерево.
 */
export type TwoModelsAction = 'tick' | 'query' | 'add' | 'reset';

/** Подпись кнопки и обещание: что должно измениться на экране. */
export interface ActionCopy {
  id: Exclude<TwoModelsAction, 'reset'>;
  /** Текст кнопки. Чистый текст: разметку кнопка не разбирает. */
  label: string;
  /** Какое поле состояния меняется. Разрешена строчная разметка. */
  field: string;
  /** Что обязано измениться в документе. Разрешена строчная разметка. */
  note: string;
}

/**
 * Точка развёртки «сколько работы на одно нажатие» в зависимости от длины списка.
 * Числа сняты запуском, см. `data.ts` урока.
 */
export interface WorkPoint {
  /** Строк в списке. */
  size: number;
  /** React без `memo`: вызовов функций компонентов. */
  plain: number;
  /** React с `memo` на каждом узле и стабильными обработчиками. */
  memo: number;
  /** Vue: прогонов render-функций (монтирование плюс обновления). */
  vue: number;
  /** Правок документа — у всех трёх одна и та же. */
  dom: number;
}
