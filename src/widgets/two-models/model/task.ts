/**
 * Сама задача — одна на оба острова, до последней строки данных.
 *
 * Это не мелочь оформления. Демо утверждает «одно и то же действие над одними и теми же
 * данными», и проверить это утверждение читатель не может — он видит только числа. Значит
 * единственная защита от вранья здесь — чтобы данных физически было одни, а не две копии,
 * которые однажды разъедутся.
 */
export interface TaskItem {
  id: number;
  name: string;
}

/** Пять строк списка. */
export const TASK_ITEMS: readonly TaskItem[] = [
  { id: 1, name: 'альфа-1' },
  { id: 2, name: 'бета-2' },
  { id: 3, name: 'гамма-3' },
  { id: 4, name: 'дельта-4' },
  { id: 5, name: 'эпсилон-5' },
];

/**
 * Строка фильтра. Одна буква, и выбрана она не случайно: её нет ровно в одном имени
 * (`эпсилон-5`), поэтому включение фильтра убирает ровно одну строку — видно, что
 * произошло, и видно, что список не пересобрался целиком. Добавленные строки её содержат,
 * поэтому «добавить» работает и при включённом фильтре.
 */
export const FILTER_QUERY = 'а';

/** Новая строка. Номер сквозной, иначе у списка появились бы одинаковые ключи. */
export function makeItem(n: number): TaskItem {
  return { id: 100 + n, name: `дзета-${n}` };
}

