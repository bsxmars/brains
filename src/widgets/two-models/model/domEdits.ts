/**
 * Правки документа — один прибор на оба острова.
 *
 * Всё демо держится на сравнении двух чисел рядом, поэтому считать их обязан **один и тот же
 * код**: разойдись правила счёта хоть в мелочи — и сравнение перестанет что-либо значить,
 * причём молча. Отсюда и слой: не хук React и не composable Vue, а обычная функция,
 * к которой каждый рантайм приделывает свою обёртку в три строки.
 *
 * ⚠️ Соседний урок про ре-рендеринг мерит то же самое своим хуком
 * (`@/features/count-renders`, `useDomMutations`), и правила там те же. Здесь он не
 * переиспользован по одной причине: тот хук копит правки на состоянии компонента и обнуляет
 * их сменой ключа, а этому демо нужно число **за одно нажатие**, снятое разностью, — и нужно
 * оно сразу двум рантаймам.
 *
 * Три правила счёта, и каждое существует, потому что без него прибор врал:
 *
 *   1. `childList` и `characterData`, но **не атрибуты**. Подсветка «этот узел пересчитался»
 *      ставится атрибутом прямо на элемент — иначе прибор мерил бы собственную подсветку.
 *   2. Считаются записи (`MutationRecord`), а не узлы: одна вставка — одна правка.
 *   3. Всё, что лежит внутри `[data-meter]`, из счёта выброшено. Счётчики — это тоже текст,
 *      и он меняется на каждом прогоне; без фильтра «правок DOM» никогда не было бы нуля.
 *
 * ⚠️ И главное про доставку: браузер отдаёт записи в колбэк **микрозадачей**, и она же
 * очищает очередь. Значит `takeRecords()`, вызванный после первого же `await`, вернёт пусто —
 * не потому, что правок не было, а потому, что их уже забрали. Поэтому счёт идёт в колбэке.
 * На этом легко намерить ровные нули там, где правки есть.
 */

/** Что наблюдаем. Атрибутов здесь нет намеренно — см. правило 1. */
export const OBSERVE_INIT: MutationObserverInit = {
  subtree: true,
  childList: true,
  characterData: true,
};

/** Правка настоящая, если она произошла не внутри прибора. */
export function countsAsEdit(record: MutationRecord): boolean {
  const node = record.target;
  const element = node.nodeType === 1 ? (node as HTMLElement) : node.parentElement;
  return !element?.closest('[data-meter]');
}

export interface EditCounter {
  /** Сколько правок насчитано с последнего обнуления. */
  read(): number;
  reset(): void;
  stop(): void;
}

/**
 * Завести счётчик правок на поддереве. Число читается синхронно — оно живёт в замыкании,
 * а не в состоянии компонента: состояние успело бы устареть ровно там, где число снимают.
 */
export function createEditCounter(target: Element): EditCounter {
  let count = 0;
  const observer = new MutationObserver((records) => {
    count += records.filter(countsAsEdit).length;
  });
  observer.observe(target, OBSERVE_INIT);

  return {
    read: () => count,
    reset: () => {
      // Забираем недоставленное, иначе правки прошлого нажатия попадут в следующее.
      observer.takeRecords();
      count = 0;
    },
    stop: () => observer.disconnect(),
  };
}
