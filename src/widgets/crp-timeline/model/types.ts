/**
 * Критический путь как последовательность во времени: отрезки на дорожках и шаги разбора.
 *
 * Отрезок задан парой «начало + длина» в миллисекундах, а не порядком в списке: на этом пути
 * половина событий идёт параллельно — сеть качает CSS, пока парсер стоит на скрипте, — и выразить
 * это порядком элементов нельзя, только координатами на общей шкале.
 *
 * Раскладов два, и шкала у них общая: сравнивать «как написано» и «как надо» имеет смысл,
 * только если миллисекунда в обоих одной длины.
 */
export interface CrpLane {
  key: 'net' | 'main' | 'screen';
  label: string;
}

export interface CrpPhase {
  id: string;
  label: string;
  /** Начало отрезка, мс от запроса документа. */
  at: number;
  /** Длина отрезка, мс. */
  ms: number;
  lane: CrpLane['key'];
  tone: 'ink' | 'info' | 'warn' | 'ok' | 'err' | 'dim';
}

/** Шаг разбора: какие отрезки подсвечены и что в этот момент происходит. */
export interface CrpStep {
  phases: string[];
  /** Где мы сейчас — пилюля над сообщением. */
  where: string;
  title: string;
  /** Разрешена строчная разметка: `код` и **жирный**. */
  message: string;
  tone?: 'info' | 'ok' | 'warn' | 'err';
}

/** Один расклад загрузки: разметка, дорожки и разбор по шагам. */
export interface CrpCase {
  key: string;
  label: string;
  tone: 'ok' | 'err';
  /** Разметка, которая даёт именно такой путь. */
  code: string;
  /** Вывод под дорожкой. Разрешена строчная разметка. */
  verdict: string;
  phases: CrpPhase[];
  steps: CrpStep[];
}
