/** Уровень запирания. `plain` — объект, к которому не применяли ничего. */
export type LockLevel = 'plain' | 'preventExtensions' | 'seal' | 'freeze';

/** Операция над запертым объектом. Те же четыре, что стояли колонками в булевой таблице. */
export type LockOp = 'add' | 'delete' | 'write' | 'define';

/**
 * Режим исполнения операции.
 *
 * Это не настройка демо, а вторая половина ответа: одна и та же операция в strict бросает,
 * а в sloppy проваливается молча. Таблица из «да» и «нет» этого различия выразить не могла.
 */
export type LockMode = 'strict' | 'sloppy';

/**
 * Итог одного настоящего прогона.
 *
 * `threw` и `error` — то, что реально бросил движок, а не пересказ; `changed` отвечает
 * на главный вопрос sloppy-режима: «исключения нет — а сработало ли?».
 */
export interface LockRun {
  /** Строки кода, которые исполнились, — включая запирание и пометку режима. */
  code: string[];
  threw: boolean;
  /**
   * Имя ошибки — `TypeError`. Отдельно от текста намеренно: имя нормативно, текст у каждого
   * движка свой. Утверждать в тесте можно только имя, показывать читателю — и то и другое.
   */
  errorName: string;
  /** `TypeError: Cannot add property b, object is not extensible` — дословно от движка. */
  error: string;
  /** Что вернула сама операция. У `delete` это `false` — единственный след молчаливого отказа. */
  returned: string;
  /** Собственные свойства объекта после операции. */
  after: string;
  /** Дескриптор `a` после операции — операция «переопределить» видна только здесь. */
  descriptor: string;
  /** Изменился ли объект на самом деле: и по свойствам, и по дескриптору. */
  changed: boolean;
  verdict: string;
  tone: 'ok' | 'warn' | 'err';
}
