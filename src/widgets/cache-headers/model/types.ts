/** Исход повторного захода: пошли ли в сеть и что оттуда приехало. */
export interface CacheOutcome {
  /** Что произошло с сетью: «сети нет», «условный запрос», «полная загрузка». */
  network: string;
  /** Что приехало: тело, `304` без тела, ничего. */
  body: string;
  tone: 'ok' | 'warn' | 'err' | 'info';
}

/**
 * Один набор директив `Cache-Control` и то, что он означает на повторном заходе.
 *
 * ⚠️ Это **модель по спецификации** (RFC 9111), а не замер: описано то, что кеш обязан
 * сделать, а не то, что сделал конкретный браузер конкретной версии. Часть строк удалось
 * подтвердить запуском — у таких заполнено поле `measured`, и только оно является замером.
 */
export interface CacheMode {
  key: string;
  /** Подпись переключателя. Разметки здесь быть не должно: это текст кнопки. */
  label: string;
  /** Заголовок целиком — как он стоит в ответе. */
  header: string;
  /** Ляжет ли ответ в постоянное хранилище. */
  stored: boolean;
  /** Повторный заход, пока ответ свежий. */
  fresh: CacheOutcome;
  /** Повторный заход после того, как свежесть кончилась. */
  stale: CacheOutcome;
  /** Уходит ли условный запрос — и когда именно. */
  conditional: string;
  /** Для чего это правильный выбор. Разрешена строчная разметка. */
  verdict: string;
  /** Что показал запуск, если это удалось померить. Разрешена строчная разметка. */
  measured?: string;
  tone: 'ok' | 'warn' | 'err' | 'info';
}
