/**
 * Класс утечки в одном формате: как течёт → по какой цепочке держится → как чинится.
 *
 * Цепочка важнее кода: чинить надо не «удалить строку», а разорвать конкретное ребро
 * в графе достижимости. Поэтому она хранится списком узлов от корня вниз.
 */
export interface LeakCase {
  label: string;
  code: string;
  /** Цепочка удержания сверху вниз: первый узел — корень, последний — то, что не освобождается. */
  chain: string[];
  why: string;
  fix: string;
  fixCode: string;
}
