/**
 * Один вызов ловушки в разборе операции.
 *
 * `times` нужен там, где ловушка срабатывает на каждый ключ: `getOwnPropertyDescriptor`
 * при `Object.keys` вызывается не один раз, а по разу на ключ. Из этих чисел складывается
 * счётчик «ловушек всего», и он важнее списка: именно он показывает, что безобидная на вид
 * операция стоит шести обращений, а не одного.
 */
export interface TrapCall {
  name: string;
  times?: number;
  note?: string;
}

/**
 * Операция над прокси: что вызвали, какие ловушки сработали, что вернулось.
 *
 * Пустой `traps` — это не «забыли заполнить», а содержательный ответ: операция идёт мимо
 * внутренних методов, и перехватить её нечем.
 */
export interface ProxyOp {
  /** Подпись операции; если `code` нет, она же исполняется как выражение над прокси `p`. */
  op: string;
  /** Тело функции от `p`, когда подпись не годится в выражение (цикл, накопление). */
  code?: string;
  /** Выражение, создающее цель, — если операции нужна своя (класс с `#`-полем, `Map`). */
  target?: string;
  /**
   * Ловушки, как их отдаёт движок, свёрнутые по подряд идущим одинаковым. Демо их не читает —
   * оно считает журнал само (`model/run.ts`); литерал держит подписи `note`, а тест сверяет
   * имена и `times` с журналом.
   */
  traps: TrapCall[];
  /** Ожидаемый результат в записи `formatValue`; тест сверяет его с вычисленным. */
  res: string;
  note: string;
  tone?: 'warn' | 'err';
}

/** Столбик диаграммы цены: подпись, замер и доля от самого дорогого варианта. */
export interface CostBar {
  label: string;
  value: string;
  /** Доля от максимума, 0…1 — ею задаётся ширина столбика. */
  ratio: number;
  tone: 'neutral' | 'violet' | 'amber';
}
