/**
 * Случай подстановки: что стоит в переменной и чего от этого ждёт читатель.
 *
 * Ожидание записано намеренно — демо сверяет его с тем, что вернул браузер. Ценность
 * не в «показать значение», а в том, что у большинства случаев ожидание неверное.
 */
export interface VarCase {
  id: string;
  /** Подпись на переключателе. */
  label: string;
  /**
   * Значение пользовательского свойства. `null` — объявления нет вовсе,
   * пустая строка — объявление есть, но значение пустое: это разные случаи.
   */
  value: string | null;
  /** Что обычно ждут. Разрешена строчная разметка. */
  expected: string;
  /** Почему выходит именно так. Разрешена строчная разметка. */
  why: string;
  tone?: 'ok' | 'warn' | 'err';
}
