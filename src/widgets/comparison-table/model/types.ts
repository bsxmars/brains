/**
 * Строка режима Comparison.
 *
 * Числа лежат дважды: строкой — ровно так, как они выглядят в панели, и числом — чтобы по ним
 * можно было отсортировать. Разделять пришлось потому, что подписи в снимке форматированы
 * по-своему («41.2 МБ», «+50.32 МБ»), и пересчитывать их обратно из байтов значило бы
 * показать другие числа, чем в оригинале.
 */
export interface CmpRow {
  /** Конструктор или служебная категория в скобках. */
  c: string;
  /** `# New` — сколько появилось между снимками. */
  nw: string;
  /** `# Deleted` — сколько исчезло. */
  del: string;
  /** `# Delta` строкой и числом: главная колонка. */
  delta: string;
  deltaN: number;
  alloc: string;
  freed: string;
  /** `Size Delta` строкой и числом: чистый прирост в байтах. */
  sizeDelta: string;
  sizeDeltaN: number;
  verdict: string;
  tone: 'ok' | 'warn' | 'err';
  why: string;
  next: string;
}

/** По какой колонке отсортирована таблица. `none` — порядок как в снимке. */
export type SortKey = 'none' | 'delta' | 'size';
