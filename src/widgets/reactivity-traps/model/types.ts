/**
 * Данные демо «почему не обновляется».
 *
 * Каждый сценарий виджет выполняет по-настоящему — на `@vue/reactivity` и, где нужно,
 * на настоящем компоненте с `props`. Вывод в консоли демо — не заготовленная строка,
 * а то, что напечатал живой эффект.
 *
 * Поэтому `verdict` здесь нет: приговор («эффект промолчал» / «сработал») виджет выносит
 * по фактическому числу прогонов. Заготовленный вердикт однажды разошёлся бы с кодом,
 * и урок бы врал — ровно то, чего этот урок и учит избегать.
 */

/** Сценарий-ловушка. `id` выбирает настоящий код внутри виджета. */
export interface TrapScenario {
  id: 'destructure' | 'raw-proxy' | 'await' | 'stale-ref' | 'to-raw' | 'props';
  /** Подпись на переключателе — коротко, чтобы влезла в «пилюлю». */
  label: string;
  /** Заголовок над разбором. */
  title: string;
  /** Листинг: ровно тот код, который выполнится по кнопке. */
  code: string[];
  /** Почему так, и что делать вместо этого. Разрешена строчная разметка. */
  note: string;
  /** Как чинится. */
  fix: string;
}
