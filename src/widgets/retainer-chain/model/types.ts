/** Звено цепочки retainers: строка панели и разбор того, чем является эта ссылка. */
export interface RetainerNode {
  /** Строка как в панели, вместе с отступом и «└─». */
  t: string;
  /** Чем является ссылка: поле объекта, элемент массива, захваченная переменная. */
  kind: string;
  what: string;
  /** Чинить здесь или нет. */
  fix: string;
  /** `ok` — ваше звено, здесь правка; `err` — корень; `warn` — подсказка. */
  tone?: 'ok' | 'warn' | 'err';
}

/** Цепочка retainers целиком: от выбранного объекта до корня. */
export interface RetainerChain {
  /** Подпись переключателя. */
  label: string;
  /** Вся цепочка одним предложением. */
  summary: string;
  /** Звенья сверху вниз: первый — выбранный объект, последний — корень. */
  nodes: RetainerNode[];
  /** Какое звено показать при выборе цепочки. */
  initial?: number;
}
