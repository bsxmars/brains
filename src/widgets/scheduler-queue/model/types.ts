/**
 * Данные демо «планировщик и `nextTick`».
 *
 * Сценарий — это набор записей в `ref`, который виджет выполняет по-настоящему: с живыми
 * `watch` трёх режимов, живым компонентом и его `onUpdated`. Лента событий, которую потом
 * листает читатель, — это то, что реально случилось, в том порядке, в каком случилось.
 *
 * Поэтому здесь только подписи и пояснения: числа виджет получает замером, а не отсюда.
 */

/** Сценарий записи. `id` выбирает настоящий код внутри виджета. */
export interface QueueScenario {
  id: 'once' | 'thrice' | 'same' | 'sync-storm';
  /** Подпись на переключателе. */
  label: string;
  /** Строки кода сценария — листинг рядом с лентой. */
  code: string[];
  /** Что этот сценарий показывает. */
  note: string;
}

/**
 * Фаза события в ленте. Порядок объявления — это и есть порядок внутри микрозадачи,
 * и он проверен запуском (см. комментарий в `SchedulerQueue.vue`).
 */
export type QueuePhase = 'write' | 'sync' | 'pre' | 'render' | 'post' | 'updated' | 'tick';

/** Подпись фазы: как она называется на ленте и что означает. */
export interface QueuePhaseCopy {
  phase: QueuePhase;
  label: string;
  note: string;
}
