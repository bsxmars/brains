/** Сценарий демо. Пять ситуаций, в которых колбэк вмешивается в чужой обход. */
export type DispatchKey = 'target' | 'emitter' | 'splice' | 'sort' | 'recursion';

/**
 * Откуда взялся ответ — и насколько ему можно верить.
 *
 * Поле существует ровно потому, что демо исполняется в браузере, а тема рассказывает
 * в том числе про Node. Смешивать эти два источника молча нельзя: «проверено» у настоящего
 * `EventTarget` и у самодельного эмиттера значит разное, и читатель обязан видеть, какое.
 *
 * - `spec` — выполнено по-настоящему, и результат задан спецификацией: другого быть не может;
 * - `model` — выполнена **модель** чужой среды (эмиттер в стиле Node), а не сама среда;
 * - `engine` — выполнено по-настоящему, но ответ спецификацией не обещан: так вышло здесь.
 */
export type DispatchSource = 'spec' | 'model' | 'engine';

/** Один круг диспетчеризации: кого позвали и в каком порядке. */
export interface DispatchRound {
  /** «первое событие» / «второе событие». */
  label: string;
  /** Имена слушателей в том порядке, в каком их позвали по-настоящему. */
  order: string[];
  /**
   * Те из них, кто к моменту вызова был уже снят.
   *
   * Собирается замером, а не знанием: слушатель при вызове спрашивает, снимали ли его.
   * Пустой список у `EventTarget` и непустой у эмиттера — это и есть вся разница темы.
   */
  stale: string[];
  /** Вывод по кругу — тоже из замера, не из заготовки. */
  note: string;
}

/** Измеренное число или значение, которое стоит показать рядом с выводом. */
export interface DispatchValue {
  /** Подпись. Без строчной разметки: печатается как есть. */
  label: string;
  value: string;
}

/** Итог одного настоящего прогона сценария. */
export interface DispatchRun {
  key: DispatchKey;
  /** Что напечатала бы консоль, строками. Для сценариев с кругами пуст. */
  log: string[];
  /** Круги диспетчеризации. Для остальных сценариев пуст. */
  rounds: DispatchRound[];
  /**
   * Порядок вызовов всеми кругами, по строке на круг: `'a → b → c\na → c'`.
   *
   * Ровно в таком виде эти две строки лежали в `data.ts` литералами. Поле нужно, чтобы
   * юнит-тест сверял литерал с прогоном одной строкой, а не пересобирал формат у себя.
   */
  summary: string;
  values: DispatchValue[];
  /**
   * Имя пойманной ошибки — `RangeError` у рекурсии, пустая строка, если не бросало.
   *
   * Отдельно от текста намеренно: имя нормативно, текст у каждого движка свой (`AGENTS.md`,
   * «имя ошибки нормативно, текст — нет»). Утверждать в тесте можно только имя.
   */
  errorName: string;
  /** Дословно от движка — для показа, но не для проверки. */
  error: string;
  verdict: string;
  tone: 'ok' | 'warn' | 'err';
}

/** Описание сценария: подпись переключателя, текст и тот самый код, который исполняется. */
export interface DispatchScenario {
  key: DispatchKey;
  /** Подпись в переключателе. Без строчной разметки: Aura печатает её как есть. */
  label: string;
  title: string;
  lead: string;
  /** Строки кода — те же, что исполняет соответствующая функция в `run.ts`. */
  code: string[];
  source: DispatchSource;
  /** Честная оговорка про источник ответа. Показывается всегда, а не по настроению. */
  caveat: string;
}
