/** Одна проба внутри рамки: кусочек кода, про который политика выносит решение. */
export interface CspProbe {
  id: string;
  /**
   * Подпись пробы. Выводится **как есть**, обычным текстом в острове, — значит строчной
   * разметки здесь быть не должно: обратные кавычки доехали бы до читателя.
   */
  label: string;
  /** Чем проба интересна: что именно она проверяет в политике. */
  hint: string;
}

/** Нарушение, о котором отчитался сам браузер: событие `securitypolicyviolation` внутри рамки. */
export interface CspViolation {
  /** `effectiveDirective` — директива, которая приняла решение. */
  directive: string;
  /** `blockedURI`: `inline`, `eval`, `blob` или адрес заблокированного ресурса. */
  blocked: string;
}

/** Набор директив, который читатель выбирает переключателем. */
export interface CspOption {
  key: string;
  /** Подпись переключателя — текст кнопки, без разметки. */
  label: string;
  /** Политика с меткой `{NONCE}`; её заменяет сгенерированный на клиенте nonce. */
  policy: string;
  /** Что этот набор показывает. Разрешена строчная разметка — идёт через `Md`. */
  about: string;
}

/** Итог прогона: что выполнилось и на что браузер пожаловался. */
export interface CspRunResult {
  ran: string[];
  violations: CspViolation[];
}
