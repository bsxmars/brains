/**
 * Пять ключевых слов на одном свойстве: `inherit`, `initial`, `unset`, `revert`, `revert-layer`.
 *
 * Разница между ними — источник значения, и увидеть её можно только на живом элементе:
 * `initial` берёт значение из спецификации свойства, `revert` — из встроенной таблицы
 * браузера, и на `display` у `<div>` это буквально разные слова. Поэтому виджет не
 * рассказывает, что получится, а применяет все шесть вариантов к настоящим элементам
 * и показывает то, что вернул `getComputedStyle` у читателя.
 *
 * ⚠️ Свойства здесь нарочно **не про цвет**. `color: initial` даёт чёрный, `color: revert`
 * на ссылке — браузерный синий; ни того ни другого в палитре курса нет, а проверка
 * `tests/e2e/palette.spec.ts` смотрит на то, что реально нарисовано. Эти два значения
 * разобраны в тексте урока таблицей — с пометкой, в каком движке они сняты.
 */

/** Ключевое слово. `none` — «ничего не писать», отправная точка для сравнения. */
export type DefaultKeyword = 'none' | 'inherit' | 'initial' | 'unset' | 'revert' | 'revert-layer';

/** Свойство, на котором ставится опыт. */
export interface DefaultProp {
  /** Имя свойства — его же виджет спрашивает у `getComputedStyle`. */
  id: 'display' | 'text-decoration-line' | 'font-weight';
  label: string;
  /** Тег подопытного элемента: у `<a>` и `<b>` свои встроенные стили, и в этом весь смысл. */
  tag: 'div' | 'a' | 'b';
  /** Наследуемое ли свойство — от этого зависит, чем окажется `unset`. */
  inherited: boolean;
  /** Значение в слое `base` — к нему возвращает `revert-layer`. */
  base: string;
  /** Значение в слое `theme` — оно стоит, пока ключевого слова нет. */
  theme: string;
  /** Значение на родителе — к нему ведёт `inherit`. */
  parent: string;
  /** Что показывает именно это свойство. Разрешена строчная разметка. */
  note: string;
}

/** Подпись ключевого слова: откуда оно берёт значение. */
export interface KeywordCopy {
  key: DefaultKeyword;
  label: string;
  /** Откуда берётся значение — одной строкой. Разрешена строчная разметка. */
  source: string;
}
