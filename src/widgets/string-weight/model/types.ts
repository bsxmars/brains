/**
 * Типы стенда «вес строки вживую».
 *
 * ⚠️ Слова «однобайтная» и «двухбайтная» здесь — про **вывод из кодов символов**, а не про
 * ответ движка. Внутреннее представление строки из JS не наблюдаемо: `%DebugPrint` требует
 * `--allow-natives-syntax` у самого бинарника, а сайт собирается статически. Поэтому в типах
 * нет поля «что сказал V8» — есть то, что мы посчитали (`units`, `utf8`), и то, что из этого
 * следует (`twoByte`, `storage`), вместе с обоснованием вывода (`maxCode`, `culprit`).
 */

/** Образец для взвешивания. Поля только строковые: пропы острова Astro сериализует. */
export interface WeightSample {
  key: string;
  /** Подпись строки в таблице. */
  label: string;
  /** Сама строка. */
  value: string;
  /** Что в ней интересного — почему она попала в набор. */
  note: string;
}

/** Взвешенный образец: посчитанное и выведенное из посчитанного. */
export interface WeightRow extends WeightSample {
  /** `length` — кодовые единицы UTF-16. Посчитано. */
  units: number;
  /** Кодовые точки: спред. Посчитано. */
  points: number;
  /** Графемы: `Intl.Segmenter`. Посчитано. */
  graphemes: number;
  /** Байты UTF-8: `TextEncoder`. Посчитано. */
  utf8: number;
  /** Наибольший код единицы — обоснование вывода о представлении. Посчитано. */
  maxCode: number;
  /**
   * Первый знак, выводящий за латиницу-1, если он есть; пустая строка — значит все ≤ U+00FF.
   * Это кодовая точка целиком: половину суррогатной пары читателю показывать нечем.
   */
  culprit: string;
  /** Код этого знака в виде `2600` или `1F600`. Пустая строка, если знака нет. */
  culpritHex: string;
  /** **Вывод:** строка хранится по два байта на единицу. */
  twoByte: boolean;
  /** **Вывод:** байт под сами знаки. Заголовок объекта строки сюда не входит. */
  storage: number;
  /** **Вывод:** байт на одну кодовую единицу — 1.00 или 2.00, третьего не бывает. */
  bytesPerUnit: number;
  /** Посчитано: байт UTF-8 на одну кодовую точку. С `storage` не совпадает — в этом весь смысл. */
  utf8PerPoint: number;
}

export interface WeightResult {
  /** Взвешивание состоялось. `false` — в среде нет `TextEncoder`, числа не снимались. */
  ok: boolean;
  rows: WeightRow[];
  /** Были ли графемы посчитаны сегментатором, а не подменены кодовыми точками. */
  segmented: boolean;
  note: string;
}
