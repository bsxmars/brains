/**
 * Кадр как последовательность во времени: отрезки на дорожке и шаги разбора.
 *
 * Отрезок задан не длительностью «сколько-то», а парой «начало + длина» в миллисекундах
 * модельного кадра. Так дорожка остаётся честной: компоновщик работает после `commit`
 * параллельно с `requestIdleCallback` на главном потоке, и выразить это порядком элементов
 * в списке нельзя — только координатами на общей шкале.
 */
export interface FramePhase {
  id: string;
  label: string;
  /** Начало отрезка, мс от начала кадра. */
  at: number;
  /** Длина отрезка, мс. */
  ms: number;
  /** Дорожка: главный поток или всё, что живёт после `commit`. */
  lane: 'main' | 'compositor';
  tone: 'ink' | 'info' | 'warn' | 'ok' | 'dim';
}

/** Шаг разбора: какие отрезки подсвечены и что в этот момент происходит. */
export interface FrameStep {
  /** Идентификаторы отрезков, о которых шаг говорит. */
  phases: string[];
  /** Где мы сейчас — подпись пилюлей над сообщением. */
  where: string;
  title: string;
  /** Разрешена строчная разметка: `код` и **жирный**. */
  message: string;
  tone?: 'info' | 'ok' | 'warn' | 'err';
  /**
   * Шаг про кадр, которого не будет: rendering opportunity наступила, а рисовать нечего.
   * Все отрезки, кроме названных в `phases`, гаснут пунктиром.
   */
  skipped?: boolean;
}
