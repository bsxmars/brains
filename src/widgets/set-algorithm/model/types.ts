/**
 * Сценарий записи `o.x = 5` — один из четырёх выходов алгоритма `[[Set]]`.
 *
 * Три сценария из четырёх заканчиваются тем, что собственного свойства так и не появилось,
 * и каждый по своей причине. Ради этого набор и собран: «запись не идёт по цепочке» — неправда,
 * идёт, просто ищет там не значение, а причину не создавать своё свойство.
 */
export interface SetScenario {
  key: string;
  label: string;
  code: string;
  /**
   * Ключ, в который пишет последняя строка `code`. По нему модель снимает дескрипторы
   * и чтение после записи (`model/run.ts`).
   */
  prop: string;
  steps: string[];
  /**
   * Какой узел подсвечен на каждом шаге: `0` — сам `o`, `1` — `proto`,
   * `null` — ни один (шаг не про обход цепочки). Длина совпадает с `steps`.
   */
  highlight: (number | null)[];
  /*
   * ⚠️ Здесь стояли `proto`, `ownBefore` и `own` — подписи узлов, набранные руками
   * («label → { get: ƒ }», «name · age · Symbol(id) — без изменений»). С 2026-10-03 узлы
   * и вывод снимаются с живых объектов (`model/run.ts`), и рукописные подписи сняты, чтобы
   * не разойтись с движком.
   */
  /** Вывод, который делает читатель из напечатанного: одна-две фразы под выводом движка. */
  result: string;
  tone: 'ok' | 'warn' | 'err';
}
