/**
 * Пути собранного сайта и то, что с ними делает базовый путь.
 *
 * Строки здесь — не выдумка для демо: каждая снята с настоящей сборки этого самого сайта
 * (см. шапку `src/content/delivery/github-pages/data.ts`), вместе с количеством — сколько
 * таких путей нашлось в `dist`. Поэтому итог демо совпадает с итогом прогона, а не
 * иллюстрирует его.
 */

/** Форма записи пути — единственное, что решает его судьбу при смене базы. */
export type PathShape =
  /** `/_astro/x.css` — от корня сайта. Работает ровно до того дня, когда сайт съезжает в подкаталог. */
  | 'absolute'
  /** `./x.css`, `x.css` — от адреса текущего документа. Базу переживает. */
  | 'relative'
  /** `#s2` — внутри страницы. */
  | 'anchor'
  /** `https://…`, `data:…` — за пределами сайта. */
  | 'external';

/** Кто написал путь: сборщик (и значит, знает про базу) или человек (и значит, нет). */
export type PathAuthor = 'builder' | 'hand';

/** Одна строка снятой описи путей. */
export interface PathRow {
  id: string;
  /** Путь **как он лежит в собранном файле** при базе `/`. */
  path: string;
  /** Где он стоит: `<link rel=stylesheet>`, `url()` в CSS, ссылка в тексте темы. */
  where: string;
  author: PathAuthor;
  /**
   * Переписывает ли сборщик этот путь под базу.
   *
   * Совпадает с `author === 'builder'` не случайно, а по существу: Astro подставляет базу
   * туда, куда пишет сам, и не трогает то, что написали вы. Два поля вместо одного потому,
   * что на странице эти два факта читаются как разные — «кто написал» и «что с ним будет».
   */
  rewritten: boolean;
  /** Сколько таких путей в собранном сайте. Снято обходом `dist`. */
  count: number;
  /** Одна фраза: почему именно так. Разрешена строчная разметка. */
  why: string;
}

/** Вариант базы для переключателя демо. */
export interface BaseOption {
  /** Сама база, как её пишут в конфиге: `/` или `/repo/`. */
  value: string;
  label: string;
  /** Адрес, по которому сайт при этом живёт. */
  origin: string;
}

/** Что стало с одной строкой при выбранной базе. */
export interface PathVerdict {
  row: PathRow;
  /** Путь, который в этом случае окажется в файле. */
  emitted: string;
  /** Отдаст ли хостинг по нему файл. */
  ok: boolean;
  /** Короткое объяснение вердикта — для подписи в демо. */
  why: string;
}
