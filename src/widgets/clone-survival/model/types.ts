/**
 * Чем кончилось клонирование значения.
 *
 * Трёх исходов, а не двух: между «прошло» и «упало» лежит самый опасный случай — клон
 * получился, но это уже не то значение, которое отправляли. Ошибку видно сразу, потерю —
 * через неделю.
 */
export type CloneVerdict = 'ok' | 'lossy' | 'throw';

/** Что осталось от значения в клоне: вердикт и строка с тем, что реально проверено. */
export interface CloneOutcome {
  verdict: CloneVerdict;
  note: string;
}

export interface CloneCase {
  key: string;
  /** Короткое имя значения — заголовок строки. */
  label: string;
  /** Что именно отдаём `structuredClone`. */
  code: string;
  /** Значение создаётся заново на каждый прогон: клонирование бывает разрушительным. */
  make: () => unknown;
  /**
   * Что проверить у клона. Вызывается, только если клон получился; возвращает вердикт
   * и строку с результатами настоящих проверок, а не заранее написанный ответ.
   */
  inspect?: (clone: unknown) => CloneOutcome;
  /** Почему движок поступает именно так. */
  why: string;
  /** Ожидаемый исход — его сверяет `tests/unit/clone-survival.test.ts`. */
  expected: CloneVerdict;
  /** Значение существует только в браузере: в Node такой проверки не будет. */
  browserOnly?: boolean;
}
