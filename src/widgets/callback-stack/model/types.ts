/** Шаг разбора: что на стеке, что в консоли и жив ли сейчас ваш `try`. */
export interface StackStep {
  message: string;
  tone?: 'ok' | 'warn' | 'err';
  /** Подсвеченная строка листинга — индекс с нуля; −1 — ни одной (стек размотан). */
  line: number;
  /**
   * Фрагмент кода, который обязан стоять в строке `line`. Нужен только тесту: номер строки
   * задан отдельно от листинга и молча уезжает при его правке, а якорь это ловит.
   */
  anchor?: string;
  /** Кадры снизу вверх: последний — тот, что исполняется. */
  frames: string[];
  out: string[];
  /** Вердикт про `try/catch` в этот момент — главный индикатор демо. */
  guard: string;
}

/** Способ передать функцию: синхронный колбэк или асинхронный. */
export interface StackMode {
  key: string;
  label: string;
  code: string[];
  steps: StackStep[];
}
