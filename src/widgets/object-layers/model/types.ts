/**
 * Слой объектной модели — одна полоса карты в начале урока.
 *
 * Порядок в массиве — сверху вниз: первым идёт то, что есть на самом деле (`ground`), дальше
 * надстройки — в том порядке, в котором их разбирает тема (перевёрнуто 2026-09-30 по просьбе
 * автора курса: так карта читается вместе с темой). Слой `ground` рисуется чернилами.
 */
export interface ObjectLayer {
  /** «слой 4 · перехват» — номер и одно слово про назначение. */
  eyebrow: string;
  title: string;
  items: string[];
  /** Что из этого слоя есть в сквозном примере `dog` — строчная разметка. */
  note?: string;
  /** Где слой разобран: ссылки на разделы темы, строчная разметка. */
  where?: string;
  ground?: boolean;
}
