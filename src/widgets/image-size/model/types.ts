/** Одна полоса диаграммы размеров: снятое число и то, как его показать человеку. */
export interface SizeBar {
  /** Подпись слева — что именно взвешено. */
  label: string;
  /** Значение на оси, в единицах `unit` диаграммы. */
  value: number;
  /** Как значение показать человеку, с единицами: «196.1 МБ». */
  text: string;
  /** Пояснение под подписью: из чего это число складывается. Необязательно. */
  note?: string;
  tone?: 'ok' | 'warn' | 'err' | 'info' | 'neutral';
}
