/**
 * Точка расширения языка: символ и обычные операции, которые его вызывают.
 *
 * У части символов в данных перечислены операции, у части — пояснение роли; бывает и то
 * и другое. Обязательным сделано только имя: дописывать недостающее означало бы сочинять
 * за автора урока.
 */
export interface SymbolHook {
  symbol: string;
  /** Обычный код, который под капотом ищет этот символ. */
  calls?: string[];
  /** Чем символ управляет. Разрешена строчная разметка. */
  note?: string;
}
