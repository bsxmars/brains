import type { Program } from '@/shared/lib/promise-sim';

/** Пресет линейки: конструкция, её цена в тиках, объяснение и прогон по операциям спеки. */
export interface RulerPreset {
  /** Подпись на переключателе — она же конструкция. */
  label: string;
  /** Цена в тиках. Её же независимо считают движок (замер) и модель (лента). */
  n: number;
  /** Код примера. Печатает `<-- здесь` там, где результат становится виден. */
  code: string;
  /** Почему цена такая. */
  why: string;
  /**
   * Тот же пример, записанный операциями спеки: из него собирается лента микрозадач.
   * Цена, посчитанная моделью, сверяется с замером в `tests/unit/promise-sim.test.ts`.
   */
  program: Program;
}
