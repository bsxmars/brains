/**
 * Разбор одного выражения `a instanceof B` — по шагам настоящего алгоритма.
 *
 * Тезис раздела: `instanceof` не проверяет тип, он вызывает метод. Доказать это списком
 * из трёх пунктов нельзя — можно только показать три случая рядом: в одном метод унаследован
 * и честно обходит цепочку, во втором метод свой и цепочки нет вовсе, в третьем цепочка
 * на месте, а звено разъехалось.
 */

/** Три подопытных раздела. */
export type InstanceofCaseKey = 'chain' | 'hasInstance' | 'reassigned';

/**
 * Шаг алгоритма.
 *
 * `probe` — то, что у алгоритма сейчас в руках: очередное звено цепочки либо значение,
 * которое вернул метод. Строка собирается из настоящих объектов, а не пишется заранее.
 */
export interface InstanceofStep {
  /** Что произошло на шаге. Допускается строчная разметка — печатать через `Md`. */
  text: string;
  /** Индекс подсвечиваемой строки листинга; `-1` — ни одной. */
  line: number;
  /** Звено цепочки или значение в руках алгоритма. */
  probe: string;
  /** Совпало ли звено с `B.prototype`. `null` — шаг не про сравнение. */
  match: boolean | null;
  tone: 'info' | 'ok' | 'warn' | 'err';
}

/**
 * Итог одного настоящего прогона.
 *
 * ⚠️ `errorName` отдельно от `error` намеренно: имя ошибки нормативно, текст сообщения
 * у каждого движка свой. В тесте можно утверждать только имя.
 */
export interface InstanceofRun {
  key: InstanceofCaseKey;
  label: string;
  /** Исходник случая — тот же, что исполнился. */
  code: string[];
  /** Выражение, чей вердикт показан: `dog instanceof Animal`. */
  expression: string;
  /** Настоящий результат настоящего оператора. */
  verdict: boolean;
  /**
   * Вердикт «до» — только у случая с переприсвоенным `prototype`: там вся суть в том,
   * что один и тот же объект отвечает по-разному в разные моменты.
   */
  before: boolean | null;
  steps: InstanceofStep[];
  /**
   * Запускался ли обход цепочки вообще.
   *
   * Это и есть доказательство тезиса: у случая с собственным `Symbol.hasInstance`
   * здесь `false` — сравнивать было нечего, просто вызвали метод.
   */
  walked: boolean;
  /** Есть ли у конструктора **собственный** `Symbol.hasInstance`. */
  ownHasInstance: boolean;
  /** Виден ли `Symbol.hasInstance` вообще (у обычной функции — унаследованный). */
  seesHasInstance: boolean;
  /** Имя ошибки, если случай её ловит. Пустая строка — ошибки не было. */
  errorName: string;
  /** Дословный текст от движка — для показа, не для утверждений. */
  error: string;
  /** Короткий вывод под демо. */
  result: string;
  tone: 'ok' | 'warn' | 'err';
}
