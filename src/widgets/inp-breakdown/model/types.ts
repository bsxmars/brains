/**
 * Один расклад одного и того же клика: сколько ждал отклик и из чего это время сложилось.
 *
 * Числа здесь — **замер**, а не модель: Chromium 153, обработчик занимает поток ровно на 400 мс,
 * нарезка идёт кусками по 8 мс. Поэтому у расклада нет поля «во сколько раз лучше»: во сколько
 * раз — видно на оси.
 */
export interface InpMode {
  key: string;
  label: string;
  /** Код, который даёт именно такой расклад. */
  code: string;
  /** Ждали освобождения потока, мс. */
  inputDelay: number;
  /** Работали обработчики, мс. */
  processing: number;
  /** Собирали кадр после обработчика, мс. */
  presentation: number;
  /** Длительность взаимодействия целиком, мс. Кратна 8 — так огрубляет Event Timing. */
  total: number;
  /** Самая длинная задача в замере, мс; `null` — длинных задач не было. */
  longTask: number | null;
  /** Вывод под графиком. Разрешена строчная разметка. */
  note: string;
  tone: 'ok' | 'warn' | 'err';
}
