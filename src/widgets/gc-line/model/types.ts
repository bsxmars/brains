/**
 * Кусок строки `--trace-gc`.
 *
 * Строка хранится списком кусков, а не одной строкой с разметкой: куски кликаются, и каждый
 * обязан уметь рассказать о себе. Куски без `name` — это пунктуация вроде стрелки: они видны
 * в строке, но ничего не объясняют и не кликаются.
 */
export interface GcToken {
  /** Текст ровно как в логе. */
  t: string;
  /** Имя поля; без него кусок не кликается. */
  name?: string;
  /** Что это значит. */
  what?: string;
  /** Зачем смотреть при разборе утечки. */
  use?: string;
  /** Главное поле строки: помечено и в строке, и в разборе. */
  star?: boolean;
  /** Поле, которого в оригинале урока не было: появилось в более новых сборках V8. */
  fresh?: boolean;
}
