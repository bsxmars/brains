/**
 * Типы «микрозондa»: что именно замеряется в браузере читателя.
 *
 * Слайс существует ради одного: в теме «Цикл событий» две таблицы — «кто микрозадача,
 * а кто нет» и «`queueMicrotask` против `.then`» — были набраны руками. Всё, что в них
 * сказано, кроме числа создаваемых объектов, наблюдаемо прямо на странице, а значит
 * набирать это литералом нельзя (`AGENTS.md`, «Таблицу о поведении языка не набирают —
 * её вычисляют»).
 */

/** Тон строки результата. `dim` — «проверять нечего»: механизма в этой среде нет. */
export type Tone = 'ok' | 'warn' | 'err' | 'dim';

/** Сценарий переключателя. */
export type ProbeKey = 'who' | 'order' | 'error' | 'starvation';

/**
 * Куда механизм попал относительно двух маркеров-микрозадач.
 *
 * Вердикта три, а не два, и третий — не придирка. Маркер ставится дважды: один
 * `queueMicrotask` **до** постановки механизма, другой **после**. Тогда порядок вывода
 * различает три разных устройства, которые булева колонка «микрозадача: да/нет» сливает
 * в одно:
 *
 * - `micro` — механизм выполнился **между** маркерами: та же очередь, строгий FIFO;
 * - `ahead` — раньше первого маркера, хотя поставлен позже него: это **другая** очередь,
 *   с приоритетом выше микрозадач (ровно так устроен `process.nextTick` в Node);
 * - `after` — после обоих: очередь микрозадач успела опустеть, значит это не микрозадача.
 *
 * Плюс два честных «не знаю»: `absent` — механизма в этой среде нет, `unknown` — механизм
 * есть, но за отведённое время не сработал (так выглядит `requestAnimationFrame` в скрытой
 * вкладке: кадров нет, и коллбэка не будет, сколько ни жди).
 */
export type QueueVerdict = 'micro' | 'ahead' | 'after' | 'absent' | 'unknown';

/** Одна строка таблицы «кто микрозадача» — целиком из прогона, кроме `claimed`. */
export interface MechanismRow {
  key: string;
  /** Короткое имя для фишки в консоли. Без обратных кавычек: печатается как есть. */
  label: string;
  /** Имя механизма для заголовка строки. Со строчной разметкой — выводить через `Md`. */
  title: string;
  /** Как механизм ставится — тот же код, что исполняет `arm`. */
  code: string;
  /**
   * Что об этом механизме утверждает таблица урока (`MICRO_ROWS` в `data.ts`).
   *
   * Единственное поле строки, которое не измерено, а перенесено, — и лежит оно здесь
   * затем, чтобы расхождение было видно на экране, а не осталось между строк. Юнит-тест
   * сверяет `verdict` с `claimed` и краснеет, если движок передумал.
   */
  claimed: QueueVerdict;
  /** Что вышло **в этой среде**. */
  verdict: QueueVerdict;
  /**
   * Есть ли что сравнивать: механизм существует и сработал.
   *
   * Отдельным полем, потому что «не сходится» и «нечего сверять» — разные вещи, а один
   * булев `agrees` их слил бы. У строки с `absent` (в браузере нет `process.nextTick`,
   * в Node нет `MutationObserver`) `agrees` равен `false` — и это не значит, что урок неправ.
   * Проверять в тесте нужно строки с `comparable`.
   */
  comparable: boolean;
  /** Сошлось ли измеренное с утверждением урока. Всегда `false`, если сверять не с чем. */
  agrees: boolean;
  /** Собранный порядок: маркеры и сам механизм, в том порядке, в каком их позвали. */
  order: string[];
  /** Сколько ждали механизм, мс. Для не сработавших — всё отведённое время. */
  waitedMs: number;
  /** Что это значит — собирается по вердикту, а не написано заранее. */
  note: string;
  /** Почему движок поступает именно так. Это объяснение, и оно перенесено, а не измерено. */
  why: string;
  tone: Tone;
}

export interface WhoRun {
  rows: MechanismRow[];
  /**
   * Был ли у прогона **отрисованный** узел для `ResizeObserver` и `IntersectionObserver`.
   *
   * ⚠️ Эти двое на отсоединённом узле честно проверить нельзя: `ResizeObserver` пропускает
   * элементы без CSS-бокса, а у `IntersectionObserver` первая доставка зависит от реализации.
   * Поэтому прогон вставляет в документ настоящий, участвующий в раскладке узел 8×8 и убирает
   * его за собой. Нет `document` (юнит-тест в Node) — обе строки честно помечаются `absent`,
   * а не додумываются.
   */
  rendered: boolean;
}

/** Порядок между `queueMicrotask` и `.then`: FIFO одной очереди или два потока? */
export interface OrderRun {
  /** Микрозадачи в порядке **постановки** — как написано в коде. */
  scheduled: string[];
  /** Всё, что выполнилось, в порядке **выполнения**. Включая задачу-таймер. */
  executed: string[];
  /** Совпал ли порядок выполнения микрозадач с порядком постановки. */
  fifo: boolean;
  /** Ушла ли задача в конец, хотя поставлена первой. */
  taskLast: boolean;
  /** Успела ли микрозадача, поставленная **изнутри** микрозадачи, в тот же слив. */
  nestedInSameDrain: boolean;
  note: string;
  tone: Tone;
}

/** Канал, по которому ушло исключение. `none` — не поймали ни одного. */
export type ErrorChannel = 'error' | 'unhandledrejection' | 'both' | 'none';

/** Одна половина опыта с ошибкой: бросок в `queueMicrotask` и бросок в `.then`. */
export interface ErrorRow {
  key: 'queueMicrotask' | 'then';
  label: string;
  code: string[];
  /** Что утверждает `QM_ROWS`. Сверяется с `channel`. */
  claimed: ErrorChannel;
  /** Какой слушатель сработал по-настоящему. */
  channel: ErrorChannel;
  agrees: boolean;
  /** Имя долетевшей ошибки. Проверено по ссылке: это тот же объект, что бросили. */
  errorName: string;
  /** Текст — для показа. Утверждать его нельзя: у каждого движка свой. */
  errorText: string;
  /** Сколько ждали события, мс. */
  waitedMs: number;
  note: string;
  tone: Tone;
}

export interface ErrorRun {
  /**
   * Есть ли где ловить. Оба канала — события **окна**, и в Node их нет вовсе:
   * там бросок из микрозадачи уронил бы процесс теста, а не пришёл событием.
   */
  supported: boolean;
  rows: ErrorRow[];
  note: string;
}

/** Голодание микрозадачами: цепочка, которая не отпускает поток. */
export interface StarvationRun {
  /** Длина цепочки — каждая микрозадача ставит следующую. */
  steps: number;
  /** Сколько миллисекунд поток был занят подряд. */
  busyMs: number;
  /** Насколько опоздал `setTimeout(…, 0)`, поставленный **до** цепочки. */
  timerDelayMs: number;
  /** Дождался ли таймер конца цепочки. Ради этого «да» демо и сделано. */
  timerAfterChain: boolean;
  /** Задержка первого кадра, мс. `null` — кадра не было (скрытая вкладка или нет `rAF`). */
  frameDelayMs: number | null;
  /** Пришёл ли кадр после цепочки. `null` — кадра не было. */
  frameAfterChain: boolean | null;
  /**
   * Результат работы, которую делала каждая микрозадача.
   *
   * Нужен затем, чтобы работу нельзя было выбросить: без чтения результата движок вправе
   * вычислить цикл в ничто, и «поток был занят» превратилось бы в замер пустоты.
   */
  checksum: number;
  log: string[];
  note: string;
  tone: Tone;
}

/** Описание сценария: подпись переключателя, текст и тот код, который исполняется. */
export interface ProbeScenario {
  key: ProbeKey;
  /** Подпись в переключателе. Без строчной разметки: Aura печатает её как есть. */
  label: string;
  title: string;
  lead: string;
  /** Строки кода — те же, что исполняет соответствующая функция в `run.ts`. */
  code: string[];
  /** Честная оговорка: что именно доказывает этот прогон, а что остаётся за ним. */
  caveat: string;
}
