/**
 * Что расходится между сервером и браузером в демо «сервер отдал → гидратация».
 *
 * `match` — ничего; `text` — время сборки (на сервере одно, в браузере другое, как у
 * `new Date()`); `attr` — класс темы (сервер не знает, что у читателя тёмная тема);
 * `extension` — расширение браузера вставило свой узел в разметку до гидратации.
 */
export type Variant = 'match' | 'text' | 'attr' | 'extension';

/** Пропы сквозного примера `Order`: время сборки заказа и класс темы. */
export interface OrderProps {
  stamp: string;
  theme: string;
  /** Только у React: обернуть абзац со временем в `<Suspense>`. */
  boundary?: boolean;
}

export interface VariantSpec {
  /** С какими пропами рендерит сервер. */
  server: OrderProps;
  /** С какими пропами гидратирует браузер. */
  client: OrderProps;
  /** Вставить ли «узел расширения» в серверную разметку до гидратации. */
  inject: boolean;
}

/**
 * Судьба узла, который лежал в контейнере до гидратации.
 *
 * `kept` — тот же объект узла остался в документе и не изменился; `patched` — тот же объект,
 * но текст в нём переписан; `dropped` — узла в документе больше нет (его выбросили,
 * а на его месте, возможно, создан новый).
 */
export type Fate = 'kept' | 'patched' | 'dropped';

export interface NodeRow {
  /** `<section.day>`, `"Заказ №42"`, `<!--$-->` — как узел выглядел до гидратации. */
  label: string;
  depth: number;
  fate: Fate;
  /** Текст узла после гидратации, если он изменился. */
  now?: string;
}

/** Узел, которого до гидратации не было: его создал фреймворк. */
export interface CreatedRow {
  label: string;
  depth: number;
}

export interface HydrationRun {
  /** Каждый узел серверной разметки по порядку обхода — и что с ним стало. */
  nodes: NodeRow[];
  /** Новые узлы в порядке обхода итогового дерева. */
  created: CreatedRow[];
  /**
   * Что фреймворк сообщил: у React — `onRecoverableError`, у Vue — `console.error`
   * и `console.warn` за время монтирования. Текст как есть, без перевода.
   */
  messages: string[];
  /** Итоговая разметка контейнера. */
  html: string;
  /**
   * Совпадает ли итог с тем, что клиент нарисовал бы с нуля (без комментариев-маркеров).
   * `false` — в документе остался серверный вариант, который никто не исправил.
   */
  matchesClient: boolean;
  /** Что клиент нарисовал бы с нуля — для сравнения, когда `matchesClient` ложно. */
  clientHtml: string;
}

/** Живой корень после гидратации: демо держит его, чтобы кнопка работала, и снимает перед новым прогоном. */
export interface Hydrated {
  run: HydrationRun;
  unmount: () => void;
}
