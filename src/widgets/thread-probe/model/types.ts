/**
 * Что прибор возвращает наружу.
 *
 * Два разных вопроса и два разных типа: «во что обходится тяжёлая работа там и там»
 * (`ThreadRun`) и «что вообще видно про эту вкладку» (`EnvRow`). Оба наполняются только
 * ответами платформы: в модуле нет ни одной величины, которая не была бы снята в момент нажатия.
 */

/** Где считалась одинаковая работа. */
export type ThreadMode = 'main' | 'worker';

export type ProbeTone = 'ok' | 'warn' | 'err' | 'dim';

/** Один прогон: сколько callbacks requestAnimationFrame вызвано, пока шла работа. */
export interface ThreadRun {
  mode: ThreadMode;
  /** Удался ли замер. Ложь — это не ошибка страницы, а честное «в этой среде нечем». */
  ok: boolean;
  /** Почему не удалось или чем результат испорчен. Разрешена строчная разметка. */
  note: string;
  /** Сколько работы заказано, мс. */
  workMs: number;
  /** Сколько её на самом деле шло, мс. */
  tookMs: number;
  /** Окно наблюдения: от первого callback rAF до последнего, мс. */
  spanMs: number;
  /** Сколько callbacks rAF зарегистрировано за это окно. */
  frames: number;
  /** Callbacks rAF в секунду в окне. */
  fps: number;
  /** Самая длинная пауза между соседними callbacks rAF, мс; не счётчик предъявленных экраном кадров. */
  longestGapMs: number;
  /** Сумма, которую вернула работа: доказательство, что цикл не выброшен. */
  checksum: number;
}

/** Строка опроса вкладки: что спросили, что ответили, что это значит. */
export interface EnvRow {
  key: string;
  label: string;
  /** Ответ платформы — как есть, без пересказа. */
  value: string;
  tone: ProbeTone;
  /** Что из этого следует. Разрешена строчная разметка. */
  note: string;
}
