/**
 * Работа, одинаковая для обоих потоков, — и доказательство того, что она одинаковая.
 *
 * Сравнивать главный поток с воркером можно только если считают они **один и тот же код**.
 * Пересказать функцию во вторую строку для `blob:` — значит завести две правды, которые
 * разъедутся на первой же правке. Поэтому источник воркера собирается из `burn.toString()`:
 * в воркер уезжает буквально эта функция, а не её двойник.
 *
 * ⚠️ `burn` не имеет права смотреть наружу себя. Замыкание не переживает `toString()`: имя
 * из модуля стало бы в воркере `ReferenceError`, и «воркер не ответил» списали бы на что угодно,
 * кроме настоящей причины.
 *
 * ⚠️ Работа ограничена **временем, а не числом оборотов.** Иначе замер сравнивал бы не потоки,
 * а то, насколько по-разному они успели прогреться: одинаковые 700 мс счёта — величина,
 * не зависящая от железа, а одинаковый миллион оборотов — зависящая целиком.
 */
export function burn(ms: number): number {
  const started = performance.now();
  let acc = 0;
  let i = 0;

  // Время спрашивается не на каждом обороте: `performance.now()` сам по себе не бесплатен,
  // и проверка в теле внутреннего цикла мерила бы часы, а не работу.
  while (performance.now() - started < ms) {
    for (let k = 0; k < 20_000; k++) {
      acc += Math.sqrt(i + k) % 7;
      i += 1;
    }
  }
  return Math.round(acc);
}

/**
 * Воркер поднимается из строки через `blob:` — как песочница курса
 * (`features/run-snippet/lib/worker.ts`) и как соседний замер переноса
 * (`widgets/transfer-cost`). Так он не зависит от того, куда бандлер разложит ассеты
 * статической сборки, и работает с файловой раздачи так же, как с сервера.
 *
 * Пустой заказ (`workMs === 0`) — это рукопожатие: агент уже создан, код разобран, первый
 * обмен сообщениями прошёл. Без него в замер попал бы старт воркера, а он к разговору
 * о потоках отношения не имеет.
 */
export const WORKER_SOURCE = `
const burn = ${burn.toString()};

self.onmessage = (event) => {
  const workMs = event.data.workMs;
  if (!workMs) {
    self.postMessage({ ready: true, checksum: 0, tookMs: 0 });
    return;
  }
  const started = performance.now();
  const checksum = burn(workMs);
  self.postMessage({ ready: false, checksum, tookMs: performance.now() - started });
};
`;

/** Не ответил за это время — считаем повисшим и снимаем. Работа длится сотни миллисекунд. */
export const WORKER_TIMEOUT_MS = 15_000;
