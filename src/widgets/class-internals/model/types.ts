/**
 * Шаг инициализации экземпляра производного класса.
 *
 * Главный сюрприз, ради которого демо и сделано: поля наследника создаются **после** возврата
 * из `super()`. Всё, что родительский конструктор успел вызвать, их не видит — отсюда
 * «работало, пока не добавили поле».
 */
export interface InitStep {
  msg: string;
  /** В каком из двух листингов стоит курсор. */
  pane: 'base' | 'child';
  /** Индекс подсвеченной строки листинга; `-1` — ни одной. */
  line: number;
  /** Поля объекта на этот момент; `null` — объекта ещё физически нет. */
  obj: string[] | null;
  out: string[];
  tone?: 'warn' | 'err';
}

/**
 * Проба приватного поля: чем его пытались достать и что получилось.
 *
 * `ok: true` — единственный способ, который работает (`#x in obj`). Все остальные строки
 * отвечают «ничего нет», и это не совпадение: приватное поле живёт в слоте
 * `[[PrivateElements]]`, а не среди свойств, и ни одна операция над ключами его не видит.
 */
export interface PrivateProbe {
  k: string;
  v: string;
  ok: boolean;
}
