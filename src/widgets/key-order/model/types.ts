/** Три группы, на которые спецификация делит собственные ключи. */
export type KeyGroup = 'index' | 'string' | 'symbol';

/** Ключ в том порядке, в каком его вернул движок. */
export interface OrderedKey {
  /** Ключ как его набрали: по нему ищется позиция ввода и считается «не попало в объект». */
  key: string;
  /**
   * Как он печатается: строка в кавычках, символ — `Symbol(s)`. Словарь тот же, что
   * у фишек порядка в уроке, — чтобы демо и текст называли ключи одинаково.
   */
  label: string;
  group: KeyGroup;
  /** Номер в списке читателя, с единицы: по нему видно, насколько порядок разошёлся с вводом. */
  typedAt: number;
}

/** Итог одной сборки объекта. */
export interface OrderRun {
  /** Ключи в том порядке, в каком их набрал читатель. */
  typed: string[];
  /** Они же в порядке `Reflect.ownKeys` — настоящем, а не описанном. */
  keys: OrderedKey[];
  json: string;
  /**
   * Набранные ключи, которых в объекте не оказалось. На практике это `__proto__`: при
   * присваивании он не ключ, а сеттер прототипа, и свойства с таким именем не появляется.
   *
   * Повтор сюда не попадает, и это проверено запуском: второе присваивание свойство
   * не создаёт, но и не убирает — перезаписывается значение, позиция остаётся от первого раза.
   */
  missing: string[];
}

/** Кнопка-заготовка: набор ключей с ловушкой внутри. */
export interface KeyPreset {
  label: string;
  keys: string;
  note: string;
}
