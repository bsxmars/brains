/**
 * «Что дешевле двигать»: одно и то же движение и стадии кадра, которые оно запускает.
 *
 * Ключ демо — не «transform быстрее left», а **кто считает промежуточные значения**
 * и на каком потоке. Поэтому у случая есть и стадии, и отдельное поле `driver`.
 */
export type StageState =
  /** Стадия выполняется на главном потоке — каждый кадр. */
  | 'main'
  /** Стадия пропускается целиком. */
  | 'skip'
  /** Стадия выполняется, но не на главном потоке. */
  | 'compositor';

export interface MoveCase {
  key: string;
  label: string;
  code: string;
  stages: Record<'style' | 'layout' | 'paint' | 'composite', StageState>;
  /** Кто вычисляет значение свойства на каждом кадре. Разрешена строчная разметка. */
  driver: string;
  /** Вывод. Разрешена строчная разметка. */
  verdict: string;
  tone: 'ok' | 'warn' | 'err';
}
