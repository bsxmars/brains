/**
 * Слот объекта `Context` в куче V8.
 *
 * Порядок важен и в оригинале урока был перепутан: по исходникам V8 (`contexts.h`)
 * слот 0 — это `ScopeInfo`, слот 1 — предыдущий контекст, и только дальше идут переменные.
 */
export interface ContextSlot {
  /** Номер слота. */
  n: string;
  k: string;
  v: string;
  /** Заголовок контекста или слот захваченной переменной. */
  kind: 'header' | 'var';
  /** Подсветить как «то самое тяжёлое, что держится заодно». */
  hot?: boolean;
}
