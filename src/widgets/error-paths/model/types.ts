/**
 * Случай, в котором ошибка из асинхронного колбэка теряется.
 *
 * Поля те же, что лежали в данных урока: номер, название, код, куда ушла ошибка и как надо.
 * Виджет не добавляет содержания — он придерживает ответ, пока читатель не предположит свой.
 */
export interface ErrorPath {
  n: string;
  /** Название случая: подпись на переключателе. */
  t: string;
  /** Что написано в коде. */
  code: string;
  /**
   * Вопрос к листингу. Свой у каждого случая: у третьего файл ни при чём — ошибка
   * рождается из типа аргумента, и общий вопрос «если файл не прочитается» к нему не подходит.
   */
  q: string;
  /** Куда на самом деле уходит ошибка. Разрешена строчная разметка. */
  why: string;
  /** Как надо. Разрешена строчная разметка. */
  fix: string;
}
