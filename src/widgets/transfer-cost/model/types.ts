/** Каким способом буфер уходил в воркер: обычной копией или с передачей владения. */
export type SendMode = 'copy' | 'transfer';

/**
 * Один замер: что отправили, сколько это стоило и что осталось у отправителя.
 *
 * Два времени, а не одно, — в этом весь смысл замера. `blocked` — сколько главный поток
 * простоял внутри самого вызова `postMessage`, то есть цена сериализации; `trip` — сколько
 * прошло до ответа воркера, то есть та же сериализация плюс десериализация на той стороне
 * плюс два прохода через очереди задач. Сравнивать копию с переносом по одному только `trip`
 * нельзя: у копии половина цены списывается с получателя, и в `blocked` её не видно.
 */
export interface TransferRun {
  /** Порядковый номер — чтобы у строки таблицы был устойчивый ключ. */
  id: number;
  mb: number;
  mode: SendMode;
  /** Время внутри `postMessage`, мс. */
  blocked: number;
  /** Время до ответа воркера, мс. */
  trip: number;
  /** `byteLength` исходного буфера после отправки: у переноса он обнуляется. */
  left: number;
  /** Что вернуло чтение `view[0]` у отправителя после отправки. */
  probe: string;
  /** Сколько байт увидел воркер — доказательство, что данные доехали. */
  got: number;
}
