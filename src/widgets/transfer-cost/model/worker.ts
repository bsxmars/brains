/**
 * Воркер замера — настоящий, а не имитация.
 *
 * Собирается из строки через `blob:`, как и воркер песочницы (`features/run-snippet/lib/worker.ts`):
 * так он не зависит от того, куда бандлер разложит ассеты статической сборки.
 *
 * Воркер трогает первый байт полученного вида и отправляет его обратно. Это не украшение:
 * без обращения к данным нечем доказать, что байты действительно доехали, — а в случае
 * переноса именно это и есть предмет разговора.
 */
export const WORKER_SOURCE = `
self.onmessage = (event) => {
  const view = event.data.view;
  self.postMessage({
    bytes: view.byteLength,
    first: view.byteLength ? view[0] : -1,
    mode: event.data.mode,
  });
};
`;

/**
 * Сколько ждать ответа, прежде чем считать воркер повисшим.
 *
 * Секунда с лишним на порядок больше самого дорогого честного замера (64 МБ копией — это
 * десятки миллисекунд). Не ответил — значит, случилось что-то, чего мы не предусмотрели,
 * и воркер снимается `terminate()`: демо обязано остаться живым, даже когда замер не удался.
 */
export const TIMEOUT_MS = 3000;
