/**
 * Расклад демонстрации сдвига: зарезервировано ли место под то, что приедет позже.
 *
 * Больше данных демо не нужно — числа оно не берёт из файла, а **считает по формуле метрики**
 * из настоящей геометрии своих же элементов. Захардкоженный «сдвиг 0.35» показывал бы, что
 * автор умеет писать числа, а не что формула работает.
 */
export interface ClsCase {
  key: string;
  label: string;
  /** Место под картинку занято заранее — `aspect-ratio` или атрибуты `width`/`height`. */
  reserved: boolean;
  /** Вывод под демо. Разрешена строчная разметка. */
  note: string;
  tone: 'ok' | 'err';
}

/** Один зафиксированный сдвиг: как его посчитала формула метрики. */
export interface ShiftRecord {
  /** Момент по часам страницы, мс — по нему сдвиги группируются в окна сессии. */
  at: number;
  /** Что именно случилось. */
  label: string;
  impact: number;
  distance: number;
  value: number;
}
