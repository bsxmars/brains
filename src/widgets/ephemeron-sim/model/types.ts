/**
 * Расклад для симулятора эфемерона: что на что ссылается и кто держит снаружи.
 *
 * Судьбу записи виджет **считает сам** по правилу спецификации, а не берёт из данных:
 * правило и есть то, чему учит демо. Из данных приходят только подписи и разбор.
 */
export interface EphemeronScenario {
  key: string;
  label: string;
  /** Значение ссылается на собственный ключ: `wm.set(el, { el, size })`. */
  valueToKey: boolean;
  /** Кто достижим снаружи записи: никто, ключ или значение. */
  holder: 'none' | 'key' | 'value';
  /** Подпись внешнего держателя — «документ», «ваш массив», «никто». */
  holderLabel: string;
  code: string;
  /** Разбор: почему получилось именно так. */
  why: string;
}
