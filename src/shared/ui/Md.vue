<script setup lang="ts">
/**
 * Тот же `Md`, что и в `.astro`, — для островов: строка из данных с её строчной разметкой.
 *
 * Здесь единственное место в проекте, где разрешён `v-html`, и вот почему это безопасно:
 * `inlineMd` **сначала экранирует HTML** и только потом расставляет свои два тега — `<code>`
 * и `<b>`. Строка из `data.ts`, принесшая `<script>` или атрибут с обработчиком, доедет
 * до страницы текстом. Правило `vue/no-v-html` остаётся включённым для всего остального
 * кода: исключение с обоснованием лучше, чем выключенное правило.
 *
 * Своего вида у компонента нет намеренно — размер и цвет задаёт окружение.
 */
import { inlineMd } from '@/shared/lib/format';

withDefaults(defineProps<{ text: string; as?: 'div' | 'span' | 'p' }>(), { as: 'div' });

/**
 * Атрибуты (`class`, `aria-*`) передаются явно, а не наследованием. Комментарии в шаблоне ниже
 * в режиме разработки остаются узлами, корень становится фрагментом — и Vue молча не отдаёт
 * `class` никому: в `npm run dev` подписи виджетов теряли свои стили, а в сборке, где
 * комментарии вырезаны, всё было на месте. Нашлось при написании темы «Формы во фреймворках».
 */
defineOptions({ inheritAttrs: false });
</script>

<template>
  <!--
    ⚠️ Три явных тега, а не `<component :is="as" v-html>`: серверный рендер Vue на динамическом
    компоненте `v-html` теряет — в разметку уходил пустой `<span>`, и текст появлялся только
    после гидратации. Сорвалась гидратация — шаги демо стоят пустыми (поймано на `lookup-chain`).
  -->
  <!-- eslint-disable vue/no-v-html -- inlineMd сначала экранирует HTML и только потом ставит свои два тега -->
  <p v-if="as === 'p'" v-bind="$attrs" v-html="inlineMd(text)" />
  <span v-else-if="as === 'span'" v-bind="$attrs" v-html="inlineMd(text)" />
  <div v-else v-bind="$attrs" v-html="inlineMd(text)" />
  <!-- eslint-enable vue/no-v-html -->
</template>
