/**
 * Направления сайта.
 *
 * Сначала это была одна коллекция уроков, один адрес `/js/` и название, вшитое в страницу.
 * Когда тем стало больше одной, понадобилась сущность — и называется она **направлением**,
 * а не курсом: курс проходят от начала до конца и заканчивают, а здесь читатель приходит
 * за темой («почему React перерисовывает лишнее») и уходит, прочитав один разбор. Уроки
 * внутри направления связаны порядком, но не обязательствами.
 *
 * `collection` — имя коллекции контента (см. `src/content.config.ts`); `base` — адрес списка
 * уроков. У каждого направления свой список: главная перестала быть списком «Внутренностей JS»
 * в тот момент, когда направлений стало два, — иначе первое из них выглядело бы всем сайтом,
 * а остальные приложением к нему.
 */
import { withBase } from '@/shared/lib/url';

export type DirectionId = 'js' | 'render' | 'frameworks' | 'platform' | 'tooling' | 'delivery' | 'algorithms' | 'data' | 'patterns';

export interface Direction {
  id: DirectionId;
  /** Имя коллекции контента. */
  collection: 'lessons' | 'render' | 'frameworks' | 'platform' | 'tooling' | 'delivery' | 'algorithms' | 'data' | 'patterns';
  /** Название направления: заголовок списка и вкладки. */
  title: string;
  /** Надзаголовок шапки урока, если урок не задал свой. */
  kicker: string;
  /** Адрес списка уроков. */
  base: string;
  /** Одна фраза о направлении — для карточки и описания страницы. */
  lead: string;
  /**
   * Вопрос, на который направление отвечает.
   *
   * Стоит на карточке над названием и делает за читателя ту работу, которую иначе делает он сам:
   * «мне это сейчас нужно или нет». Название темы на этот вопрос не отвечает — «Рендеринг»
   * одинаково похож и на то, что человек ищет, и на то, что ему не нужно.
   */
  question: string;
}

